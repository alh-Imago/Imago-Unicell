"""tests/vm/test_latex_division_core_v1.py -- ledger #1074: the LaTeX front end with division="core": a general division or remainder is ONE `udiv` / `urem` cell of the
division core (about 6 cells, against about 23,000 unrolled), any number per formula. Every formula is compiled and the built-in check compares the generated operations AND the
compiled design (run in the standard VM) with the Python oracle on corner and random values (x/0 = all ones, x mod 0 = x included)."""
import os
import subprocess
import sys

import pytest

NANO = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "nano")
sys.path.insert(0, NANO)

import latex_frontend_v1 as L  # noqa: E402

FORMULAS = [
    "a / b",
    "a \\bmod b",
    "\\frac{a + b}{c}",
    "100 / b",                      # a literal dividend
    "a / 3",                        # a literal divisor that is not a power of two
    "a \\bmod 10",
    "(a / b) / c",                  # a quotient divided again
    "a / b + c / d",                # two different divisions: refused when unrolled
    "a / b + b / a",                # the same operands in the other order are a DIFFERENT division (not commutative)
    "a / b + a \\bmod b",           # a quotient and a remainder of the same pair
    "(a + b) \\bmod (c + 1)",
    "a \\bmod b + b \\bmod a",      # the remainder is not commutative either
    "(a \\bmod b) \\bmod c",
    "(a * c) \\bmod (b + d)",
    "(a + b) \\bmod (c * d + 1)",
]


def divcells(r):
    return [x for x in r.result.records if x.core == "div"]


@pytest.mark.parametrize("src", FORMULAS)
def test_formula_core_division_checks_out(src):
    r = L.compile_latex(src, division="core")
    assert r.ir_checked > 10 and r.checked == r.ir_checked, (r.ir_checked, r.checked, r.hw_skipped)
    assert divcells(r), "a general division must be a div cell"
    assert r.cells < 150, r.cells                                       # the unrolled form is about 23,000 per division


def test_one_division_is_a_handful_of_cells():
    assert L.compile_latex("a / b", division="core").cells <= 10


def test_a_power_of_two_is_still_a_shift_not_a_division_cell():
    r = L.compile_latex("a / 8 + a \\bmod 8", division="core")
    assert not divcells(r)
    assert r.checked > 0


def test_two_divisions_are_refused_unrolled_but_fine_as_core():
    with pytest.raises(L.LatexError):
        L.to_llvm(L.parse_latex("a / b + c / d")[1])                    # the default is unchanged
    ir, _ = L.to_llvm(L.parse_latex("a / b + c / d")[1], division="core")
    assert ir.count("udiv") == 2


def test_the_default_is_still_unrolled():
    ir, _ = L.to_llvm(L.parse_latex("a / b")[1])
    assert "udiv" not in ir and len(ir.splitlines()) > 300


def test_division_option_is_validated():
    with pytest.raises(L.LatexError):
        L.to_llvm(L.parse_latex("a / b")[1], division="fast")


def test_streaming_through_the_step_simulator_agrees():
    r = L.compile_latex("(a + b) / c + a \\bmod c", division="core")
    vecs = [{"a": 100, "b": 20, "c": 7}, {"a": 5, "b": 1, "c": 0}, {"a": 4000000000, "b": 5, "c": 13}]
    assert r.stream_step(vecs) == [r.reference(v) for v in vecs]


def test_cli_division_core():
    out = subprocess.run([sys.executable, os.path.join(NANO, "latex_cli_v1.py"), "(a + b) / c + a \\bmod c", "--division", "core",
                          "--set", "a=100", "--set", "b=20", "--set", "c=7"], capture_output=True, text=True, timeout=250)
    assert out.returncode == 0, out.stderr
    assert "result: 19" in out.stdout and "Python says 19" in out.stdout


# ---- the compiled design as REAL flex RTL (generated by the assembler, run in iverilog) ----
import json
import re
import shutil
import tempfile

import flex_rtl_harness_v1 as _h  # noqa: E402  (tests/vm is on the path when pytest collects this file)

M32 = 0xFFFFFFFF
_VECS = [{"a": 100, "b": 7, "c": 3}, {"a": 5, "b": 0, "c": 0}, {"a": M32, "b": 3, "c": 13}, {"a": 0, "b": 4, "c": 1}, {"a": 1000, "b": 1000, "c": 7},
         {"a": 7, "b": 100, "c": 9}, {"a": 4000000000, "b": 5, "c": 2}, {"a": 123456789, "b": 987, "c": 65537}]


@pytest.mark.parametrize("src", ["a / b", "a \\bmod b", "(a + b) / c + a \\bmod c", "a / b + b / a"])
def test_the_compiled_design_as_generated_flex_rtl_agrees_with_the_formula(src):
    assert shutil.which("iverilog") and shutil.which("vvp"), "iverilog is REQUIRED (this test must not skip silently)"
    r = L.compile_latex(src, division="core")
    vecs = [{k: v for k, v in vec.items() if k in r.args} for vec in _VECS]
    tmp = tempfile.mkdtemp(prefix="latexdiv_")
    try:
        d, res = _h.build(tmp, "lx", r.result.records, 32)
        assert res.returncode == 0, (res.stderr or res.stdout)[:500]
        top = json.load(open(os.path.join(d, "ASSEMBLY.json")))["top"]
        text = open(os.path.join(d, top + ".v")).read()
        assert "div_cell_v4sa" in text
        cmap = L._input_cells(r)                                    # input cell id -> argument name (one input cell per USE of an argument)
        ins = sorted(set(re.findall(r"\bin_(\w+)_data", text)))
        streams = {}
        for name in ins:
            cid = [c for c in cmap if c.replace(".", "_") == name]
            assert len(cid) == 1, (name, list(cmap))
            streams[name] = [v[cmap[cid[0]]] & M32 for v in vecs]
        _, got = _h.run_level(d, streams, "plain", 3, settle=600, cycles=60000, width=32)
        (out,) = got.values()
        assert out == [r.reference(v) for v in vecs], (src, out, [r.reference(v) for v in vecs])
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
