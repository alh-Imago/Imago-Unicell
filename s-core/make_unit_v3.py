#!/usr/bin/env python3
"""make_unit_v3.py L - writes uc_unitr<W>.v (W = 2**L lanes): the pipelined unit uc_unitp<W> (make_unit_v2.py) WITH ITS OWN WORD-RAM INTERFACE (ledger #1369, plan of #1365).
The RAMs are the pool's: registers and data as whole 32-bit words.  This wrapper does what a slice does for a 1-bit core, for W bits at a time:
  read  = pick the W bits [W*k +: W] of the word the unit addressed (k = digit index), per output lane;
  write = insert the W bits at digit k into a 32-bit accumulator, count the digits, and on the last one (32/W of them) write the whole word.
Ports: word addresses and whole words instead of {word, digit} and digits.  Needs uc_unitp<W>.v.  Gate: test_wordio.py uc_unitr<W> L."""
import os, subprocess, sys
L = int(sys.argv[1]); W = 1 << L; LWB = max(1, L.bit_length()); HERE = os.path.dirname(os.path.abspath(__file__))
subprocess.run([sys.executable, os.path.join(HERE, 'make_unit_v2.py'), str(L)], check=True, stdout=subprocess.DEVNULL)
def ch(f, default):
    s = default
    for k in range(1, L + 1): s = "(lw == %d'd%d) ? %s : %s" % (LWB, k, f(k), s)
    return s
rd = []
for l in range(W):
    arms = ["%d'd%d: o = w[({kk, %d'b0}) + %d];" % (LWB, k, k, l) if False else None for k in range(L + 1)]
    lines = []
    for k in range(L, -1, -1):
        if l < (1 << k):
            lines.append("%d'd%d: o%d = w[(kk << %d) + %d];" % (LWB, k, l, k, l))
    rd.append((l, lines))
rdtxt = ''
for l, lines in rd:
    rdtxt += "    reg o%d; always @* begin o%d = 1'b0; case (lw) %s default: o%d = 1'b0; endcase end\n    assign d[%d] = o%d;\n" % (l, l, ' '.join(lines), l, l, l)
bits = ''
for i in range(32):
    upd = ch(lambda k: "(kk == 5'd%d)" % (i >> k), "(kk == 5'd%d)" % i)
    val = ch(lambda k: "wd[%d]" % (i & ((1 << k) - 1)), "wd[0]")
    bits += "    assign word[%d] = (en & %s) ? %s : acc[%d];\n" % (i, upd, val, i)
acc = f'''
// word-RAM digit select (read): lane l of the digit = bit (kk * W + l) of the word, for l < W (width W = 2**lw)
module sc_rdsel{W} (input [31:0] w, input [4:0] kk, input [{LWB-1}:0] lw, output [{W-1}:0] d);
{rdtxt}endmodule

// write accumulator + digit counter: digits are inserted at digit index kk; the last digit of a pass (32/W of them) gives flush = 1 and the whole word on `word`
module sc_wacc{W} (input clk, input rst, input [{LWB-1}:0] lw, input en, input [4:0] kk, input [{W-1}:0] wd, output flush, output [31:0] word);
    reg [31:0] acc; reg [4:0] cnt;
    wire [4:0] nlast = {ch(lambda k: "5'd%d" % ((32 >> k) - 1), "5'd31")};
    assign flush = en & (cnt == nlast);
{bits}    always @(posedge clk) begin
        if (rst) begin cnt <= 5'd0; acc <= 32'd0; end
        else if (en) begin acc <= word; cnt <= flush ? 5'd0 : cnt + 5'd1; end
    end
endmodule
'''
top = f'''
module uc_unitr{W} (
    input  wire              clk,
    input  wire              rst,
    input  wire [{LWB-1}:0]        lw,
    output wire              halted,
    output wire              trap,
    output wire [29:0]       imem_addr,
    input  wire [31:0]       imem_data,
    // register file: whole words, two read ports, one word write port
    output wire [4:0]        ra_wa,
    input  wire [31:0]       ra_word,
    output wire [4:0]        rb_wa,
    input  wire [31:0]       rb_word,
    output wire              rw_we,
    output wire [4:0]        rw_wa,
    output wire [31:0]       rw_word,
    // data memory: whole words
    output wire [29:0]       d_wa,
    input  wire [31:0]       d_word,
    output wire              d_wwe,
    output wire [31:0]       d_wword
);
    wire [9:0]  ra_addr, rb_addr, rw_addr;
    wire [{W-1}:0] ra_data, rb_data, rw_data, d_wdata, d_rdata;
    wire        rw_en, d_we;
    wire [34:0] d_addr;
    uc_unitp{W} core (.clk(clk), .rst(rst), .lw(lw), .halted(halted), .trap(trap), .imem_addr(imem_addr), .imem_data(imem_data),
        .ra_addr(ra_addr), .ra_data(ra_data), .rb_addr(rb_addr), .rb_data(rb_data),
        .rw_en(rw_en), .rw_addr(rw_addr), .rw_data(rw_data),
        .d_addr(d_addr), .d_we(d_we), .d_wdata(d_wdata), .d_rdata(d_rdata));
    assign ra_wa = ra_addr[9:5]; assign rb_wa = rb_addr[9:5];
    sc_rdsel{W} sa (.w(ra_word), .kk(ra_addr[4:0]), .lw(lw), .d(ra_data));
    sc_rdsel{W} sb (.w(rb_word), .kk(rb_addr[4:0]), .lw(lw), .d(rb_data));
    sc_rdsel{W} sd (.w(d_word),  .kk(d_addr[4:0]),  .lw(lw), .d(d_rdata));
    assign rw_wa = rw_addr[9:5];
    assign d_wa  = d_addr[34:5];
    sc_wacc{W} wr (.clk(clk), .rst(rst), .lw(lw), .en(rw_en), .kk(rw_addr[4:0]), .wd(rw_data), .flush(rw_we), .word(rw_word));
    sc_wacc{W} wd (.clk(clk), .rst(rst), .lw(lw), .en(d_we),  .kk(d_addr[4:0]),  .wd(d_wdata), .flush(d_wwe), .word(d_wword));
endmodule
'''
open(os.path.join(HERE, 'uc_unitr%d.v' % W), 'w').write('// uc_unitr%d.v (GENERATED by make_unit_v3.py %d, do not edit): uc_unitp%d with its own word-RAM interface (ledger #1369).  Needs uc_unitp%d.v.\n' % (W, L, W, W) + acc + top)
print('wrote uc_unitr%d.v' % W)
