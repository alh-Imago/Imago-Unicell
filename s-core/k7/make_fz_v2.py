#!/usr/bin/env python3
"""make_fz_v2.py - stand-alone CLOCK TEST of the fusion units on the Kintex (ledger #1364).  Writes, for each variant, a top file sc_k7_fz_<v>.v and Makefile.fz_<v>.
Variants: p4, p8, p16 (uc_unitp4/8/16: the units of #1363 with the shift index pipelined).  Compare with fz_clk_result_2026-11-18.txt (fix16, g4, g8, g16).
The top is a stub: LFSR registers feed every input of the unit (instruction word, register and data bits, the width select lw), every output goes into a register and then
through a pipelined XOR tree to a LED, so nothing can be pruned and every path starts and ends at a flop.  What it times: the paths INSIDE the unit (decode -> lanes ->
carry chain -> rings and flags, the funnel, the address outputs).  What it does not time: the register / data RAM read in front of the unit (the pool's word-RAM digit
select), the host link, anything outside the unit.  The stub does not run a useful program; only static timing matters here.
Usage: python3 make_fz_v2.py            (writes the three variants)"""
import os
here = os.path.dirname(os.path.abspath(__file__))
base = open(os.path.join(here, 'Makefile.v2')).read()
assert 'PROJECT = sc_k7_v2' in base and 'rtl/sc_sys_v12.sv' in base
VARS = {  # name: (lanes W, rtl file stem, module text builder)
    'p4':    dict(W=4,  stem='uc_unitp4',  RA=10, DA=35, lwb=3),
    'p8':    dict(W=8,  stem='uc_unitp8',  RA=10, DA=35, lwb=3),
    'p16':   dict(W=16, stem='uc_unitp16', RA=10, DA=35, lwb=3),
}
for name, v in VARS.items():
    W, RA, DA = v['W'], v['RA'], v['DA']
    inst = ("uc_core_v2 #(.W(%d)) dut (" % W if name == 'fix16' else "uc_unitp%d dut (" % W) + \
           ".clk(SYS_CLK), .rst(rst)," + ("" if name == 'fix16' else " .lw(lw),") + \
           " .halted(halted), .trap(trap), .imem_addr(imem_addr), .imem_data(imem_data), .ra_addr(ra_addr), .ra_data(ra_data), .rb_addr(rb_addr), .rb_data(rb_data), " \
           ".rw_en(rw_en), .rw_addr(rw_addr), .rw_data(rw_data), .d_addr(d_addr), .d_we(d_we), .d_wdata(d_wdata), .d_rdata(d_rdata));"
    nb = 30 + RA + RA + 1 + RA + W + DA + 1 + W + 2
    top = f'''// sc_k7_fz_{name}.v - GENERATED by make_fz_v2.py: clock test stub around {'uc_core_v2 W=16 (fixed baseline)' if name == 'fix16' else 'uc_unitp%d' % W} (ledger #1364).  Do not edit.
module top (input SYS_CLK, output [2:0] led);
    localparam W = {W};
    localparam NB = {nb};                       // output bits registered and reduced
    reg [63:0] l1 = 64'h0123456789ABCDEF, l2 = 64'hFEDCBA9876543210;
    reg [7:0]  rcnt = 8'd0;
    reg        rst = 1'b1;
    always @(posedge SYS_CLK) begin
        l1 <= {{l1[62:0], l1[63] ^ l1[62] ^ l1[60] ^ l1[59]}};
        l2 <= {{l2[62:0], l2[63] ^ l2[62] ^ l2[60] ^ l2[59]}};
        if (rcnt != 8'hFF) rcnt <= rcnt + 8'd1;
        rst <= (rcnt < 8'd8);
    end
    wire [2:0]    lw         = l1[34:32];
    wire [31:0]   imem_data  = l1[31:0];
    wire [W-1:0]  ra_data    = l2[W-1:0];
    wire [W-1:0]  rb_data    = l2[W+15:16];
    wire [W-1:0]  d_rdata    = l2[W+31:32];
    wire          halted, trap, rw_en, d_we;
    wire [29:0]   imem_addr;
    wire [{RA-1}:0]    ra_addr, rb_addr, rw_addr;
    wire [W-1:0]  rw_data, d_wdata;
    wire [{DA-1}:0]   d_addr;
    {inst}
    wire [NB-1:0] ob = {{imem_addr, ra_addr, rb_addr, rw_en, rw_addr, rw_data, d_addr, d_we, d_wdata, halted, trap}};
    reg  [NB-1:0] oq;
    localparam N1 = (NB + 5) / 6, N2 = (N1 + 5) / 6;
    reg  [N1-1:0] r1;
    reg  [N2-1:0] r2;
    reg           r3;
    integer i;
    always @(posedge SYS_CLK) begin
        oq <= ob;
        for (i = 0; i < N1; i = i + 1) r1[i] <= ^((oq >> (6 * i)) & {{{{(NB-6){{{{1'b0}}}}}}, 6'h3F}});
        for (i = 0; i < N2; i = i + 1) r2[i] <= ^((r1 >> (6 * i)) & {{{{(N1-6){{{{1'b0}}}}}}, 6'h3F}});
        r3 <= ^r2;
    end
    assign led = {{l1[63], oq[0], r3}};
endmodule
'''
    open(os.path.join(here, 'sc_k7_fz_%s.v' % name), 'w').write(top)
    mk = base.replace('PROJECT = sc_k7_v2', 'PROJECT = sc_k7_fz_%s' % name)
    import re
    mk = re.sub(r'ADDITIONAL_SOURCES = .*', 'ADDITIONAL_SOURCES = rtl/%s.sv' % v['stem'], mk)
    mk = '# Makefile.fz_%s - GENERATED by make_fz_v2.py from Makefile.v2: clock test of %s (project sc_k7_fz_%s).\n' % (name, v['stem'], name) + mk
    open(os.path.join(here, 'Makefile.fz_%s' % name), 'w').write(mk)
    print('wrote sc_k7_fz_%s.v and Makefile.fz_%s' % (name, name))
