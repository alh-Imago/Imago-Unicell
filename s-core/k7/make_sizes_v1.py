#!/usr/bin/env python3
"""make_sizes_v1.py - write the files for a size sweep of the stage 1 build (block-RAM far RAM, host link v2): one Makefile and one top per slice count.

Why: one build (S=4) cannot say what a slice costs.  Builds at S=4, 8 and 16 with everything else equal give the cost per slice (the difference) and
the fixed part (dispatcher + RAM side + host link = what is left at S=0).  Three points also show whether the cost is a straight line.
Nothing proven is touched: this writes NEW files  Makefile.sN  and  sc_k7_sN_v1.v  next to Makefile.v2 (same sources, same pin file, same everything but S).
Usage:  python3 make_sizes_v1.py            writes S = 4 8 16
        python3 make_sizes_v1.py 4 8 12 16 32
Then see sizes_v1.sh (build them one after another) and sizetable_v1.py (read the logs into one table).
"""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
sizes = [int(a) for a in sys.argv[1:]] or [4, 8, 16]
base = open(os.path.join(here, "Makefile.v2")).read()
assert "PROJECT = sc_k7_v2" in base
for s in sizes:
    proj = "sc_k7_s%d" % s
    mk = base.replace("PROJECT = sc_k7_v2", "PROJECT = %s" % proj)
    mk = ("# Makefile.s%d - GENERATED by make_sizes_v1.py from Makefile.v2: same design, S=%d slices (project %s). Use:  make -f Makefile.s%d PNR_ARGS=\"--freq 50 --seed 2\"\n" % (s, s, proj, s)) + mk
    open(os.path.join(here, "Makefile.s%d" % s), "w").write(mk)
    top = ("// %s.v - GENERATED by make_sizes_v1.py: the stage 1 top (see sc_k7_v2.v) with S=%d slices; everything else as sc_k7_v2.v.\n"
           "module top (input SYS_CLK, output [2:0] led);\n"
           "    sc_top_k7_v3 #(.S(%d), .QD(16), .IMEM_WORDS(128), .DMW(16), .DSH(256), .SHL(14), .FAR_AW(16), .JK(32), .RXGAP(512)) u (.SYS_CLK(SYS_CLK), .led(led));\n"
           "endmodule\n") % (proj, s, s)
    open(os.path.join(here, "%s.v" % proj), "w").write(top)   # openXC7.mk wants the top in a file named after PROJECT
    print("wrote Makefile.s%d and %s.v" % (s, proj))
