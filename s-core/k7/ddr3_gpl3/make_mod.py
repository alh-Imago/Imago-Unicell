#!/usr/bin/env python3
"""make_mod.py - write MODIFIED copies of two UberDDR3 files into mod/ (GPL-3.0, derived from upstream/rtl, Angelo Jacobo).

Why: upstream UberDDR3 (commit 79d8fd3) does not place and calibrate on the Kintex-7 card with the open toolchain as it stands.  The same three changes
that sirmick's designs/uberddr3/prebuild.py makes (sirmick/ypcb-00338-1p1, MIT) are applied here as text edits, each checked, so any upstream change that
breaks one of them stops this script instead of producing a silently different file:
  1. DQS output stage: the clock inversion is done in the I/O tile (IS_CLK_INVERTED on the OSERDES) instead of a fabric inverter on i_ddr3_clk.
  2. DDR3 CK output: an ODDR clocked by its own PLL output i_ck_clk (the top level gives it 60 degrees after i_ddr3_clk) instead of a fabric inverter.
     This card's banks have no ODELAY, so there is no write leveling; one fixed CK offset suits all nine chips at DDR3-667 (sirmick's measurement).
  3. The single IDELAYCTRL moves out of the PHY into the top level (nextpnr allows one per design); the PHY and ddr3_top get ports i_ck_clk and i_idelayctrl_rdy.
Run:  python3 make_mod.py        (reads upstream/rtl, writes mod/ddr3_phy_ypcb_v1.v and mod/ddr3_top_ypcb_v1.v)
The module names stay ddr3_phy and ddr3_top: build with these two files INSTEAD OF upstream/rtl/ddr3_phy.v and ddr3_top.v, never together.
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
up = os.path.join(here, "upstream", "rtl")
out = os.path.join(here, "mod")
os.makedirs(out, exist_ok=True)

def sub(text, a, b, count=1):
    n = text.count(a)
    assert n == count, "expected %d occurrence(s) of %r, found %d" % (count, a, n)
    return text.replace(a, b)

HEADER = """// ============================================================================================================================================
// MODIFIED COPY of upstream/rtl/%(f)s  --  UberDDR3 by Angelo Jacobo, commit 79d8fd3, licensed GNU GPL version 3 (see ../upstream/LICENSE).
// This file is NOT under the MIT / CERN OHL licences of the rest of the repository.  It was generated by ../make_mod.py on the changes below;
// do not edit it by hand, change make_mod.py and run it again.  Changes made to the upstream file (GPL-3.0 section 5a notice):
%(changes)s// The original copyright and licence notice of the upstream file follows unchanged.
// ============================================================================================================================================
"""

# ---------------------------------------------------------------- PHY
phy = open(os.path.join(up, "ddr3_phy.v")).read()
dec = "        input wire i_ddr3_clk_90, //required only when ODELAY_SUPPORTED is zero\n"
phy = sub(phy, dec, dec + "        input wire i_ck_clk,\n        input wire i_idelayctrl_rdy,\n")

# 1. DQS OSERDES clock inversion in the I/O tile
i = phy.index(".CLK(!i_ddr3_clk)")
j = phy.rindex("#(", 0, i)
phy = phy[:j + 2] + "\n                    .IS_CLK_INVERTED(1'b1)," + phy[j + 2:i] + ".CLK(i_ddr3_clk)" + phy[i + len(".CLK(!i_ddr3_clk)"):]
assert ".CLK(!i_ddr3_clk)" not in phy

# 2. DDR3 CK from an ODDR on i_ck_clk
phy = sub(phy, ".I(!i_ddr3_clk)", ".I(ck_oddr)", count=3)
k = phy.index("    //synchronous reset\n")
phy = phy[:k] + """    // added by make_mod.py: the DDR3 CK output from an ODDR (D1=0, D2=1 is the inverted clock), not a fabric inverter (single rank only)
    wire ck_oddr;
    ODDR #(.DDR_CLK_EDGE("SAME_EDGE"), .INIT(1'b0), .SRTYPE("SYNC")) ck_oddr_inst (
        .Q(ck_oddr), .C(i_ck_clk), .CE(1'b1), .D1(1'b0), .D2(1'b1), .R(1'b0), .S(1'b0));

""" + phy[k:]

# 3. IDELAYCTRL out of the PHY
a = phy.rindex('    (* IODELAY_GROUP="DDR3-GROUP" *)', 0, phy.index("IDELAYCTRL IDELAYCTRL_inst ("))
b = phy.index("// End of IDELAYCTRL_inst instantiation", a)
phy = phy[:a] + "    assign idelayctrl_rdy = i_idelayctrl_rdy; // added by make_mod.py: the IDELAYCTRL is in the top level\n    " + phy[b:]

phy_changes = (
    "//   1. DQS OSERDES: .CLK(!i_ddr3_clk) became .CLK(i_ddr3_clk) with .IS_CLK_INVERTED(1'b1) (inversion in the I/O tile).\n"
    "//   2. DDR3 CK: the three .I(!i_ddr3_clk) of the clock output buffers became .I(ck_oddr), an ODDR on the new port i_ck_clk.\n"
    "//   3. IDELAYCTRL instance removed (now in the top level); new ports i_ck_clk and i_idelayctrl_rdy; idelayctrl_rdy is assigned from the port.\n")
open(os.path.join(out, "ddr3_phy_ypcb_v1.v"), "w").write(HEADER % dict(f="ddr3_phy.v", changes=phy_changes) + phy)

# ---------------------------------------------------------------- TOP
top = open(os.path.join(up, "ddr3_top.v")).read()
top = sub(top, dec, dec + "        input wire i_ck_clk,\n        input wire i_idelayctrl_rdy,\n")
top, n = re.subn(r"(\n\s*)\.i_ddr3_clk_90\(i_ddr3_clk_90\), *\n",
                 r"\1.i_ddr3_clk_90(i_ddr3_clk_90),\1.i_ck_clk(i_ck_clk),\1.i_idelayctrl_rdy(i_idelayctrl_rdy),\n", top)
assert n == 2, "expected 2 PHY instantiations in ddr3_top.v, found %d" % n
top_changes = "//   New ports i_ck_clk and i_idelayctrl_rdy on ddr3_top, passed to both PHY instances (only the first, ddr3_phy, is used on this card).\n"
open(os.path.join(out, "ddr3_top_ypcb_v1.v"), "w").write(HEADER % dict(f="ddr3_top.v", changes=top_changes) + top)

print("wrote mod/ddr3_phy_ypcb_v1.v and mod/ddr3_top_ypcb_v1.v")
