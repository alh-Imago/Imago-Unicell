#!/usr/bin/env python3
"""make_fz_v3.py - stand-alone CLOCK TEST of the units WITH word-RAM interface uc_unitr4/8/16 (ledger #1369); same stub idea and settings as make_fz_v2.py (#1364) so the numbers compare.
Variants r4, r8, r16.  The whole 32-bit RAM words come from LFSR flops (no RAM read delay); the unit's own digit select (read) and write accumulator are inside the timed paths.
Usage: python3 make_fz_v3.py"""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
base = open(os.path.join(here, 'Makefile.v2')).read()
for W in (4, 8, 16):
    name = 'r%d' % W
    nb = 30 + 5 + 5 + 1 + 5 + 32 + 30 + 1 + 32 + 2
    top = f'''// sc_k7_fz_{name}.v - GENERATED by make_fz_v3.py: clock test stub around uc_unitr{W} (word-RAM interface, ledger #1369).  Do not edit.
module top (input SYS_CLK, output [2:0] led);
    localparam NB = {nb};
    reg [63:0] l1 = 64'h0123456789ABCDEF, l2 = 64'hFEDCBA9876543210;
    reg [7:0]  rcnt = 8'd0;
    reg        rst = 1'b1;
    always @(posedge SYS_CLK) begin
        l1 <= {{l1[62:0], l1[63] ^ l1[62] ^ l1[60] ^ l1[59]}};
        l2 <= {{l2[62:0], l2[63] ^ l2[62] ^ l2[60] ^ l2[59]}};
        if (rcnt != 8'hFF) rcnt <= rcnt + 8'd1;
        rst <= (rcnt < 8'd8);
    end
    wire [2:0]  lw        = l1[34:32];
    wire [31:0] imem_data = l1[31:0];
    wire [31:0] ra_word   = l2[31:0];
    wire [31:0] rb_word   = l2[63:32];
    wire [31:0] d_word    = l1[63:32] ^ l2[47:16];
    wire        halted, trap, rw_we, d_wwe;
    wire [29:0] imem_addr, d_wa;
    wire [4:0]  ra_wa, rb_wa, rw_wa;
    wire [31:0] rw_word, d_wword;
    uc_unitr{W} dut (.clk(SYS_CLK), .rst(rst), .lw(lw), .halted(halted), .trap(trap), .imem_addr(imem_addr), .imem_data(imem_data),
        .ra_wa(ra_wa), .ra_word(ra_word), .rb_wa(rb_wa), .rb_word(rb_word), .rw_we(rw_we), .rw_wa(rw_wa), .rw_word(rw_word),
        .d_wa(d_wa), .d_word(d_word), .d_wwe(d_wwe), .d_wword(d_wword));
    wire [NB-1:0] ob = {{imem_addr, ra_wa, rb_wa, rw_we, rw_wa, rw_word, d_wa, d_wwe, d_wword, halted, trap}};
    reg  [NB-1:0] oq;
    localparam N1 = (NB + 5) / 6, N2 = (N1 + 5) / 6;
    reg  [N1-1:0] r1;
    reg  [N2-1:0] r2;
    reg           r3;
    integer i;
    always @(posedge SYS_CLK) begin
        oq <= ob;
        for (i = 0; i < N1; i = i + 1) r1[i] <= ^((oq >> (6 * i)) & {{{{(NB-6){{{{1'b0}}}}}}, 6'h3F}});
        for (i = 0; i < N2; i = i + 1) r2[i] <= ^((r1 >> (6 * i)) & {{{{(N1-6){{{{1'b0}}}}}}, 6'h3F}});
        r3 <= ^r2;
    end
    assign led = {{l1[63], oq[0], r3}};
endmodule
'''
    open(os.path.join(here, 'sc_k7_fz_%s.v' % name), 'w').write(top)
    mk = base.replace('PROJECT = sc_k7_v2', 'PROJECT = sc_k7_fz_%s' % name)
    mk = re.sub(r'ADDITIONAL_SOURCES = .*', 'ADDITIONAL_SOURCES = rtl/uc_unitr%d.sv rtl/uc_unitp%d.sv' % (W, W), mk)
    mk = '# Makefile.fz_%s - GENERATED by make_fz_v3.py from Makefile.v2: clock test of uc_unitr%d (project sc_k7_fz_%s).\n' % (name, W, name) + mk
    open(os.path.join(here, 'Makefile.fz_%s' % name), 'w').write(mk)
    print('wrote sc_k7_fz_%s.v and Makefile.fz_%s' % (name, name))
