#!/usr/bin/env python3
"""make_sizes_v2.py - clone of make_sizes_v1.py (kept as is) for the dispatcher sc_sys_v13: writes Makefile.v13_sN and sc_k7_v13s_sN.v.
Same design and sources as the size sweep, with sc_sys_v13.sv and sc_top_k7_v5.sv in place of sc_sys_v12.sv and sc_top_k7_v3.sv (ledger #1340/#1342).
Usage:  python3 make_sizes_v2.py 16        (default 16)     Then  S_CORE=... sh stage_v13.sh   and   make -f Makefile.v13_s16 PNR_ARGS="--freq 50 --seed 2" 2>&1 | tee build_v13_s16.log
"""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
sizes = [int(a) for a in sys.argv[1:]] or [16]
base = open(os.path.join(here, "Makefile.v2")).read()
assert "PROJECT = sc_k7_v2" in base and "rtl/sc_sys_v12.sv" in base and "rtl/sc_top_k7_v3.sv" in base
for s in sizes:
    proj = "sc_k7_v13s%d" % s
    mk = base.replace("PROJECT = sc_k7_v2", "PROJECT = %s" % proj).replace("rtl/sc_sys_v12.sv", "rtl/sc_sys_v13.sv").replace("rtl/sc_top_k7_v3.sv", "rtl/sc_top_k7_v5.sv")
    mk = "# Makefile.v13_s%d - GENERATED by make_sizes_v2.py from Makefile.v2: dispatcher sc_sys_v13, S=%d slices (project %s).\n" % (s, s, proj) + mk
    open(os.path.join(here, "Makefile.v13_s%d" % s), "w").write(mk)
    top = ("// %s.v - GENERATED by make_sizes_v2.py: the stage 1 top with the dispatcher sc_sys_v13 (sc_top_k7_v5) and S=%d slices.\n"
           "module top (input SYS_CLK, output [2:0] led);\n"
           "    sc_top_k7_v5 #(.S(%d), .QD(16), .IMEM_WORDS(128), .DMW(16), .DSH(256), .SHL(14), .FAR_AW(16), .JK(32), .RXGAP(512)) u (.SYS_CLK(SYS_CLK), .led(led));\n"
           "endmodule\n") % (proj, s, s)
    open(os.path.join(here, "%s.v" % proj), "w").write(top)
    print("wrote Makefile.v13_s%d and %s.v" % (s, proj))
