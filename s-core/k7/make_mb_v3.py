#!/usr/bin/env python3
"""make_mb_v3.py - build files for the multi-block top sc_top_k7_v10 with the FUSION UNIT (ledger #1378): writes Makefile.fu<NB>_s<S>_u<W> and sc_k7_fu<NB>s<S>u<W>.v.
Usage:  python3 make_mb_v3.py 2 8 3 2    (NB blocks of S slices, units of 2**ULW lanes, NU units per block; ULW = 0: no unit, same logic as v15).
Then  S_CORE=... sh stage_mb_v2.sh   and   MAKEFILE=Makefile.fu2_s8_u8_n2 SEEDS="3 1 2" bash seeds_v1.sh     (inside the nix shell, in the build folder)"""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
nb = int(sys.argv[1]) if len(sys.argv) > 1 else 2
s = int(sys.argv[2]) if len(sys.argv) > 2 else 4
ulw = int(sys.argv[3]) if len(sys.argv) > 3 else 2
nu = int(sys.argv[4]) if len(sys.argv) > 4 else 2
W = 1 << ulw
base = open(os.path.join(here, "Makefile.v2")).read()
assert "PROJECT = sc_k7_v2" in base and "rtl/sc_sys_v12.sv" in base and "rtl/sc_top_k7_v3.sv" in base and "rtl/host_bridge_v10.sv" in base
proj = "sc_k7_fu%ds%du%dn%d" % (nb, s, W, nu)
units = (" rtl/uc_unitw%d.sv rtl/uc_unith%d.sv" % (W, W)) if ulw else ""
mk = (base.replace("PROJECT = sc_k7_v2", "PROJECT = %s" % proj)
          .replace("rtl/sc_sys_v12.sv", "rtl/sc_sys_v17.sv rtl/fit_search_tree.sv" + units)
          .replace("rtl/host_bridge_v10.sv", "rtl/host_bridge_v11.sv")
          .replace("rtl/sc_top_k7_v3.sv", "rtl/far_arb.sv rtl/sc_block_v3.sv rtl/sc_top_k7_v10.sv"))
mk = "# Makefile.fu%d_s%d_u%d_n%d - GENERATED by make_mb_v3.py from Makefile.v2: %d blocks of %d slices, %d fusion units of %d lanes per block (sc_top_k7_v10, project %s).\n" % (nb, s, W, nu, nb, s, nu, W, proj) + mk
open(os.path.join(here, "Makefile.fu%d_s%d_u%d_n%d" % (nb, s, W, nu)), "w").write(mk)
top = ("// %s.v - GENERATED by make_mb_v3.py: the multi-block Kintex top with the fusion unit, %d blocks of %d slices, unit %d lanes.\n"
       "module top (input SYS_CLK, output [2:0] led);\n"
       "    sc_top_k7_v10 #(.NB(%d), .S(%d), .QD(16), .IMEM_WORDS(128), .DMW(16), .DSH(256), .SHL(14), .FZ(%d), .ULW(%d), .NU(%d), .FAR_AW(16), .JK(32), .RXGAP(512)) u (.SYS_CLK(SYS_CLK), .led(led));\n"
       "endmodule\n") % (proj, nb, s, W, nb, s, 1 if ulw else 0, ulw if ulw else 2, nu)
open(os.path.join(here, "%s.v" % proj), "w").write(top)
print("wrote Makefile.fu%d_s%d_u%d_n%d and %s.v" % (nb, s, W, nu, proj))
