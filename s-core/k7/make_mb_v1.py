#!/usr/bin/env python3
"""make_mb_v1.py - build files for the MULTI-BLOCK top sc_top_k7_v8 (ledger #1347): writes Makefile.mb<NB>_s<S> and sc_k7_mb<NB>s<S>.v (project sc_k7_mb<NB>s<S>).
Usage:  python3 make_mb_v1.py 2 16      (NB blocks of S slices; default 2 16).   Then  S_CORE=... sh stage_mb.sh   and
        MAKEFILE=Makefile.mb2_s16 SEEDS="3 1 2" bash seeds_v1.sh     (inside the nix shell, in the build folder)"""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
nb = int(sys.argv[1]) if len(sys.argv) > 1 else 2
s = int(sys.argv[2]) if len(sys.argv) > 2 else 16
base = open(os.path.join(here, "Makefile.v2")).read()
assert "PROJECT = sc_k7_v2" in base and "rtl/sc_sys_v12.sv" in base and "rtl/sc_top_k7_v3.sv" in base and "rtl/host_bridge_v10.sv" in base
proj = "sc_k7_mb%ds%d" % (nb, s)
mk = (base.replace("PROJECT = sc_k7_v2", "PROJECT = %s" % proj)
          .replace("rtl/sc_sys_v12.sv", "rtl/sc_sys_v15.sv rtl/fit_search_tree.sv")
          .replace("rtl/host_bridge_v10.sv", "rtl/host_bridge_v11.sv")
          .replace("rtl/sc_top_k7_v3.sv", "rtl/far_arb.sv rtl/sc_block.sv rtl/sc_top_k7_v8.sv"))
mk = "# Makefile.mb%d_s%d - GENERATED by make_mb_v1.py from Makefile.v2: %d blocks of %d slices (sc_top_k7_v8, project %s).\n" % (nb, s, nb, s, proj) + mk
open(os.path.join(here, "Makefile.mb%d_s%d" % (nb, s)), "w").write(mk)
top = ("// %s.v - GENERATED by make_mb_v1.py: the multi-block Kintex top, %d blocks of %d slices.\n"
       "module top (input SYS_CLK, output [2:0] led);\n"
       "    sc_top_k7_v8 #(.NB(%d), .S(%d), .QD(16), .IMEM_WORDS(128), .DMW(16), .DSH(256), .SHL(14), .FAR_AW(16), .JK(32), .RXGAP(512)) u (.SYS_CLK(SYS_CLK), .led(led));\n"
       "endmodule\n") % (proj, nb, s, nb, s)
open(os.path.join(here, "%s.v" % proj), "w").write(top)
print("wrote Makefile.mb%d_s%d and %s.v" % (nb, s, proj))
