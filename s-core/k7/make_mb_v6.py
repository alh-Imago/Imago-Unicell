#!/usr/bin/env python3
"""# make_mb_v6.py - make_mb_v5.py with the unit-less fix (ULW 0 gives FZ(0) NU(1), not NU(0); ledger #1466), files named hd... Cloned from make_mb_v5.py (left as proven; its unit-less builds hc4 / hc8 / hc2_s4 do not run jobs).
# make_mb_v6.py - like make_mb_v3.py but for the top sc_top_k7_v12 (status read inside the blocks: host_bridge_v12 + blk_rd_v1 + sc_top_k7_v12; ledger #1457). Files are named hn<NB>... Cloned from make_mb_v4.py (left as proven); the top is sc_top_k7_v12 (status AND command decode inside the blocks, ledger #1459), files named hc...
make_mb_v6.py - build files for the multi-block top sc_top_k7_v12 with the FUSION UNIT (ledger #1378): writes Makefile.fu<NB>_s<S>_u<W> and sc_k7_fu<NB>s<S>u<W>.v.
Usage:  python3 make_mb_v6.py 2 8 3 2    (NB blocks of S slices, units of 2**ULW lanes, NU units per block; ULW = 0: no unit, same logic as v15).
Then  S_CORE=... sh stage_mb_v2.sh   and   MAKEFILE=Makefile.fu2_s8_u8_n2 SEEDS="3 1 2" bash seeds_v1.sh     (inside the nix shell, in the build folder)"""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
nb = int(sys.argv[1]) if len(sys.argv) > 1 else 2
s = int(sys.argv[2]) if len(sys.argv) > 2 else 4
ulw = int(sys.argv[3]) if len(sys.argv) > 3 else 2
nu = int(sys.argv[4]) if len(sys.argv) > 4 else 2
W = 1 << ulw
if ulw == 0: nu = max(nu, 1)      # v6 (ledger #1466): NU=0 breaks sc_sys_v17 (arrays [NU-1:0]); a unit-less build is FZ=0 with NU=1 (the unit is declared and never bound)
base = open(os.path.join(here, "Makefile.v2")).read()
assert "PROJECT = sc_k7_v2" in base and "rtl/sc_sys_v12.sv" in base and "rtl/sc_top_k7_v3.sv" in base and "rtl/host_bridge_v10.sv" in base
proj = "sc_k7_hd%ds%du%dn%d" % (nb, s, W, nu)
units = (" rtl/uc_unitw%d.sv rtl/uc_unith%d.sv" % (W, W)) if ulw else ""
mk = (base.replace("PROJECT = sc_k7_v2", "PROJECT = %s" % proj)
          .replace("rtl/sc_sys_v12.sv", "rtl/sc_sys_v17.sv rtl/fit_search_tree.sv" + units)
          .replace("rtl/host_bridge_v10.sv", "rtl/host_bridge_v13.sv rtl/blk_rd_v2.sv rtl/blk_cmd_v1.sv")
          .replace("rtl/sc_top_k7_v3.sv", "rtl/far_arb.sv rtl/sc_block_v3.sv rtl/sc_top_k7_v12.sv"))
mk = "# Makefile.hd%d_s%d_u%d_n%d - GENERATED by make_mb_v6.py from Makefile.v2: %d blocks of %d slices, %d fusion units of %d lanes per block (sc_top_k7_v12, project %s).\n" % (nb, s, W, nu, nb, s, nu, W, proj) + mk
open(os.path.join(here, "Makefile.hd%d_s%d_u%d_n%d" % (nb, s, W, nu)), "w").write(mk)
top = ("// %s.v - GENERATED by make_mb_v6.py: the multi-block Kintex top with the fusion unit, %d blocks of %d slices, unit %d lanes.\n"
       "module top (input SYS_CLK, output [2:0] led);\n"
       "    sc_top_k7_v12 #(.NB(%d), .S(%d), .QD(16), .IMEM_WORDS(128), .DMW(16), .DSH(256), .SHL(14), .FZ(%d), .ULW(%d), .NU(%d), .FAR_AW(16), .JK(32), .RXGAP(512)) u (.SYS_CLK(SYS_CLK), .led(led));\n"
       "endmodule\n") % (proj, nb, s, W, nb, s, 1 if ulw else 0, ulw if ulw else 2, nu)
open(os.path.join(here, "%s.v" % proj), "w").write(top)
print("wrote Makefile.hd%d_s%d_u%d_n%d and %s.v" % (nb, s, W, nu, proj))
