#!/usr/bin/env python3
"""make_unit_v11.py L - writes uc_unity<W>.v (ledger #1608): uc_unitx<W> (left as proven) plus the output dmem_mis = a MISALIGNED HALFWORD load is live (lh / lhu with address bit 0 set), taken from the ld_nar / ld_off outputs of uc_unitm<W>, so the pool can trap it (cause 6).  Needs uc_unitx<W>.v.  Usage: python3 make_unit_v11.py 2 | 3 | 4 | 5"""
import os, re, sys
L = int(sys.argv[1]); W = 1 << L; HERE = os.path.dirname(os.path.abspath(__file__))
r = open(os.path.join(HERE, 'uc_unitx%d.v' % W)).read()
def rep(old, new):
    global r
    assert r.count(old) == 1, (old, r.count(old)); r = r.replace(old, new)
rep("module uc_unitx%d (" % W, "module uc_unity%d (" % W)
rep("    output wire              dmem_nar,", "    output wire              dmem_mis,       // v11: a halfword load of an odd address is live (lh / lhu, address bit 0 set)\n    output wire              dmem_nar,")
rep("    assign dmem_nar = ld_nar[0];\n", "    assign dmem_nar = ld_nar[0];\n    assign dmem_mis = ld_nar[1] & ld_off[0];\n")
r = re.sub(r'^// uc_unitx%d.v.*\n' % W, '// uc_unity%d.v (GENERATED by make_unit_v11.py %d, do not edit): uc_unitx%d plus the output dmem_mis (a misaligned halfword load is live; ledger #1608).  Needs uc_unitm%d.v.\n' % (W, L, W, W), r, count=1)
open(os.path.join(HERE, 'uc_unity%d.v' % W), 'w').write(r)
print('wrote uc_unity%d.v' % W)
