#!/usr/bin/env python3
"""make_unit_v6.py 5 - make_unit_v1.py for 32 lanes (ledger #1514): the same generator with the two things W = 32 breaks fixed: a rotate by 32 is no change (no empty part select), and the effective width WE has 6 bits (32 does not fit 5). Cloned from make_unit_v1.py (left as proven); refuses any L but 5 so the proven 4-, 8- and 16-lane files are never overwritten.
Original text of make_unit_v1.py follows:  make_unit_v1.py L - writes uc_unitg<W>.v (W = 2**L lanes, widths 1, 2, ..., W chosen at run time by input lw = 0..L): the controller unit with lane cells of
uc_unit4.v generalised (ledger #1359).  Every width-dependent choice is an explicit multi-way choice (not a variable shift: those become barrel shifters).
Usage: python3 make_unit_v1.py 3    -> uc_unitg8.v ;    python3 make_unit_v1.py 4   -> uc_unitg16.v ;   python3 make_unit_v1.py 2 gives the 4-lane unit again as uc_unitg4.v (checked equal in results to uc_unit4.v)."""
import re, sys, os
L = int(sys.argv[1]); assert L == 5, 'make_unit_v6.py is for 32 lanes only (L = 5); the 4, 8 and 16 lane files come from make_unit_v1.py'; W = 1 << L; LWB = max(1, L.bit_length()); HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, 'uc_unit4.v')).read()
def chain(f):      # nested choice over lw, widest first, default width 1
    s = f(0)
    for k in range(1, L + 1): s = '(lw == %d\'d%d) ? %s : %s' % (LWB, k, f(k), s)
    return s if L else f(0)
def top(f): return chain(f)
ME = lambda k: -(-5 // (1 << k)); SHW = max(ME(k) * (1 << k) for k in range(L + 1))
rep = {
 'parameter W   = 4,': "parameter W   = %d,                     // lanes built (max width); widths 1 .. %d" % (W, W),
 'parameter SHW = 8': 'parameter SHW = %d' % SHW,
 'input  wire [1:0]        lw,': 'input  wire [%d:0]        lw,           // log2 of bits per cycle, 0 .. %d (held steady while a task runs)' % (LWB - 1, L),
 'wire [3:0]    lm   =': "wire [%d:0]   lm   = %s;   // lane mask" % (W - 1, chain(lambda k: "%d'd%d" % (W, (1 << (1 << k)) - 1))),
 'wire [2:0]    WE   =': "wire [5:0]    WE   = %s;   // effective width (6 bits: 32 does not fit 5)" % chain(lambda k: "6'd%d" % (1 << k)),
 'wire [5:0]    NE   =': "wire [5:0]    NE   = %s;   // digits per word" % chain(lambda k: "6'd%d" % (32 >> k)),
 'wire [2:0]    ME   =': "wire [2:0]    ME   = %s;   // digits holding a 5-bit shift amount" % chain(lambda k: "3'd%d" % ME(k)),
 'wire [W-1:0] c4_d  =': "wire [W-1:0] c4_d  = %s;" % chain(lambda k: "((32'd4 >> (k * %d)) & 32'd%d)" % (1 << k, (1 << (1 << k)) - 1)),
 'wire [31:0] pc_rot   =': "wire [31:0] pc_rot   = %s;" % chain(lambda k: ("{pc[%d:0], pc[31:%d]}" % ((1 << k) - 1, 1 << k)) if k < 5 else "pc"),
 'wire [31:0] imm_rot  =': "wire [31:0] imm_rot  = %s;" % chain(lambda k: ("{imm_sr[%d:0], imm_sr[31:%d]}" % ((1 << k) - 1, 1 << k)) if k < 5 else "imm_sr"),
 'wire [4:0] q =': "wire [4:0] q = %s;" % chain(lambda k: "(shamt >> %d)" % k),
 'wire [4:0] r =': "wire [4:0] r = %s;" % chain(lambda k: "(shamt & 5'd%d)" % ((1 << k) - 1)),
 'wire [5:0]   fsh  =': "wire [5:0]   fsh  = is_sll ? ({1'b0, WE} - {1'b0, r}) : {1'b0, r};",
 'wire [2*W-1:0] cat =': "wire [2*W-1:0] cat = %s;" % chain(lambda k: ("{%d'd0, hi[%d:0], lo[%d:0]}" % (2 * W - 2 * (1 << k), (1 << k) - 1, (1 << k) - 1)) if 2 * W - 2 * (1 << k) else "{hi, lo}"),
 'wire         xtop =': "wire         xtop = %s;     // sign lane" % chain(lambda k: "X[%d]" % ((1 << k) - 1)),
 'wire         ytop =': "wire         ytop = %s;" % chain(lambda k: "Yr[%d]" % ((1 << k) - 1)),
 'wire         cout =': "wire         cout = %s;" % chain(lambda k: "cc[%d]" % (1 << k)),
 'wire [31:0] pc_ins   =': "wire [31:0] pc_ins   = %s;" % chain(lambda k: ("{sum_d[%d:0], pc[31:%d]}" % ((1 << k) - 1, 1 << k)) if k < 5 else "sum_d[31:0]"),
 'wire [31:0] addr_ins =': "wire [31:0] addr_ins = %s;" % chain(lambda k: ("{sum_d[%d:0], addr[31:%d]}" % ((1 << k) - 1, 1 << k)) if k < 5 else "sum_d[31:0]"),
}
lines = src.split('\n'); out = []
for ln in lines:
    done = False
    for key, new in rep.items():
        if ln.strip().startswith(key):
            ind = ln[:len(ln) - len(ln.lstrip())]; out.append(ind + new); done = True; break
    if done: continue
    if 'sgn <= (lw == 2' in ln:
        ind = ln[:len(ln) - len(ln.lstrip())]; out.append(ind + 'sgn <= %s;' % chain(lambda k: "a_val[%d]" % ((1 << k) - 1))); continue
    if ln.strip().startswith('if (is_op) begin if (lw == 2'):
        ind = ln[:len(ln) - len(ln.lstrip())]
        t = ' else '.join(('if (lw == %d\'d%d) shamt_w[%d*j +: %d] <= b_val[%d:0];' % (LWB, k, 1 << k, 1 << k, (1 << k) - 1)) for k in range(L, 0, -1))
        out.append(ind + 'if (is_op) begin ' + (t + ' else ' if L else '') + 'shamt_w[j] <= b_val[0]; end'); continue
    out.append(ln)
s = '\n'.join(out)
s = s.replace('module uc_unit4 #(', 'module uc_unitg%d #(' % W, 1)
s = s.replace('// uc_unit4.v - ', '// uc_unitg%d.v (GENERATED by make_unit_v6.py %d from uc_unit4.v, do not edit; uc_unit4.v itself is never changed) - was: ' % (W, L), 1)
s = s.replace('(a_val)', '(a_val)')
open(os.path.join(HERE, 'uc_unitg%d.v' % W), 'w').write(s)
print('wrote uc_unitg%d.v' % W)
