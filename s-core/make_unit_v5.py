#!/usr/bin/env python3
"""make_unit_v5.py L - writes uc_unith<W>.v and uc_unitw<W>.v (ledger #1377): step I0 of the pool integration plan (FUSION_PLAN.md).
uc_unith<W> = the pipelined unit uc_unitp<W> with the HOOKS the pool's slice needs around a core (the ones uc_core_v2s/t/u/v added to uc_core_v2): inputs start, entry, ce, abort;
outputs fetching, dmem_act, dmem_ld; reset into HALT; the core steps only when ce = 1; `start` while halted loads pc = entry.  The pipelined shift index (ia, ib, va, vb) steps only on ce too.
uc_unitw<W> = the word-RAM wrapper of make_unit_v3.py around it, with the same hooks, plus an input dblk (a store is blocked by the region check): writes into the accumulators happen only
when ce = 1 (and, for data, not blocked), as the pool's `rw_now = rwe & ce_g`, `dw_now = dwe & ~dviol & ce_g`.
Needs uc_unitp<W>.v and uc_unitr<W>.v (make_unit_v2.py / make_unit_v3.py).  Usage: python3 make_unit_v5.py 2 | 3 | 4"""
import os, re, subprocess, sys
L = int(sys.argv[1]); W = 1 << L; HERE = os.path.dirname(os.path.abspath(__file__))
subprocess.run([sys.executable, os.path.join(HERE, 'make_unit_v3.py'), str(L)], check=True, stdout=subprocess.DEVNULL)
s = open(os.path.join(HERE, 'uc_unitp%d.v' % W)).read()
def rep(old, new, cnt=1):
    global s
    assert s.count(old) == cnt, (old, s.count(old)); s = s.replace(old, new)
rep("    output wire              halted,\n    output wire              trap,\n",
    "    input  wire              start,          // pool hooks (I0): start while halted loads pc = entry; the core steps only when ce = 1\n"
    "    input  wire [31:0]       entry,\n    input  wire              ce,\n    input  wire              abort,          // stop now, as a trap\n"
    "    output wire              halted,\n    output wire              trap,\n"
    "    output wire              fetching,       // state == S_FETCH\n    output wire              dmem_act,       // a data word address is live (load / store, WR2)\n"
    "    output wire              dmem_ld,        // ... and it is a load\n")
rep("    assign imem_addr = pc[31:2];\n",
    "    assign imem_addr = pc[31:2];\n    assign fetching = (state == S_FETCH);\n    assign dmem_act = (state == S_WR2) & (is_ld | is_st);\n    assign dmem_ld  = (state == S_WR2) & is_ld;\n")
rep("            shamt_w <= 0; halted_r <= 1'b0; trap_r <= 1'b0;\n        end else begin\n",
    "            shamt_w <= 0; halted_r <= 1'b1; trap_r <= 1'b0; state <= S_HALT;\n"
    "        end else if (abort && state != S_HALT) begin\n            trap_r <= 1'b1; halted_r <= 1'b1; state <= S_HALT;\n"
    "        end else if (ce && start && state == S_HALT) begin\n            pc <= entry; k <= 0; halted_r <= 1'b0; trap_r <= 1'b0; state <= S_FETCH;\n"
    "        end else if (ce) begin\n")
rep("        else if (pre_exit) begin", "        else if (pre_exit & ce) begin")
rep("        end else if (stp) begin", "        end else if (stp & ce) begin")
s = s.replace('module uc_unitp%d #(' % W, 'module uc_unith%d #(' % W, 1)
s = '// uc_unith%d.v (GENERATED by make_unit_v5.py %d from uc_unitp%d.v, do not edit): the pipelined unit with the pool hooks start / entry / ce / abort / fetching / dmem_act / dmem_ld (ledger #1377).\n' % (W, L, W) + s
open(os.path.join(HERE, 'uc_unith%d.v' % W), 'w').write(s)
r = open(os.path.join(HERE, 'uc_unitr%d.v' % W)).read()
def rr(old, new):
    global r
    assert r.count(old) == 1, (old, r.count(old)); r = r.replace(old, new)
rr("module uc_unitr%d (" % W, "module uc_unitw%d (" % W)
rr("    output wire              halted,\n    output wire              trap,\n",
   "    input  wire              start,\n    input  wire [31:0]       entry,\n    input  wire              ce,\n    input  wire              abort,\n    input  wire              dblk,           // a data store is blocked (region check of the slice): it is not accumulated\n"
   "    output wire              halted,\n    output wire              trap,\n    output wire              fetching,\n    output wire              dmem_act,\n    output wire              dmem_ld,\n")
rr("    uc_unitp%d core (.clk(clk), .rst(rst), .lw(lw), .halted(halted), .trap(trap), .imem_addr(imem_addr), .imem_data(imem_data),"
   % W, "    uc_unith%d core (.clk(clk), .rst(rst), .lw(lw), .start(start), .entry(entry), .ce(ce), .abort(abort), .halted(halted), .trap(trap), .fetching(fetching), .dmem_act(dmem_act), .dmem_ld(dmem_ld), .imem_addr(imem_addr), .imem_data(imem_data),"
   % W)
rr("wr (.clk(clk), .rst(rst),", "wr (.clk(clk), .rst(rst | start),")
rr(".en(rw_en),", ".en(rw_en & ce),")
rr(".en(d_we),", ".en(d_we & ce & ~dblk),")
rr("wd (.clk(clk), .rst(rst),", "wd (.clk(clk), .rst(rst | start),")
r = re.sub(r'^// uc_unitr%d.v.*\n' % W, '// uc_unitw%d.v (GENERATED by make_unit_v5.py %d, do not edit): uc_unitr%d with the pool hooks (start, entry, ce, abort, dblk; fetching, dmem_act, dmem_ld) around uc_unith%d (ledger #1377).  Needs uc_unith%d.v.\n' % (W, L, W, W, W), r, count=1)
open(os.path.join(HERE, 'uc_unitw%d.v' % W), 'w').write(r)
print('wrote uc_unith%d.v and uc_unitw%d.v' % (W, W))
