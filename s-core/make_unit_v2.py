#!/usr/bin/env python3
"""make_unit_v2.py L - writes uc_unitp<W>.v (W = 2**L lanes): the unit of make_unit_v1.py with the shift index PIPELINED (ledger #1364).
The shift-index arithmetic (ia, ib, va, vb: which digits a shift reads and whether they exist) was the critical path of the stand-alone clock test (#1363).  Here it is
worked out one clock ahead and held in registers: ia/ib step by one digit exactly as k does, and at the end of S_PRE they are loaded from the (merged) shift amount.
Same behaviour and the SAME clock counts as uc_unitg<W>.v (gate: test_wide.py uc_unitp<W> L).  Nothing existing is changed: it reads the generated uc_unitg<W>.v.
Usage: python3 make_unit_v2.py 2 | 3 | 4"""
import os, subprocess, sys
L = int(sys.argv[1]); W = 1 << L; LWB = max(1, L.bit_length()); HERE = os.path.dirname(os.path.abspath(__file__))
subprocess.run([sys.executable, os.path.join(HERE, 'make_unit_v1.py'), str(L)], check=True, stdout=subprocess.DEVNULL)
s = open(os.path.join(HERE, 'uc_unitg%d.v' % W)).read()
def chain(f):
    t = f(0)
    for k in range(1, L + 1): t = "(lw == %d'd%d) ? %s : %s" % (LWB, k, f(k), t)
    return t
old = ["wire signed [8:0] ia = is_sll ? (ks - qs)     : (ks + qs);",
       "wire signed [8:0] ib = is_sll ? (ks - qs - 1) : (ks + qs + 1);",
       "wire va = (ia >= 0) && (ia <= $signed({3'b0, NE}) - 1);",
       "wire vb = (ib >= 0) && (ib <= $signed({3'b0, NE}) - 1);"]
for o in old: assert s.count(o) == 1, o
s = s.replace(old[0], "reg signed [8:0] ia;   // registered (pipelined) shift index, see the block before endmodule")
s = s.replace(old[1], "reg signed [8:0] ib;")
s = s.replace(old[2], "reg va;")
s = s.replace(old[3], "reg vb;")
ifs = ' else '.join(("if (lw == %d'd%d) shamt_nx[%d*j +: %d] = b_val[%d:0];" % (LWB, k, 1 << k, 1 << k, (1 << k) - 1)) for k in range(L, 0, -1))
blk = f'''
    // ---- pipelined shift index (make_unit_v2.py) ----
    // shift amount as it will be at the end of S_PRE (the digit being written now merged in; before the last write shamt_w alone is not final)
    reg [SHW-1:0] shamt_nx;
    always @* begin
        shamt_nx = shamt_w;
        if (is_op) begin {ifs + ' else ' if L else ''}shamt_nx[j] = b_val[0]; end
    end
    wire [4:0] qn = {chain(lambda k: "(shamt_nx[4:0] >> %d)" % k)};
    wire signed [8:0] qns = $signed({{4'b0, qn}});
    wire signed [8:0] nem1 = $signed({{3'b0, NE}}) - 9'sd1;
    wire signed [8:0] ia_p = is_sll ? (nem1 - qns)       : qns;           // first EXEC digit: k = NE-1 (sll) or 0
    wire signed [8:0] ib_p = is_sll ? (nem1 - qns - 9'sd1) : (qns + 9'sd1);
    wire signed [8:0] ia_s = is_sll ? (ia - 9'sd1) : (ia + 9'sd1);       // next EXEC digit
    wire signed [8:0] ib_s = is_sll ? (ib - 9'sd1) : (ib + 9'sd1);
    wire pre_exit = in_pre & (j == (is_op ? ME - 1 : 0));
    wire stp      = in_exec & is_shift & ~exec_done;
    always @(posedge clk) begin
        if (rst) begin ia <= 0; ib <= 0; va <= 1'b0; vb <= 1'b0; end
        else if (pre_exit) begin
            ia <= ia_p; ib <= ib_p;
            va <= (ia_p >= 0) && (ia_p <= nem1);
            vb <= (ib_p >= 0) && (ib_p <= nem1);
        end else if (stp) begin
            ia <= ia_s; ib <= ib_s;
            va <= (ia_s >= 0) && (ia_s <= nem1);
            vb <= (ib_s >= 0) && (ib_s <= nem1);
        end
    end
endmodule'''
i = s.rindex('endmodule', 0, s.index('\nmodule sc_lane')); s = s[:i].rstrip('\n') + '\n' + blk + s[i + len('endmodule'):]
s = s.replace('module uc_unitg%d #(' % W, 'module uc_unitp%d #(' % W, 1)
s = '// uc_unitp%d.v (GENERATED by make_unit_v2.py %d from uc_unitg%d.v, do not edit): shift index pipelined one clock ahead (ledger #1364); same clock counts.\n' % (W, L, W) + s
open(os.path.join(HERE, 'uc_unitp%d.v' % W), 'w').write(s); print('wrote uc_unitp%d.v' % W)
