#!/usr/bin/env python3
"""make_probe_rom.py - assemble the register-file stress program for bram_probe_top and write bram_probe_rom.vh.

The program touches EVERY register x1..x31 (so every register-file address bit is used), mixes them with
add / xor / sub / shifts, stores and loads a few data words, and loops forever.  What it computes does not
matter: the probe only compares block-RAM reads against a LUT-RAM copy, so all it needs is lots of varied
traffic on every address.
"""
import os, random, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import runtests

rng = random.Random(20261114)
lines = []
for r in range(1, 32):
    lines.append('li x%d, 0x%08x' % (r, rng.getrandbits(32)))
lines.append('loop:')
ops = ['add', 'xor', 'sub', 'or', 'and']
for rnd in range(3):
    for r in range(1, 32):
        a, b = (r % 31) + 1, ((r * 7 + rnd * 5) % 31) + 1
        lines.append('%s x%d, x%d, x%d' % (rng.choice(ops), r, a, b))
    for r in (3, 9, 14, 20, 27, 31):
        lines.append('slli x%d, x%d, %d' % (r, r, rng.randint(1, 31)))
        lines.append('srli x%d, x%d, %d' % (r, r, rng.randint(1, 31)))
    for i, r in enumerate((5, 12, 17, 22, 29, 31)):
        lines.append('sw x%d, %d(x0)' % (r, 4 * (i + rnd * 3)))
    for i, r in enumerate((6, 13, 18, 24, 30, 28)):
        lines.append('lw x%d, %d(x0)' % (r, 4 * (i + rnd * 3)))
    lines.append('bne x%d, x0, skip%d' % (rng.randint(1, 31), rnd))
    lines.append('addi x%d, x%d, 1' % (rng.randint(1, 31), rng.randint(1, 31)))
    lines.append('skip%d:' % rnd)
lines.append('j loop')
words = runtests.assemble('\n'.join(lines))
try:
    runtests.iss(words, max_steps=200000)
except runtests.Trap as e:
    assert 'too many steps' in str(e), e          # runs forever, as intended; anything else is a bug
n = 1
while n < len(words): n *= 2
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bram_probe_rom.vh')
with open(out, 'w') as f:
    f.write('// generated by make_probe_rom.py - register-file stress program, %d words\n' % len(words))
    for i, w in enumerate(words): f.write("            %d: rom_f = 32'h%08x;\n" % (i, w))
print('%d words (ROM depth %d) -> %s' % (len(words), n, out))
