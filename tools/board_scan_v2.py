#!/usr/bin/env python3
"""tools/board_scan_v2.py -- ledger #1151: the in-flight capture / restore card kit for a design that comes from a LaTeX formula (v2 of the generator board_scan_v1.py, which stays as it was).

formula (LaTeX)  ->  nano/latex_frontend_v1.py  ->  ICM file  ->  flex assembler  ->  freeze net + busy port + SCAN CHAIN (tools/flex_scan_net_v2.py: now with mul and div cells)
                 ->  a loop wrapper generated for the design's ports (the result is fed back as the next input: z -> f(z) -> f(f(z)) ...)  ->  the same serial controller and protocol as board_scan_v1.py.
The designer writes one line of maths; nothing about cells or Verilog is chosen by hand. The loop wrapper feeds the word to ALL of the design's input ports of the one variable at the same moment (it waits until every
port can take it), so no half-injected word can exist outside the scan chain.

  python3 tools/board_scan_v2.py --formula 'y = (z^2 + 12345) \\bmod 65521' --name qcgmod --out fpga/board_tests_scan_latex [--no-pnr]
"""
import argparse, json, os, re, shutil, subprocess, sys, tempfile
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools")); sys.path.insert(0, os.path.join(ROOT, "nano"))
import board_scan_v1 as v1  # noqa: E402
import board_tests_v1 as bt, board_mutability_v1 as bm  # noqa: E402
import flex_freeze_net_v1 as fz, flex_busy_port_v1 as bz, flex_scan_net_v2 as sn  # noqa: E402

FORMULA = r"y = (z^2 + 12345) \bmod 65521"
NAME = "qcgmod1"          # exactly 7 characters: it is printed in every dump line


def gen_wrapper(top, name, in_ports, out_port):
    """The stop wrapper (sub/verilog/looped_cordic_stop_wrapper_v3.v, untouched) re-cut for another grid: every input port gets the loop word at the same moment, and only when all of them can take it."""
    s = open(os.path.join(ROOT, "sub", "verilog", "looped_cordic_stop_wrapper_v3.v")).read()
    s = "// GENERATED by tools/board_scan_v2.py (ledger #1151) from looped_cordic_stop_wrapper_v3.v for the grid %s; do not hand-edit.\n" % top + s[s.index("`default_nettype"):]
    s = s.replace("looped_cordic_stop_wrapper_v3", "looped_%s_wrapper" % name)
    old = "    wire [31:0] o_d; wire o_v, o_a; wire [31:0] i_d; wire i_v, i_a;\n"
    assert old in s
    acks = ", ".join("a%d" % k for k in range(len(in_ports)))
    s = s.replace(old, "    wire [31:0] o_d; wire o_v, o_a; wire [31:0] i_d; wire i_v; wire %s;\n    wire all_ack = &{%s};\n" % (acks, acks))
    old = "& ~bp & ~gate;"
    assert old in s
    s = s.replace(old, "& ~bp & ~gate & all_ack;")
    old = "else if (cv && i_v && i_a) cv <= 0;"
    assert old in s
    s = s.replace(old, "else if (cv && i_v) cv <= 0;")
    a = s.index("    icm_open_flex_fz_scan grid")
    b = s.index(");", a) + 2
    ins = ", ".join(".in_%s_data(i_d), .in_%s_valid(i_v), .in_%s_ack(a%d)" % (p, p, p, k) for k, p in enumerate(in_ports))
    inst = ("    %s grid (.scan_en(scan_en), .scan_in(scan_in), .scan_out(scan_out), .freeze_all(fz), .busy_any(busy), .clk(clk), .rst(rst), .cfg_valid(cfg_grid),\n        %s,\n"
            "        .out_%s_data(o_d), .out_%s_valid(o_v), .out_%s_ack(o_a));" % (top, ins, out_port, out_port, out_port))
    return s[:a] + inst + s[b:]


def top_text(cpb, tmo, mutant, nb, core, dname):
    assert len(dname) == 7
    t = v1.top_text(cpb, tmo, mutant, nb, core)
    old = '4: obyte = "l"; 5: obyte = "c"; 6: obyte = "o"; 7: obyte = "r"; 8: obyte = "d"; 9: obyte = "i"; 10: obyte = "c";'
    assert old in t
    return t.replace(old, " ".join('%d: obyte = "%s";' % (4 + k, ch) for k, ch in enumerate(dname)))


def build_files(work, cpb, tmo, mutant="none", formula=FORMULA, dname=NAME):
    from latex_frontend_v1 import compile_latex
    from icm_v3 import IcmV3File
    r = compile_latex(formula)
    icm = os.path.join(work, "d.icm"); IcmV3File(name="d", records=r.result.records).save(icm)
    g = os.path.join(work, "grid")
    subprocess.run([sys.executable, os.path.join(ROOT, "tools", "project_assemble_v1.py"), "-s", "flex", "--icm", icm, "--output", g, "--top", "dsg_flex"], check=True, capture_output=True)
    fz.make(g, "dsg_flex"); bz.add(g, "dsg_flex"); info = sn.make(g, "dsg_flex")
    nb = info["total_bits"]
    assert nb <= 1920, "the image holds 1920 scan bits; this design has %d" % nb
    top_src = open(os.path.join(g, "dsg_flex_fz_scan.v")).read()
    ins = re.findall(r"input\s+wire\s*(?:\[\d+:0\])?\s*in_(\w+?)_data\b", top_src)
    outs = re.findall(r"output\s+wire\s*(?:\[\d+:0\])?\s*out_(\w+?)_data\b", top_src)
    assert len(outs) == 1 and ins, "expected one result port and at least one input port: %r %r" % (ins, outs)
    for f in ("accumulator_cell_v4sa.v", "latch_cell_v4sa.v"):
        shutil.copy(os.path.join(ROOT, "sub", "verilog", f), g)
    wname = "looped_%s_wrapper" % dname
    open(os.path.join(g, wname + ".v"), "w").write(gen_wrapper("dsg_flex_fz_scan", dname, ins, outs[0]))
    open(os.path.join(work, "board_uart_tx.v"), "w").write(bt.UART_V)
    open(os.path.join(work, "board_uart_rx.v"), "w").write(bm.UART_RX_V)
    top = "board_top_scan"
    open(os.path.join(work, top + ".v"), "w").write(top_text(cpb, tmo, mutant, nb, wname, dname))
    grid_files = sorted(os.path.join(g, f) for f in os.listdir(g) if f.endswith(".v") and f not in ("dsg_flex.v", "dsg_flex_fz.v"))
    meta = dict(formula=formula, name=dname, scan_bits=nb, cells=info["cells_in_chain"], inputs=ins, output=outs[0], args=r.args)
    return top, [os.path.join(work, "board_uart_tx.v"), os.path.join(work, "board_uart_rx.v"), os.path.join(work, top + ".v")] + grid_files, g, meta


def layout_id(scan_map):
    """A short fingerprint of the register layout of the scan chain (cell names, types, register names and widths, in order): two images belong together only if this is equal."""
    import hashlib
    canon = json.dumps([[c["cell"], c["type"], [[r["name"], r["bits"]] for r in c["regs"]]] for c in scan_map["chain"]], separators=(",", ":"))
    return hashlib.sha256(canon.encode()).hexdigest()[:16]


def main():
    import board_mutability2_v1 as m2
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--formula", default=FORMULA); ap.add_argument("--name", default=NAME)
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "board_tests_scan_latex"))
    ap.add_argument("--step", default="((z*z + 12345) & 0xFFFFFFFF) % 65521", help="the formula as a Python expression in z (the host's independent model)"); ap.add_argument("--z0", type=int, default=50000)
    ap.add_argument("--seed", type=int, default=1); ap.add_argument("--freq", type=float, default=27.0); ap.add_argument("--no-pnr", action="store_true")
    a = ap.parse_args()
    out = os.path.abspath(a.out); os.makedirs(out, exist_ok=True)
    work = tempfile.mkdtemp(dir=out, prefix="_work")
    try:
        top, files, g, meta = build_files(work, bt.CPB, 2097152, "none", a.formula, a.name)
        open(os.path.join(out, "scan_latex.v"), "w").write(open(os.path.join(work, top + ".v")).read())
        open(os.path.join(out, "scan_latex.cst"), "w").write(bm.cst_host())
        shutil.copy(os.path.join(out, "scan_latex.cst"), os.path.join(work, "scan_latex.cst"))
        shutil.copy(os.path.join(g, "SCAN_MAP.json"), os.path.join(out, "SCAN_MAP.json"))
        meta["layout"] = layout_id(json.load(open(os.path.join(g, "SCAN_MAP.json"))))
        json.dump(dict(name=a.name, formula=a.formula, z0=a.z0, step=a.step, layout=meta["layout"]), open(os.path.join(out, "design.json"), "w"), indent=1)
        print("design: %s | %d cells in the chain, %d scan bits | inputs %s -> output %s" % (meta["formula"], meta["cells"], meta["scan_bits"], meta["inputs"], meta["output"]))
        if not a.no_pnr:
            r = m2.pnr_report(work, "scan_latex", top, files, a.seed, a.freq, pack_to=out, meta=meta.setdefault("build", {}))
            print("place and route: Fmax %.1f MHz (target %s); used: %s" % (r["fmax_mhz"], a.freq, {k: "%d/%d" % (v["used"], v["available"]) for k, v in r["utilization"].items()}))
        json.dump(meta, open(os.path.join(out, "scan_latex.json"), "w"), indent=1)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
