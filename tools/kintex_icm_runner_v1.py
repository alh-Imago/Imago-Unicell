RUN_LIB = r'''# run_lib.tcl -- helpers for the ICM runner (OpenOCD). USER1 = IR 0x02. Every scan is NW words of 32 bits.
proc rn_xfer {words} {
    set f {}
    foreach v $words { lappend f 32 $v }
    return [drscan xc7.tap {*}$f]
}
proc rn_cmd_file {file} {
    set fh [open $file]
    set w [split [string trim [read $fh]]]
    close $fh
    return [rn_xfer $w]
}
proc rn_read {label} {
    set z {}
    for {set i 0} {$i < NW} {incr i} { lappend z 0 }
    puts "SNAP $label [rn_xfer $z]"
}
'''

