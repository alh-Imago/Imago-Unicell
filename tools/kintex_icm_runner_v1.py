def sig_of(words):
    s = 0
    for v in words:
        s = (((s << 1) | (s >> 31)) & 0xFFFFFFFF) ^ (v & 0xFFFFFFFF)
    return s


def collapse(words):
    """The runner counts a word when an exit's valid rises or its data changes (a HOLD exit never drops valid), so equal words in a row are one event. The VM's list gets the same rule."""
    out = []
    for v in words:
        if not out or out[-1] != v:
            out.append(v)
    return out


def run_streams2(recs, streams, exits, ticks=6000, settle=12):
    """tools/replay_card_icm_vm_v2.run_streams, additionally reading an ADDER exit (adder_data_valid / adder_out_buffer); the original only reads ram exits.
    settle (ledger #1267): clock the grid this many ticks BEFORE the first word is fed, as the original CORDIC test does (6 ticks) so that internal constant sources (the CORDIC's zero references) are in place; the card is fed long after power-up, so it always has this. Exit words seen during the settle are discarded."""
    import warnings
    import flex_grid_v2 as fg                       # ledger #1271: FlexGrid v2 (held constants), the flex generator's reading of a preloaded ram; flex_grid_v1 stays the proven reference
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        g = fg.FlexGrid2(recs)
    pos = {r.cell_id: (r.row, r.col) for r in recs}
    core = {r.cell_id: r.core for r in recs}
    todo = {k: list(v) for k, v in streams.items()}
    seen = {x: [] for x in exits}
    for _ in range(settle):
        g.tick()
    for x in exits:
        e = g.cells[pos[x]]
        if core[x] == "adder":
            e.adder_data_valid = False
        else:
            e.ram_data_valid = False
    for _ in range(ticks):
        for k, vals in todo.items():
            c = g.cells[pos[k]]
            if vals and not c.ram_data_valid and not g._pending.get(pos[k]):
                g.inject(*pos[k], vals.pop(0))
        g.tick()
        for x in exits:
            e = g.cells[pos[x]]
            if core[x] == "adder":
                if e.adder_data_valid:
                    seen[x].append(e.adder_out_buffer)
                    e.adder_data_valid = False
            elif e.ram_data_valid:
                seen[x].append(e.ram_data_reg)
                e.ram_data_valid = False
    return seen


def vm_expected(icm_path, entries, exits, vec):
    """What the VM's FlexGrid delivers at each exit for the given entry words. entries/exits: port names; vec: {entry name: [words]}."""
    import replay_card_icm_vm_v2 as rp
    import flexsub_icm_netlist_v1 as nl
    import flexsub_icm_flex_v1 as fx
    doc, recs, *_ = nl.extract(icm_path)
    byp = {}
    for r in recs:
        byp.setdefault(fx._pname(r.io_name, r.cell_id), []).append(r.cell_id)
    streams, ex = {}, []
    for n, _ in entries:
        assert len(byp.get(n, [])) == 1, f"entry {n}: cannot find exactly one cell with that name in the ICM"
        streams[byp[n][0]] = list(vec[n])
    for n, _ in exits:
        assert len(byp.get(n, [])) == 1, f"exit {n}: cannot find exactly one cell with that name in the ICM"
        ex.append(byp[n][0])
    seen = run_streams2(recs, streams, ex)
    return {n: collapse([int(v) & 0xFFFFFFFF for v in seen[ex[j]]]) for j, (n, _) in enumerate(exits)}


def default_vectors(entries, k):
    """Deterministic small vectors: 3 words per entry. Set 0: 10*(i+1), 1, 2; set 1: other values."""
    out = {}
    for i, (n, w) in enumerate(entries):
        base = [10 * (i + 1), 1, 2] if k == 0 else [7 * (i + 2), 100 + i, 3]
        out[n] = [v & ((1 << w) - 1) for v in base]
    return out


def tb_runs(entries, exits, lay, sets):
    L = []
    for r, (vec, exp) in enumerate(sets):
        L.append(f"        // run {r}")
        L.append("        cmd = {NB{1'b0}}; cmd[1:0] = 2'b11;")
        for i, (n, w) in enumerate(entries):
            L.append(f"        cmd[({lay['ecnt'] + i})*32 +: 16] = 16'd{len(vec[n])};")
            for k, v in enumerate(vec[n]):
                L.append(f"        cmd[({lay['ebuf'] + i * DEPTH + k})*32 +: 32] = 32'd{v};")
        L.append("        scan(cmd); #(20 * 6000); scan({NB{1'b0}});")
        for j, (n, w) in enumerate(exits):
            words = exp[n]
            b = lay["xst"] + 3 * j
            L.append(f"        check(rx[({b})*32 +: 16] === 16'd{len(words)}, \"run {r}: exit {n} word count\");")
            L.append(f"        check(rx[({b + 1})*32 +: 32] === 32'h{sig_of(words):08X}, \"run {r}: exit {n} signature\");")
            for k, v in enumerate(words[:DEPTH]):
                L.append(f"        check(rx[({lay['xbuf'] + j * DEPTH + k})*32 +: 32] === 32'd{v}, \"run {r}: exit {n} word {k}\");")
        fmt = f"run {r}: " + "".join(f"{n}=%0d " for n, _ in exits)
        args = "".join(f", rx[({lay['xst'] + 3 * j})*32 +: 16]" for j in range(len(exits)))
        L.append(f'        $display("{fmt}"{args});')
        for j, (n, _) in enumerate(exits):
            L.append(f'        $display("   exit {n} words: %0d %0d %0d %0d", rx[({lay["xbuf"] + j * DEPTH})*32 +: 32], rx[({lay["xbuf"] + j * DEPTH + 1})*32 +: 32], rx[({lay["xbuf"] + j * DEPTH + 2})*32 +: 32], rx[({lay["xbuf"] + j * DEPTH + 3})*32 +: 32]);')
    return "\n".join(L)


def wrap(design_dir, icm_path, man, out_dir=None, proj=None):
    """Turn the folder fig.generate() wrote (a flex design: module + cells) into an openXC7 project that runs on the Kintex card. Works in place on design_dir unless out_dir is given."""
    import flexsub_assemble_v1 as fa
    out = out_dir or design_dir
    rec = json.load(open(os.path.join(design_dir, "ASSEMBLY.json")))
    dut_top = rec["top"]
    proj = proj or f"k7_{dut_top}"[:60]
    ports_path = os.path.join(design_dir, dut_top + ".v")
    top, entries, exits = parse_ports(ports_path)
    lay = layout(len(entries), len(exits))
    if out != design_dir:
        os.makedirs(out, exist_ok=True)
    # design files -> .sv (the openXC7 flow reads .sv as SystemVerilog), the design's .ys (a Gowin script) is not needed
    src_files = [f for f in rec["files"] if f.endswith(".v")]
    sv = []
    for f in src_files:
        n = os.path.splitext(f)[0] + ".sv"
        shutil.copy2(os.path.join(design_dir, f), os.path.join(out, n))
        sv.append(n)
        if out == design_dir:
            os.remove(os.path.join(design_dir, f))
    for f in os.listdir(design_dir):
        if out == design_dir and f.endswith((".ys", ".v")) and f != "ASSEMBLY.json":
            os.remove(os.path.join(design_dir, f))
    open(os.path.join(out, proj + ".v"), "w").write(gen_top(proj, top, entries, exits, lay))
    open(os.path.join(out, proj + ".xdc"), "w").write(fa.generate_xdc(fa.load_man_flexsub(man) if isinstance(man, str) else man))
    mandict = fa.load_man_flexsub(man) if isinstance(man, str) else man
    mk = fa.generate_openxc7_makefile(mandict, proj, sv)
    mk = mk.replace(f"TOP_MODULE = {proj}", "TOP_MODULE = top")
    mk += "\nsim:\n\tiverilog -g2012 -o sim.vvp tb_%s.v %s.v %s && vvp sim.vvp\n" % (proj, proj, " ".join(sv))
    open(os.path.join(out, "Makefile"), "w").write(mk)
    # vectors and the VM's answers
    sets, expected = [], {}
    for k in range(2):
        vec = default_vectors(entries, k)
        exp = vm_expected(icm_path, entries, exits, vec)
        fn = "vectors.txt" if k == 0 else "vectors2.txt"
        open(os.path.join(out, fn), "w").write("# words fed to each entry (decimal or 0x hex), at most %d per entry\n" % DEPTH + "\n".join(f"{n}: " + " ".join(str(v) for v in vec[n]) for n, _ in entries) + "\n")
        expected[fn] = {"exits": {n: {"words": exp[n]} for n, _ in exits}}
        sets.append((vec, exp))
    json.dump(expected, open(os.path.join(out, "expected.json"), "w"), indent=1)
    design = {"proj": proj, "dut": top, "entries": [{"name": n, "width": w} for n, w in entries], "exits": [{"name": n, "width": w} for n, w in exits],
              "depth": DEPTH, "layout": lay, "nw": lay["nw"], "source_icm": os.path.basename(icm_path)}
    json.dump(design, open(os.path.join(out, "design.json"), "w"), indent=1)
    tb = TB.replace("PROJECT", proj).replace("NWV", str(lay["nw"])).replace("NEV", str(len(entries))).replace("NXV", str(len(exits))).replace("DEPTHV", str(DEPTH)).replace("MAGIC", str(MAGIC))
    tb = tb.replace("RUNS", tb_runs(entries, exits, lay, sets)).replace("{NB{", "{NB{")
    open(os.path.join(out, f"tb_{proj}.v"), "w").write(tb)
    open(os.path.join(out, "run_lib.tcl"), "w").write(RUN_LIB.replace("NW", str(lay["nw"])))
    for fn, txt in (("run_vectors.sh", SH_RUN), ("run_read.sh", SH_READ), ("make_cmd.py", MAKE_CMD), ("decode_run.py", DECODE_RUN)):
        open(os.path.join(out, fn), "w").write(txt)
    shutil.copy(os.path.join(ROOT, "fpga", "kintex7_tests", "k7_freeze_load", "k7_ft232h.cfg"), os.path.join(out, "k7_ft232h.cfg"))
    sim = run_sim(out, proj, sv)
    open(os.path.join(out, "README.md"), "w").write(readme(proj, icm_path, mandict, entries, exits, lay, sim))
    kit = {"title": f"{proj} -- ICM design {os.path.basename(icm_path)} on {mandict['card_id']}, fed and read over JTAG", "card_id": mandict["card_id"], "flow": "openxc7",
           "startup": mandict["build"].get("startup"), "runner": True, "sim": sim["verdict"]}
    json.dump(kit, open(os.path.join(out, "kit.json"), "w"), indent=1)
    rec.update({"sim_vs_vm": sim, "flow": "openxc7", "runner": "tools/kintex_icm_runner_v1.py", "project": proj, "files": sv + [proj + ".v", proj + ".xdc", "Makefile", "design.json", "expected.json", "vectors.txt", "vectors2.txt"]})
    json.dump(rec, open(os.path.join(out, "ASSEMBLY.json"), "w"), indent=2)
    return {"proj": proj, "entries": entries, "exits": exits, "layout": lay, "sim": sim}


def run_sim(out, proj, sv):
    """Simulate the project's own testbench (iverilog) and say whether the runner agrees with the VM on both vector sets. Skipped when iverilog is missing or UNICELL_RUNNER_SIM=0."""
    import subprocess
    if os.environ.get("UNICELL_RUNNER_SIM", "1") == "0" or not shutil.which("iverilog"):
        return {"verdict": "not run", "why": "iverilog missing or UNICELL_RUNNER_SIM=0"}
    exe = os.path.join(out, "sim.vvp")
    c = subprocess.run(["iverilog", "-g2012", "-o", exe, f"tb_{proj}.v", f"{proj}.v"] + sv, cwd=out, capture_output=True, text=True)
    if c.returncode:
        return {"verdict": "did not compile", "why": c.stderr[:300]}
    try:
        r = subprocess.run(["vvp", exe], cwd=out, capture_output=True, text=True, timeout=600)
    finally:
        if os.path.exists(exe):
            os.remove(exe)
    tail = r.stdout.strip().splitlines()
    ok = bool(tail) and "PASS" in [x.strip() for x in tail]
    fails = [x.strip() for x in tail if x.strip().startswith("FAIL:")][:6]
    return {"verdict": "PASS" if ok else "DISAGREES WITH THE VM", "fails": fails}


