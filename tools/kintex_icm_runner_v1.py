#!/usr/bin/env python3
"""kintex_icm_runner_v1.py -- wraps a generated FLEX ICM design (tools/flexsub_icm_flex_v1.py output) for the Kintex card, ledger #1259.

The generated design is only a module: clk, rst, cfg_valid and, per entry, in_<n>_data / _valid / _ack, per exit out_<n>_data / _valid / _ack (valid/ready handshakes).
This adds what a card needs: the card's pins (CLK, LED0-2) and a power-up reset, the reset and configuration sequence, and a JTAG USER1 register (BSCANE2, as in the freeze kits) through which
  * the host writes the words to feed each entry (up to DEPTH per entry) and starts a run,
  * the host reads back what every exit delivered (count, signature, clock of the last word, the first DEPTH words) and a clock counter.
The expected answers come from the VM (FlexGrid) at folder-creation time, so the results window can compare card and VM word for word.

Scan (32-bit words; the same length in both directions, NW words):
  read  : w0 'RUN1' (0x52554E31)  w1 clock count  w2 {rst_run, started, 6'b0, NE[7:0], DEPTH[7:0], NX[7:0]}  w3 run number
          w4..          per entry: fed count [15:0] | loaded count [31:16]
          then          per exit: count, signature, clock of the last word
          then          exit buffers (NX x DEPTH words)      then  entry buffers read back as zero
  write : w0 {valid=bit1, go=bit0}   w4..  per entry: number of words to feed [15:0]     (exit regions ignored)      entry buffers (NE x DEPTH words) at the same place as in the read layout
"""
