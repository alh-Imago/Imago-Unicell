MAKE_CMD = '''#!/usr/bin/env python3
"""make_cmd.py VECTORS OUT -- turn a vectors file (lines `entry: w w w ...`, decimal or 0x hex) into the command words for the runner (written to OUT as hex words)."""
import json
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, "design.json")))
lay, depth, nw = d["layout"], d["depth"], d["nw"]
words = {}
for line in open(sys.argv[1]):
    line = line.split("#")[0].strip()
    if not line:
        continue
    name, rest = line.split(":", 1)
    words[name.strip()] = [int(x, 0) & 0xFFFFFFFF for x in rest.split()]
names = [e["name"] for e in d["entries"]]
bad = [n for n in words if n not in names]
if bad:
    sys.exit("unknown entry name(s) %s; this design's entries are: %s" % (bad, ", ".join(names)))
w = [0] * nw
w[0] = 3
for i, n in enumerate(names):
    ws = words.get(n, [])
    if len(ws) > depth:
        sys.exit("entry %s: %d words, at most %d fit" % (n, len(ws), depth))
    w[lay["ecnt"] + i] = len(ws)
    for k, v in enumerate(ws):
        w[lay["ebuf"] + i * depth + k] = v
open(sys.argv[2], "w").write(" ".join("0x%08x" % x for x in w) + "\\n")
print("command written: %s" % ", ".join("%s=%d words" % (n, len(words.get(n, []))) for n in names))
'''

