#!/usr/bin/env python3
"""tools/board_loops_v1.py -- ledger #1118: SELF-CHECKING bitstreams for the Tang Nano 20K that put the ring-controlled loops on the real card (Alan 12 Oct: "create the streams for each and I will test them directly").
Same package shape and tooling as tools/board_tests_v1.py (#1023): one line over the USB serial port (115200), LED1 = PASS, LED2 = FAIL, LED3 = finished, LED0 = heartbeat; run_all.sh / run_all.bat / board_run.py.

Each LOOP test: after the card boots, z0 is injected once; the wrapper captures the ring's results and compares each with the expected word (the model's, which the generated RTL was proven equal to); the ring must stop after
exactly N = 20 results and stay quiet (and, where the design has the flag, `ring_stopped` must be high); then ONE release is given; the flex and sub rings then run another N = 20 results (a release opens a new window of N, measured in #1110/#1111) and stop again; the std ring gives exactly one more (the 21st). All stay on the model.
Tests: flex_ring (generated flex RTL, `--ring-steps`), sub_ring (generated SUB RTL), std_ring (standalone v4 shells, counter + branch + join-gate), mixed_pipe (flex -> bridge -> SUB -> bridge -> flex, x + 1239; a pipeline, not a loop).
Report line: UCT <name> res=P|F n=<results> e=<expected: 40 for flex and sub, 21 for std> bad=<wrong or extra> to=<timeout> n0=<results at the release, must be 14 hex = 20> st=<stop flag seen at release and at the end> last=<cycle of the last result> sig=<checksum> w=<first 8 words>.

  python3 tools/board_loops_v1.py [--out DIR] [--only a,b] [--seed N] [--no-pnr]"""
import argparse, json, os, re, shutil, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
for p in (HERE, os.path.join(ROOT, "nano"), os.path.join(ROOT, "nano", "examples")):
    sys.path.insert(0, p)
import board_tests_v1 as bt
import looped_cordic_v1 as L
import standalone_grid_v1 as SG
import verilog_deps_v1 as vd

N = 20
RF = 20   # a flex release restarts a window of N more results (measured, tests/vm/test_flex_ring_v1.py)
RS = 20   # the sub ring: checked in simulation by this tool before anything is written
KEEP = 8
ASM = [sys.executable, os.path.join(ROOT, "tools", "project_assemble_v1.py")]
MAN = os.path.join(ROOT, "docs", "man", "tang-nano-20k.man.json")
ICM = os.path.join(ROOT, "nano", "examples", "looped_cordic_v1_closed_flex.icm-hier.json")
MIXED = os.path.join(ROOT, "nano", "examples", "mixed_flex_sub_flex_v1.icm-hier.json")

DUT = {
 "flex": ("    wire [31:0] od; wire ov; wire iack, stopped;\n"
          "    reg inj = 1'b0; always @(posedge clk) begin if (started && t == 32'd30) inj <= 1'b1; if (inj && iack) inj <= 1'b0; end\n"
          "    DUTTOP dut (.clk(clk), .rst(rst), .cfg_valid(cfg_valid), .in_z_input_data(32'd%(z0)d), .in_z_input_valid(inj), .in_z_input_ack(iack),\n"
          "                .out_result_data(od), .out_result_valid(ov), .out_result_ack(1'b1), .ring_release(relp), .ring_stopped(stopped));\n"
          "    wire cap = ov; wire stop_now = stopped;\n"),
 "sub":  ("    wire [31:0] od; wire ov; wire stopped, held;\n"
          "    reg inj = 1'b0; always @(posedge clk) begin inj <= 1'b0; if (started && t == 32'd60) inj <= 1'b1; end\n"
          "    DUTTOP dut (.clk(clk), .rst(rst), .cfg_valid(cfg_valid), .in_z_input_data(32'd%(z0)d), .in_z_input_valid(inj),\n"
          "                .out_result_data(od), .out_result_valid(ov), .ring_release(relp), .ring_held(held), .ring_stopped(stopped));\n"
          "    wire cap = ov; wire stop_now = stopped;\n"),
 "std":  ("    wire [31:0] od; wire tv;\n"
          "    wire zp = started && (t == 32'd44);\n"
          "    DUTTOP dut (.clk(clk), .rst(rst), .ld_valid(zp | relp), .ld_cell(relp ? 16'd%(rel)d : 16'd%(zi)d), .ld_word(relp ? 32'd0 : 32'd%(z0)d), .tap_valid(tv), .tap_data(od),\n"
          "                .ext_arrived(%(ne)d'b0), .ext_ack_in(%(ne)d'b0), .ext_data_in({%(nb)d{1'b0}}), .ext_fire(), .ext_data_out());\n"
          "    wire cap = tv; wire stop_now = 1'b1;   // no stop flag reaches a pin in this build: quiet after exactly N results is the check\n"),
}


def loop_wrapper(name, style, params, dut_top, exp, cpb, settle, timeout):
    n_exp = len(exp)
    h = ["// board_top_%s.v -- GENERATED by tools/board_loops_v1.py (ledger #1118); do not hand-edit." % name, "`default_nettype none", "`timescale 1ns / 1ps",
         "module board_top_%s #(parameter integer CPB = %d, parameter integer SETTLE = %d, parameter integer TIMEOUT = %d) (" % (name, cpb, settle, timeout),
         "    input wire BOARD_CLK, output wire UART_TX, output wire LED0_N, output wire LED1_N, output wire LED2_N, output wire LED3_N);",
         "wire clk = BOARD_CLK;",
         "reg [7:0] por_cnt = 8'h00; wire rst = (por_cnt != 8'hFF); always @(posedge clk) if (rst) por_cnt <= por_cnt + 8'd1;",
         "reg [3:0] cfg_sr = 4'hF; always @(posedge clk) if (!rst) cfg_sr <= {cfg_sr[2:0], 1'b0};",
         "wire cfg_valid = !rst && cfg_sr[3] && !cfg_sr[2];",
         "reg [5:0] wait_cnt = 6'd0; reg started = 1'b0;",
         "always @(posedge clk) if (!rst && !cfg_sr[3] && !started) begin wait_cnt <= wait_cnt + 6'd1; if (wait_cnt == 6'd8) started <= 1'b1; end",
         "reg [31:0] t = 32'd0; always @(posedge clk) if (started) t <= t + 32'd1;",
         "reg done = 1'b0; reg relp = 1'b0;"]
    h.append((DUT[style] % params).replace("DUTTOP", dut_top))
    h.append("reg [31:0] expm [0:%d]; initial begin " % n_exp + " ".join("expm[%d] = 32'h%08X;" % (j, v & 0xFFFFFFFF) for j, v in enumerate(exp)) + " expm[%d] = 32'h0; end" % n_exp)
    h.append("reg [15:0] cnt = 16'd0, bad = 16'd0, n0 = 16'd0; reg [31:0] sig = 32'd0, cyc = 32'd0, last = 32'd0, quiet = 32'd0; reg timed_out = 1'b0, st0 = 1'b0, st1 = 1'b0, phase = 1'b0;")
    for j in range(KEEP):
        h.append("reg [31:0] w%d = 32'd0;" % j)
    h.append("wire [15:0] want = 16'd%d;" % n_exp)
    h.append("always @(posedge clk) begin")
    h.append("    relp <= 1'b0;")
    h.append("    if (started && !done) begin")
    h.append("        cyc <= cyc + 32'd1; quiet <= quiet + 32'd1;")
    h.append("        if (cap) begin")
    h.append("            cnt <= cnt + 16'd1; last <= cyc; quiet <= 32'd0; sig <= {sig[30:0], sig[31]} ^ od;")
    h.append("            if (cnt >= want || od != expm[cnt]) bad <= bad + 16'd1;")
    for j in range(KEEP):
        h.append("            if (cnt == 16'd%d) w%d <= od;" % (j, j))
    h.append("        end")
    h.append("        if (!phase && cnt >= 16'd%d && quiet >= SETTLE) begin phase <= 1'b1; n0 <= cnt; st0 <= stop_now; relp <= 1'b1; quiet <= 32'd0; end" % N)
    h.append("        if (phase && cnt >= 16'd%d && quiet >= SETTLE) begin done <= 1'b1; st1 <= stop_now; end" % n_exp)
    h.append("        if (cyc >= TIMEOUT) begin done <= 1'b1; timed_out <= (cnt < want); end")
    h.append("    end")
    h.append("end")
    h.append("wire pass = done && !timed_out && (cnt == want) && (bad == 16'd0) && (n0 == 16'd%d) && st0 && st1;" % N)
    items = [("s", "UCT " + name + " res="), ("c", "pass ? 8'h50 : 8'h46"), ("s", " n="), ("h", "cnt", 4), ("s", " e="), ("h", "want", 4), ("s", " bad="), ("h", "bad", 4), ("s", " to="), ("h", "{15'd0, timed_out}", 1),
             ("s", " n0="), ("h", "n0", 4), ("s", " st="), ("h", "{2'd0, st0, st1}", 1), ("s", " last="), ("h", "last", 8), ("s", " sig="), ("h", "sig", 8), ("s", " w=")]
    for j in range(KEEP):
        if j:
            items.append(("s", ","))
        items.append(("h", "w%d" % j, 8))
    items.append(("s", "\r\n"))
    body, idx = [], 0
    for it in items:
        if it[0] == "s":
            for ch in it[1]:
                body.append("        10'd%d: msg_byte = 8'h%02X;" % (idx, ord(ch))); idx += 1
        elif it[0] == "c":
            body.append("        10'd%d: msg_byte = %s;" % (idx, it[1])); idx += 1
        else:
            _, expr, nd = it
            for d in range(nd):
                body.append("        10'd%d: msg_byte = hexch((%s >> %d) & 4'hF);" % (idx, expr, (nd - 1 - d) * 4)); idx += 1
    h.append("function [7:0] hexch(input [3:0] v); hexch = (v < 4'd10) ? (8'h30 + v) : (8'h41 + v - 4'd10); endfunction")
    h.append("reg [9:0] mi = 10'd0;")
    h.append("function [7:0] msg_byte(input [9:0] i); begin case (i)")
    h += body
    h.append("        default: msg_byte = 8'h20; endcase end endfunction")
    h.append("localparam integer MSGLEN = %d;" % idx)
    h.append("wire tx_busy; reg tx_start = 1'b0; reg [7:0] tx_data = 8'h00; reg [31:0] gapc = 32'd0; reg [1:0] ps = 2'd0;")
    h.append("board_uart_tx #(.CPB(CPB)) utx (.clk(clk), .start(tx_start), .data(tx_data), .tx(UART_TX), .busy(tx_busy));")
    h += ["always @(posedge clk) begin", "    tx_start <= 1'b0;", "    case (ps)",
          "        2'd0: if (done) begin mi <= 10'd0; ps <= 2'd1; end",
          "        2'd1: if (!tx_busy && !tx_start) begin tx_data <= msg_byte(mi); tx_start <= 1'b1; ps <= 2'd2; end",
          "        2'd2: if (tx_busy) begin if (mi == MSGLEN - 1) begin gapc <= 32'd0; ps <= 2'd3; end else begin mi <= mi + 10'd1; ps <= 2'd1; end end",
          "        2'd3: if (!tx_busy) begin gapc <= gapc + 32'd1; if (gapc >= SETTLE * 4) ps <= 2'd0; end", "    endcase", "end",
          "reg [23:0] hb = 24'd0; always @(posedge clk) hb <= hb + 24'd1;",
          "assign LED0_N = ~hb[23]; assign LED1_N = ~pass; assign LED2_N = ~(done && !pass); assign LED3_N = ~done;", "endmodule"]
    return "\n".join(h) + "\n"


def assemble(args, gen):
    r = subprocess.run(ASM + args + ["--output", gen], capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError("generator: %s%s" % (r.stderr[-500:], r.stdout[-300:]))
    if os.path.exists(os.path.join(gen, "ASSEMBLY_mixed.json")):   # a mixed design: the top is `--top`, the files are everything the regions and the bridge wrote
        return args[args.index("--top") + 1], [os.path.join(gen, f) for f in sorted(os.listdir(gen)) if f.endswith(".v")]
    rec = json.load(open(os.path.join(gen, "ASSEMBLY.json")))
    return rec["top"], [os.path.join(gen, f) for f in rec["files"] if f.endswith(".v")]


def tests(work):
    """-> list of (name, what, kind, dut_top, source files, params, expected words, stream-wrapper args)"""
    mm = lambda r: L.model(N + r)
    out = []
    g = os.path.join(work, "gen_flex"); top, f = assemble(["-s", "flex", "--allow-rings", "--ring-steps", str(N), "--icm", ICM, "--man", MAN, "--top", "ring_flex"], g)
    out.append(("flex_ring", "looped CORDIC ring in generated flex RTL: stops after exactly %d results; one release lets it run %d more and stop again" % (N, RF), "loop", top, f, ("flex", {"z0": L.Z0 & 0xFFFFFFFF}), mm(RF)))
    g = os.path.join(work, "gen_sub"); top, f = assemble(["-s", "sub", "--allow-rings", "--ring-steps", str(N), "--icm", ICM, "--top", "ring_sub"], g)
    out.append(("sub_ring", "looped CORDIC ring in generated SUB RTL (fixed 1-clock cells): stops after exactly %d results; one release lets it run %d more and stop again" % (N, RS), "loop", top, f, ("sub", {"z0": L.Z0 & 0xFFFFFFFF}), mm(RS)))
    recs = L.build_records(join=True, ring_laps=N)
    inp = next(r for r in recs if r.io_name == "z_input"); rel = next(r for r in recs if r.io_name == "ring_release")
    tap = next(r.cell_id for r in recs if r.cell_id.endswith("fb19"))
    g = os.path.join(work, "gen_std"); meta = SG.generate(recs, g, "std_grid", tap)
    idx = {c["cell_id"]: c["index"] for c in meta["cells"]}
    ne = len(meta["ext"])
    deps = set()
    for mod in meta["shells"]:
        deps |= set(vd.deps(mod, [g, os.path.join(ROOT, "fpga", "verilog")]))
    out.append(("std_ring", "looped CORDIC ring on standalone v4 shells (counter + branch + join-gate in the ring): stops after exactly %d results; one release gives exactly one more" % N, "loop", "std_grid",
                [os.path.join(g, "std_grid.v")] + sorted(deps), ("std", {"z0": L.Z0 & 0xFFFFFFFF, "zi": idx[inp.cell_id], "rel": idx[rel.cell_id], "ne": ne, "nb": 32 * ne}), mm(1)))
    g = os.path.join(work, "gen_mix"); top, f = assemble(["-s", "flex", "--icm", MIXED, "--top", "mix"], g)
    xs = [5, 100, -7, 12345, 0, 77, 1000, 31]
    out.append(("mixed_pipe", "flex -> bridge -> SUB -> bridge -> flex pipeline, x + 1239 (random exit stalls)", "stream", top, f, None, [(x + 1239) & 0xFFFFFFFF for x in xs]))
    return out, xs


def build(name, what, kind, top_mod, files, spec, exp, xs, out, pnr, seed, work):
    wd = os.path.join(work, "w_" + name); shutil.rmtree(wd, ignore_errors=True); os.makedirs(wd)
    open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
    top = "board_top_" + name
    if kind == "loop":
        src = loop_wrapper(name, spec[0], spec[1], top_mod, exp, bt.CPB, bt.SETTLE, bt.TIMEOUT)
    else:
        src = bt.wrapper(name, top_mod, {"x_in": xs}, "y_out", exp, False, True, bt.CPB, bt.SETTLE, bt.TIMEOUT)
    open(os.path.join(wd, top + ".v"), "w").write(src)
    files = [os.path.join(wd, "board_uart_tx.v"), os.path.join(wd, top + ".v")] + list(files)
    sim = bt.simulate(wd, name, files)
    line = next((l for l in sim.splitlines() if l.startswith("UCT")), "")
    if " res=P " not in line + " ":
        raise RuntimeError("%s: the wrapper FAILED in simulation (not written): %s" % (name, sim[-600:]))
    res = dict(name=name, what=what, expected=[int(v) & 0xFFFFFFFF for v in exp], sim_line=line.strip())
    open(os.path.join(out, name + ".cst"), "w").write(bt.cst())
    shutil.copy(os.path.join(wd, top + ".v"), os.path.join(out, name + ".v"))
    if pnr:
        rel = []                       # yosys here cannot open an absolute path under /tmp: work from the folder with relative names
        for f in files:
            if not f.startswith(wd + os.sep):
                shutil.copy(f, os.path.join(wd, os.path.basename(f)))
            rel.append(os.path.basename(f))
        s = subprocess.run(["yosys", "-q", "-p", "read_verilog -sv %s; hierarchy -top %s; synth_gowin -top %s -nowidelut -json %s.json" % (" ".join(rel), top, top, name)], cwd=wd, capture_output=True, text=True, timeout=3000)
        if s.returncode:
            raise RuntimeError("%s: yosys: %s" % (name, s.stderr[-500:]))
        shutil.copy(os.path.join(out, name + ".cst"), os.path.join(wd, name + ".cst"))
        p = subprocess.run(["yowasp-nextpnr-himbaechel-gowin", "--device", bt.DEVICE, "--vopt", "family=GW2A-18C", "--vopt", "cst=%s.cst" % name, "--seed", str(seed), "--json", name + ".json",
                            "--write", name + "_r.json", "--report", name + "_rep.json", "--freq", "27"], cwd=wd, capture_output=True, text=True, timeout=6000)
        if p.returncode:
            raise RuntimeError("%s: nextpnr: %s" % (name, (p.stdout[-400:] + p.stderr[-600:])))
        rep = json.load(open(os.path.join(wd, name + "_rep.json")))
        fmax = rep["fmax"]["clk"]["achieved"] if "clk" in rep["fmax"] else min(v["achieved"] for v in rep["fmax"].values())
        u = rep["utilization"]
        res.update(fmax_mhz=round(fmax, 1), lut4=u["LUT4"]["used"], dff=u["DFF"]["used"])
        if fmax < 27:
            raise RuntimeError("%s: timing NOT met at 27 MHz (Fmax %.1f)" % (name, fmax))
        g = subprocess.run(["gowin_pack", "-d", bt.DEVICE, "-o", os.path.join(out, name + ".fs"), "-s", os.path.join(wd, name + ".cst"), name + "_r.json"], cwd=wd, capture_output=True, text=True)
        if g.returncode:
            raise RuntimeError("%s: gowin_pack: %s" % (name, g.stderr[-400:]))
    json.dump(res, open(os.path.join(out, name + ".json"), "w"), indent=1)
    return res


def readme(results):
    L_ = ["# Tang Nano 20K: the ring-controlled loops on the card (ledger #1118)\n",
          "Each `<name>.fs` is a self-checking bitstream. Run `./run_all.sh` (Linux, needs `openFPGALoader`, root or the dialout group) or `run_all.bat` (Windows, needs `pip install pyserial`); the results land in `board_results.txt` / `.csv`. "
          "LED1 on = PASS, LED2 on = FAIL, LED3 on = finished, LED0 = heartbeat (active low). Bitstreams go to SRAM only. Same tooling and serial settings as the #1023 package (`fpga/board_tests/`); the board stops answering after about 5 loads in a row, so `run_all.sh` asks for a replug every 4.\n",
          "## What each loop test does\n", "z0 is injected once. The ring must give exactly **20** results, each equal to the model's word, stay quiet, and (flex and sub) show `ring_stopped`. One **release** is then given: flex and sub run another **20** (a release opens a new window of N) and stop again, std gives exactly **one more** (the 21st). "
          "`mixed_pipe` is a pipeline, not a loop: 8 words through flex, bridge, SUB, bridge, flex, each x + 1239, with random exit stalls.\n",
          "## The line\n", "`UCT <name> res=P|F n=<results> e=<expected, hex: 0028 = 40 for flex and sub, 0015 = 21 for std> bad=<wrong or extra> to=<timeout> n0=<results when the release was given: 0014 = 20> st=<bit1 stopped at release, bit0 stopped at the end: 3 = both> last=<cycle of the last result> sig=<checksum> w=<first 8 words>` (all hex). "
          "`std_ring` has no stop flag on a pin, so its `st` only means 'quiet after exactly 20'.\n",
          "## The tests\n", "| test | what it proves | LUT4 | FF | Fmax (MHz, 27 needed) |", "|---|---|---|---|---|"]
    for r in results:
        L_.append("| `%s` | %s | %s | %s | %s |" % (r["name"], r["what"], r.get("lut4", ""), r.get("dff", ""), r.get("fmax_mhz", "")))
    L_ += ["\n## Honest limits\n", "- Each passed in simulation (UART text decoded) and closed timing at 27 MHz in place-and-route; none has been on the board yet.",
           "- 27 MHz only (no PLL): a correctness test on silicon, not a speed test. Fmax is nextpnr's static figure.",
           "- The expected words are the model's (`looped_cordic_v1.model`); the generated RTL and the grids were proven equal to it in simulation (#1110, #1111, #1116, #1117).",
           "- Only 20 + 1 results are checked; the long-run behaviour (hundreds of steps) was checked in simulation, not here.\n"]
    return "\n".join(L_)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "board_tests_loops"))
    ap.add_argument("--only", default="")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--no-pnr", action="store_true")
    a = ap.parse_args()
    a.out = os.path.abspath(a.out)
    os.makedirs(a.out, exist_ok=True)
    only = [x for x in a.only.split(",") if x]
    work = tempfile.mkdtemp(prefix="bloops_")
    lst, xs = tests(work)
    results = []
    for name, what, kind, top_mod, files, spec, exp in lst:
        if only and name not in only:
            continue
        print("== " + name, flush=True)
        r = build(name, what, kind, top_mod, files, spec, exp, xs, a.out, not a.no_pnr, a.seed, work)
        print("   ok: %s   %s LUT4  Fmax %s" % (r["sim_line"], r.get("lut4", "-"), r.get("fmax_mhz", "-")), flush=True)
        results.append(r)
    for fn, txt in (("run_all.bat", bt.BAT), ("board_run.py", bt.RUNPY), ("board_collect.py", bt.COLLECT), ("run_one.sh", bt.ONE), ("run_all.sh", bt.SH)):
        txt = txt.replace("to=[01] last=", "to=[01](?: n0=[0-9A-F]{4} st=[0-9A-F])? last=").replace("to=\\d last=", "to=\\d(?: n0=[0-9A-F]{4} st=[0-9A-F])? last=")    # ledger #1119: the loop tests' line has n0= and st= before last=; the #1023 parser rejected it
        p = os.path.join(a.out, fn)
        open(p, "w", newline="\r\n" if fn.endswith(".bat") else "\n").write(txt)
        if fn.endswith(".sh"):
            os.chmod(p, 0o755)
    open(os.path.join(a.out, "README.md"), "w").write(readme(results) + "\n## If a test prints nothing\nTry one at a time with a replug between: unplug the USB cable, plug it back in, wait 20 s, then `sudo env ONLY=\"mixed_pipe\" ./run_all.sh /dev/ttyUSB1`. If it is still silent, keep the `raw/` folder (`raw/<name>.bin`, `.loader.txt`, `.ports`) and send it.\n")
    print("wrote %d tests to %s" % (len(results), a.out))


if __name__ == "__main__":
    main()
