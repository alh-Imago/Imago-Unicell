#!/usr/bin/env python3
"""Kintex array design generator (4 Nov 2026, Alan 22:30 'limiting it to the small 7x7 array sizes ... real sizing of the individual patterns').
One hex pattern array + the byte-port frame (hexn_frame_v4) + the JTAG bridge (hexn_jtag_bridge_v1, USER chain 2) for the YPCB-00338-1P1 (XC7K480T). Pins: SYS_CLK and led[2:0] only.
  hexn_arr_core  clk, rx_d, rx_v, tx_dout, tx_s, tx_b, led  -- frame v4 around the pattern; this is what the simulation drives (tests/hexn_bytecard_tb.v)
  hexn_arr       SYS_CLK, led[2:0]                            -- the board top: bridge + core
usage: hexn_kxarr_v1.py sim   REF.json OUTDIR     -> OUTDIR/src/*.v for iverilog (no bridge: BSCANE2 is not simulated)
       hexn_kxarr_v1.py build REF.json BUILDDIR   -> BUILDDIR/gen_00_hexn_arr.v for the ypcb build flow (prebuild of fpga/ypcb/hexn_arr)
       hexn_kxarr_v1.py top   -                   -> prints the static board top (fpga/ypcb/hexn_arr/hexn_arr.v)
Nothing here touches a board."""
import json, os, shutil, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); sys.path.insert(0, HERE)
import hexn_pattern_gen_hex_v1 as P
SV = os.path.join(ROOT, "sub", "verilog"); RV = os.path.join(ROOT, "rtl")
def frame_files(frame="v4"): return [os.path.join(SV, f) for f in ("hexn_cross_v2.v", "hexn_xtop_v2.v", "hexn_frame_%s.v" % frame)]
FRAME_FILES = frame_files()


def chain_len(ref): return P.chain_len(ref)


def core_text(ref, frame="v4"):
    return ("`default_nettype none\n// hexn_arr_core for hex pattern %s (ID %s), generated by tools/hexn_kxarr_v1.py; do not edit.\n"
            "module hexn_arr_core (input wire clk, input wire [7:0] rx_d, input wire rx_v, output wire [7:0] tx_dout, output wire tx_s, input wire tx_b, output wire [5:0] led);\n"
            "    hexn_frame_%s #(.ROWS(%d), .CHAIN_BITS(%d), .PATTERN_ID(32'h%s)) f (.clk(clk), .rx_d(rx_d), .rx_v(rx_v), .tx_dout(tx_dout), .tx_s(tx_s), .tx_b(tx_b), .led(led));\n"
            "endmodule\n") % (ref["name"], ref["pattern_id_hex"], frame, ref["rows"], chain_len(ref), ref["pattern_id_hex"])


def top_text():
    """the board top; the same for every pattern (the pattern is inside hexn_arr_core), so it lives as a static file in fpga/ypcb/hexn_arr/hexn_arr.v"""
    return ("`default_nettype none\n// hexn_arr on the YPCB-00338-1P1: JTAG bridge on USER2 (IR 0x03) + hexn_arr_core (frame v4 around one hex pattern). Same for every pattern. Written by tools/hexn_kxarr_v1.py top; do not edit.\n"
            "module hexn_arr (input SYS_CLK, output [2:0] led);\n"
            "    reg [31:0] count = 0; always @(posedge SYS_CLK) count <= count + 1;\n"
            "    wire [7:0] rx_d, tx_d; wire rx_v, tx_s, tx_b; wire [5:0] cled;\n"
            "    hexn_jtag_bridge_v1 #(.CHAIN(2), .FSPACING(128)) br (.clk(SYS_CLK), .rst(1'b0), .rx_d(rx_d), .rx_v(rx_v), .tx_d(tx_d), .tx_s(tx_s), .tx_b(tx_b));\n"
            "    hexn_arr_core core (.clk(SYS_CLK), .rx_d(rx_d), .rx_v(rx_v), .tx_dout(tx_d), .tx_s(tx_s), .tx_b(tx_b), .led(cled));\n"
            "    reg txseen = 0; always @(posedge SYS_CLK) if (tx_s) txseen <= ~txseen;\n"
            "    assign led = {txseen, ~&cled[2:0], count[25]};\nendmodule\n")


def no_ram(text, which="1"):
    """debug variant (HEXN_NORAM): the same RTL with the small memories made of plain flip-flops (which = 'ram'), the config shift chains kept as flip-flops (which = 'srl'), or both ('1'), so the Kintex flow infers no RAM32M and/or no SRL16E (found 5 Nov 2026: with both removed the 5x5 works on the card, with them it does not). The source files are NOT changed; this rewrites the text that goes into the build file."""
    pairs = []
    if which in ("1", "srl"): pairs.append(("reg [CW-1:0] cfg = 0;", '(* keep *) reg [CW-1:0] cfg = 0;'))
    if which in ("1", "ram"):
        pairs += [("reg mem [0:31];", '(* ram_style = "registers" *) reg mem [0:31];'),
                  ("reg [2:0] lrow [0:15]; reg [31:0] ldat [0:15]; reg [15:0] ltick [0:15];", '(* ram_style = "registers" *) reg [2:0] lrow [0:15]; (* ram_style = "registers" *) reg [31:0] ldat [0:15]; (* ram_style = "registers" *) reg [15:0] ltick [0:15];')]
    for a, b in pairs: text = text.replace(a, b)
    return text


def sources(ref, with_bridge, frame=None):
    frame = frame or os.environ.get("HEXN_FRAME", "v4")      # v4 = proven in simulation; v5 = v4 + the S status command (debug build)
    fs = list(P.FILES) + frame_files(frame) + ([os.path.join(RV, "hexn_jtag_bridge_v1.v")] if with_bridge else [])
    gen = [("hexn_pattern_top.v", P.generate(ref)), ("hexn_arr_core.v", core_text(ref, frame))]       # the board top hexn_arr.v is a static file of the design folder
    return fs, gen


def main():
    if sys.argv[1] == "top": sys.stdout.write(top_text()); return
    cmd, refp, out = sys.argv[1:4]; ref = json.load(open(refp)); pr = P.check_reference(ref)
    if pr: raise SystemExit("reference refused: %s" % pr)
    if cmd == "sim":
        src = os.path.join(out, "src"); os.makedirs(src, exist_ok=True); fs, gen = sources(ref, False)
        nr = os.environ.get("HEXN_NORAM", "")
        for f in fs: open(os.path.join(src, os.path.basename(f)), "w").write(no_ram(open(f).read(), nr) if nr else open(f).read())
        for n, t in gen: open(os.path.join(src, n), "w").write(t)
        print("sim sources in", src, "(%d files)" % (len(fs) + len(gen)))
    elif cmd == "build":
        os.makedirs(out, exist_ok=True); fs, gen = sources(ref, True); txt = []
        nr = os.environ.get("HEXN_NORAM", "")
        for f in fs: txt.append("// ---- %s ----\n" % os.path.relpath(f, ROOT) + (no_ram(open(f).read(), nr) if nr else open(f).read()) + "\n")
        for n, t in gen: txt.append("// ---- generated %s ----\n" % n + t + "\n")
        open(os.path.join(out, "gen_00_hexn_arr.v"), "w").write("".join(txt)); print("wrote", os.path.join(out, "gen_00_hexn_arr.v"), "pattern", ref["name"], ref["pattern_id_hex"])
    else: raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
