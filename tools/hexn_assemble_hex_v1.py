#!/usr/bin/env python3
"""hexn_assemble_hex_v1.py - the HEX assembler (3 Nov 2026, Alan 20:31 'do two runs ... see if it actually fits'). Not a clone of hexn_assemble_v4 (four faces, untouched); it reuses that file's pin table reader, frame file list and sha helper.
  build  HEXREF.json --out DIR [--open-unit] [--seed N] [--clkdiv N]
         -> DIR/src (flat copy of every Verilog file), hexn.cst, synth.ys, build.sh (yosys -> nextpnr-himbaechel-gowin -> gowin_pack), ASSEMBLY.json.
         Run 1 (default): hexn_card_top = hexn_frame_v1 (UART command port) around the generated six-face hexn_pattern_top.
         Run 2 (--open-unit): hexn_hex_open_top = the existing Hex-N OPEN UNIT (hexn_open_top_v13: SPI bridge v2, tables, the two neural judges, raw engine, the chain of gated units, pattern bank) AND the hex array with its UART frame on the same chip.
         The two halves are NOT joined through one link: the open unit is reached over SPI, the array over the UART frame. This answers 'does it fit', not 'is it integrated'.
  image  HEXREF.json UNIT.json --out FILE -> the config chain bytes ('B' command of the frame) from an icm-hexn-v4 program.
SCOPE: pin numbers of the open unit are copied from tools/hexn_open_build_v13.sh (not re-checked on a board); no board run."""
import argparse, hashlib, json, os, shutil, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import hexn_pattern_gen_hex_v1 as P
import hexn_icm_export_v4 as X
import hexn_assemble_v4 as A4

V = os.path.join(ROOT, "fpga", "verilog"); SV = os.path.join(ROOT, "sub", "verilog"); RV = os.path.join(ROOT, "rtl")
OPEN_FILES = [os.path.join(V, f) for f in ("hexn_open_top_v13.v", "hexn_unit_v2.v", "hexn_pins_v1.v", "hexn_presets_v1.v", "spi_bridge_v2.v", "hexn_react_core_v2.v", "hexn_tabs_v5.v", "hexn_raw_engine_v4.v", "hexn_morse_core_v2.v", "hexn_demo_rom_v1.v", "hexn_morse_gen_v1.v", "hexn_scorer_v1.v", "hexn_scorer_v3.v", "hw262_shield_v2.v")] + \
             [os.path.join(SV, f) for f in ("config_gate_v3.v", "arith_block_v10.v", "flex_sub_bridge_v1.v")] + [os.path.join(RV, f) for f in ("hexn_neural_v1.v", "hexn_tanh512_v1.v")]
OPEN_PINS = {"BOARD_CLK": 4, "KEY_S1": 88, "SPI_CS_N": 73, "SPI_SCLK": 74, "SPI_MOSI": 75, "SPI_MISO": 76, "READY": 77, "LED_N[0]": 15, "LED_N[1]": 16, "LED_N[2]": 17, "LED_N[3]": 18, "LED_N[4]": 19, "LED_N[5]": 20}
POOL = [72, 71, 86, 25, 26, 27, 28, 29, 30, 31, 85, 80, 42, 41, 56, 54]


def chain_len(ref): return P.chain_len(ref)


def chain_image(ref, program):
    words, widths = P.load_words(ref, program); bits = P.chain_bits(words, widths)
    out = bytearray((len(bits) + 7) // 8)
    for i, b in enumerate(bits):
        if b: out[i // 8] |= 1 << (i % 8)
    return bytes(out)


def frame_inst(ref, clkdiv, clk, rx, tx, led, frame="v1"):
    return "    hexn_frame_%s #(.ROWS(%d), .CHAIN_BITS(%d), .CLKDIV(%s), .PATTERN_ID(32'h%s)) f (.clk(%s), .rx(%s), .tx(%s), .led(%s));\n" % (frame, ref["rows"], chain_len(ref), clkdiv, ref["pattern_id_hex"], clk, rx, tx, led)


def card_top(ref, clkdiv=234, frame="v1"):
    return ("`default_nettype none\n// hexn_card_top for hex pattern %s (ID %s), generated by tools/hexn_assemble_hex_v1.py; do not edit.\n"
            "module hexn_card_top #(parameter CLKDIV = %d) (input wire clk, input wire uart_rx, output wire uart_tx, output wire [5:0] led);\n%sendmodule\n") % (ref["name"], ref["pattern_id_hex"], clkdiv, frame_inst(ref, "CLKDIV", "clk", "uart_rx", "uart_tx", "led", frame))


def open_top(ref, clkdiv=234, frame="v1", nu=4):
    return ("`default_nettype none\n// hexn_hex_open_top: the Hex-N open unit (SPI) and the hex array %s (ID %s, UART frame) on one chip; generated by tools/hexn_assemble_hex_v1.py; do not edit. Not joined through one link.\n"
            "module hexn_hex_open_top (input wire BOARD_CLK, input wire KEY_S1, input wire SPI_SCLK, input wire SPI_CS_N, input wire SPI_MOSI, output wire SPI_MISO, output wire READY, inout wire [15:0] POOL, output wire [5:0] LED_N, input wire uart_rx, output wire uart_tx);\n"
            "    hexn_open_top_v13 #(.NU(%d)) ou (.BOARD_CLK(BOARD_CLK), .KEY_S1(KEY_S1), .SPI_SCLK(SPI_SCLK), .SPI_CS_N(SPI_CS_N), .SPI_MOSI(SPI_MOSI), .SPI_MISO(SPI_MISO), .READY(READY), .POOL(POOL), .LED_N(LED_N));\n"
            "    wire [5:0] hx_led;\n%sendmodule\n") % (ref["name"], ref["pattern_id_hex"], nu, frame_inst(ref, clkdiv, "BOARD_CLK", "uart_rx", "uart_tx", "hx_led", frame))


def open_cst(man):
    uart = man["board"]["uart"]; L = []
    pins = dict(OPEN_PINS, uart_tx=uart["tx"]["pin"], uart_rx=uart["rx"]["pin"])
    for i, p in enumerate(POOL): pins["POOL[%d]" % i] = p
    for n, p in pins.items():
        L.append('IO_LOC "%s" %d;' % (n, p))
        if n in ("BOARD_CLK", "KEY_S1"): m = "PULL_MODE=NONE"
        elif n.startswith("POOL") or n in ("SPI_CS_N", "SPI_MOSI", "uart_rx"): m = "PULL_MODE=UP"
        elif n == "SPI_SCLK": m = "PULL_MODE=DOWN"
        else: m = "DRIVE=8"
        L.append('IO_PORT "%s" IO_TYPE=LVCMOS33 %s;' % (n, m))
    return "\n".join(L) + "\n"


FRAMES = {"v1": ("hexn_cross_v1.v", "hexn_xtop_v1.v", "hexn_frame_v1.v"), "v2": ("hexn_cross_v2.v", "hexn_xtop_v2.v", "hexn_frame_v2.v")}


def assemble(ref, outdir, man_path=None, clkdiv=234, open_unit=False, seed=1, frame="v1", nu=4):
    pr = P.check_reference(ref)
    if pr: raise ValueError("reference refused: %s" % pr)
    man = json.load(open(man_path or A4.DEFAULT_MAN)); src = os.path.join(outdir, "src"); os.makedirs(src, exist_ok=True); files = {}
    for f in P.FILES + [os.path.join(SV, f) for f in FRAMES[frame]] + (OPEN_FILES if open_unit else []):
        shutil.copy(f, src); files[os.path.basename(f)] = A4._sha(f)
    top = "hexn_hex_open_top" if open_unit else "hexn_card_top"
    for name, text in (("hexn_pattern_top.v", P.generate(ref)), (top + ".v", open_top(ref, clkdiv, frame, nu) if open_unit else card_top(ref, clkdiv, frame))):
        open(os.path.join(src, name), "w").write(text); files[name] = hashlib.sha256(text.encode()).hexdigest()
    open(os.path.join(outdir, "hexn.cst"), "w").write(open_cst(man) if open_unit else A4.cst_from_man(man))
    open(os.path.join(outdir, "synth.ys"), "w").write("".join("read_verilog -sv src/%s\n" % f for f in sorted(files)) + "hierarchy -top %s\nsynth_gowin -top %s -json hexn.json\n" % (top, top))
    open(os.path.join(outdir, "build.sh"), "w").write("#!/bin/sh\n# generated by hexn_assemble_hex_v1.py for card %s; needs yosys, nextpnr-himbaechel (gowin) and gowin_pack\nset -e\n"
        "cd \"$(dirname \"$0\")\"\nNP=${NEXTPNR:-$(command -v nextpnr-himbaechel || command -v yowasp-nextpnr-himbaechel-gowin || true)}\n"
        "for t in yosys gowin_pack; do command -v $t >/dev/null || { echo \"missing tool: $t\"; exit 2; }; done\n[ -n \"$NP\" ] || { echo \"missing tool: nextpnr-himbaechel (gowin)\"; exit 2; }\n"
        "yosys -q -l synth.log synth.ys\n"
        "$NP --device GW2AR-LV18QN88C8/I7 --vopt family=GW2A-18C --vopt cst=hexn.cst --json hexn.json --write hexn_pnr.json --report report.json --freq 27 --seed %d --timing-allow-fail 2>&1 | tee pnr.log\n"
        "gowin_pack -d GW2A-18C -o hexn.fs hexn_pnr.json\n" % (man["card_id"], seed))
    os.chmod(os.path.join(outdir, "build.sh"), 0o755)
    rec = dict(format="hexn-assembly-hex-v1", card=man["card_id"], top=top, pattern=ref["name"], pattern_id_hex=ref["pattern_id_hex"], content_hash=ref["content_hash"], rows=ref["rows"], cols=ref["cols"], offset=ref["offset"],
               chain_bits=chain_len(ref), clkdiv=clkdiv, open_unit=open_unit, seed=seed, frame=frame, nu=nu, files=files)
    json.dump(rec, open(os.path.join(outdir, "ASSEMBLY.json"), "w"), indent=1, sort_keys=True)
    return rec


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0]); sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build"); b.add_argument("ref"); b.add_argument("--out", required=True); b.add_argument("--clkdiv", type=int, default=234); b.add_argument("--open-unit", action="store_true"); b.add_argument("--seed", type=int, default=1); b.add_argument("--frame", default="v1", choices=["v1", "v2"]); b.add_argument("--nu", type=int, default=4)
    i = sub.add_parser("image"); i.add_argument("ref"); i.add_argument("unit"); i.add_argument("--out", required=True)
    a = ap.parse_args(); ref = json.load(open(a.ref))
    if a.cmd == "build": r = assemble(ref, a.out, None, a.clkdiv, a.open_unit, a.seed, a.frame, a.nu); print("built", r["top"], r["pattern_id_hex"], "chain bits", r["chain_bits"])
    else: open(a.out, "wb").write(chain_image(ref, X.from_icm(json.load(open(a.unit))["program"]) if "program" in json.load(open(a.unit)) else X.from_icm(json.load(open(a.unit))))); print("wrote", a.out)
