class SimCard:
    """A simulated card on the real design: send bytes, read the bytes it answers. Same two calls as the serial transport of the host script."""

    def __init__(self, work=None, cpb=8, tmo=3000, mutant="none", built=None):
        self.cpb, self.tmo = cpb, tmo
        self.work = work or tempfile.mkdtemp(prefix="scan_sim_")
        self.own = work is None
        if built is None:
            top, files, g = build_files(self.work, cpb, tmo, mutant)
        else:
            top, files, g = built
        quiet = tmo + 40 * cpb
        tb = TB.replace("@CPB@", str(cpb)).replace("@TMO@", str(tmo)).replace("@QUIET@", str(quiet))
        open(os.path.join(self.work, "tbs.v"), "w").write(tb)
        c = subprocess.run(["iverilog", "-g2012", "-o", "tbs.vvp", "tbs.v"] + files, cwd=self.work, capture_output=True, text=True)
        if c.returncode:
            raise SystemExit("iverilog: " + c.stderr[:2000])
        self.files = (top, files, g)
        self.p = subprocess.Popen(["vvp", "tbs.vvp"], cwd=self.work, stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, bufsize=1)
        self.buf = b""
        self.clocks_note = 0

    def _cmd(self, line):
        self.p.stdin.write(line + "\n"); self.p.stdin.flush()
        r = self.p.stdout.readline()
        while r and not r.startswith("R "):
            r = self.p.stdout.readline()
        if not r:
            raise RuntimeError("simulation ended")
        h = r[2:].strip()
        return b"" if h == "-" else bytes.fromhex(h)

    def send(self, data):
        if data:
            self.buf += self._cmd("T " + data.hex())

    def read(self, n, timeout=None):
        out, self.buf = self.buf[:n], self.buf[n:]
        return out

    def drain(self):
        out, self.buf = self.buf, b""
        return out

    def idle(self, clocks):
        self.buf += self._cmd("N %d" % clocks)

    def close(self):
        try:
            self.p.stdin.close(); self.p.wait(timeout=20)
        except Exception:
            self.p.kill()
        if self.own:
            shutil.rmtree(self.work, ignore_errors=True)


