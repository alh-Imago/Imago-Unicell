#!/usr/bin/env python3
"""tools/board_scan_v1.py -- ledger #1146: the serial scan controller for in-flight capture / restore of the flex looped CORDIC (stage 2).

On the card: the scan-chain grid (tools/flex_scan_net_v1.py), the stop wrapper sub/verilog/looped_cordic_stop_wrapper_v3.v, a 256-byte image memory, a CRC-32 unit, and a UART front end.
The image (256 bytes) = scan stream (240 bytes: 1905 bits + 15 zero pad bits) + closing word (4) + flag (1: closing register holds a word) + step count (2) + zeros. It travels in 8 chunks of 32 bytes.

Serial protocol (115200 8N1; the PC is the host; every card->host chunk is one text line, every host->card chunk is binary with a CRC; the bitstream never changes):
  'X' soft reset (grid, counter, latch, closing register, step offset; the image memory and the chunk mask are kept)      -> 'K'
  'C' mode(1) N(2) dly(1) lag(1)  configure the self-stop (as the save/load kit)                                           -> 'K'
  'L' word(4)                     load the closing register                                                                -> 'K'
  'G'                             release the stop latch and the scan hold (go)                                           -> 'K'
  'Q'                             query -> 'Q' flags(1) steps(2) held(4) run_clocks(4); flags bit0 stopped, bit1 busy, bit2 held_valid, bit3 scan hold
  'S'                             capture: needs stopped or scan-hold; reads the whole chain by recirculating (the state is unchanged), fills the image memory,
                                  session number +1                                                                         -> 'K' (or 'N' when not stopped)
  'D' seq(1)                      dump chunk seq (0..7) as one text line:
                                  "UCS lcordic ses=SSSS seq=N of=8 d=<64 hex> crc=CCCCCCCC\\r\\n"   CRC-32 (zlib) over the 36 bytes  ses(2) seq(1) 8(1) data(32)
  'W' ses(2) seq(1) of(1) data(32) crc(4, big-endian, same CRC)   write chunk: staged, checked, only a good chunk reaches the image memory -> 'K' seq mask  or 'E' seq mask (bad CRC)
                                  or 'T' (a byte went missing: the card gave up after the timeout)
  'M'                             -> 'M' mask(1) ses(2)   (mask bit n = chunk n written and checked since the last 'Z' / power-up)
  'Z'                             clear the mask -> 'K'
  'A'                             apply: needs mask = FF; holds the grid, loads the closing word, shifts the stream into the chain, step offset = image steps -> 'K' (or 'N')
Restore = X, C, (W x 8), A, then G.  Read-back check = S again, D x 8, compare with what was sent.
  python3 tools/board_scan_v1.py [--out DIR] [--no-pnr] [--seed N]
"""
