#!/usr/bin/env python3
"""tools/board_esp32_pulse_v1.py -- ledger #1227: test P1, the mirror of T4: how short can a pulse be before the ESP32's interrupt handler no longer notices it?
The Tang drives pulses of 12 widths (2700 clocks = 100 us down to 1 clock = 37 ns; 27 MHz clock), NP per width, on pin 86 -> ESP32 IO16. The ESP32 handler (rising-edge interrupt) TOGGLES its answer pin IO17 -> Tang pin 72
every time it runs. A pulse is "caught" if the answer pin is in a different state 5,000 clocks (185 us) after the pulse than it was at the start of the pulse. (If the handler ran twice for one pulse the toggles would cancel: counted as missed; the ESP32's own run count is printed as a cross-check.)
Optional storm (pulse_storm build): pin 53 -> ESP32 IO21 edges every 26 to 102 us as in C1 (the ESP32 does STORM_WORK_US of busy work in each). Before each pulse 20,000 + random 0..32,767 clocks of gap.
Pre-flight: 8 slow pulses (100 ms each); the answer pin must flip each time (pre=8). res=L if not.
Builds: pe_quiet and pe_storm.  Usage: python3 tools/board_esp32_pulse_v1.py [--out fpga/board_tests_esp32_pulse] [--no-pnr] [--sim-only] [--seed N]
"""
import argparse, json, os, re, shutil, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import board_tests_v1 as bt  # noqa: E402

WIDTHS = [2700, 1350, 540, 270, 135, 54, 27, 16, 8, 4, 2, 1]
NW = len(WIDTHS)
NP = 512
GAPMIN = 20000
WATCH = 5000
CST = open(os.path.join(ROOT, "tools", "board_esp32_c1_v2.py")).read().split('CST = """', 1)[1].split('"""', 1)[0]


def hexfn():
    return """    function [7:0] hx(input [3:0] n); hx = (n < 4'd10) ? (8'd48 + {4'b0, n}) : (8'd55 + {4'b0, n}); endfunction
    function [63:0] h8(input [31:0] v); h8 = {hx(v[31:28]), hx(v[27:24]), hx(v[23:20]), hx(v[19:16]), hx(v[15:12]), hx(v[11:8]), hx(v[7:4]), hx(v[3:0])}; endfunction
"""


def top_v():
    wcase = " ".join(f"4'd{i}: wval = 32'd{w};" for i, w in enumerate(WIDTHS))
    cgdecl = " ".join(f"reg [31:0] cg{i} = 32'd0;" for i in range(NW))
    cginc = " ".join(f"4'd{i}: if (caught) cg{i} <= cg{i} + 1'b1;" for i in range(NW))
    parts = [('"UCW "', 4), ("NAME", 8), ('" res="', 5), ("res_c", 1), ('" np="', 4), ("h8(NP)", 8), ('" pre="', 5), ("h8(pre_hit)", 8)]
    for i in range(NW):
        tag = f' w{i}='
        parts += [(f'"{tag}"', len(tag)), (f"h8(cg{i})", 8)]
    parts += [('"\\015\\n"', 2)]
    line = ", ".join(e for e, _ in parts)
    LEN = sum(n for _, n in parts)
    v = f"""// pe_top.v -- GENERATED by tools/board_esp32_pulse_v1.py (ledger #1227). P1: Tang pulses of 12 widths into the ESP32; the ESP32 toggles an answer pin per handler run. Do not hand-edit.
`default_nettype none
module pe_top #(parameter [63:0] NAME = "pe_quiet", parameter integer STORM = 0, parameter integer NP = {NP}, parameter integer CPB = {bt.CPB},
                parameter integer WARM = 27000000, parameter integer REPEAT = 40000000, parameter integer PRET = 2700000, parameter integer HALF = 1350000, parameter integer RAND_W = 15,
                parameter integer SPER = 700, parameter integer SRND = 11) (
    input  wire BOARD_CLK, output wire UART_TX, input wire RESP, output wire STIM, output wire STORMP,
    output wire LED0_N, output wire LED1_N, output wire LED2_N, output wire LED3_N, output wire LED4_N, output wire LED5_N
);
    wire clk = BOARD_CLK;
{hexfn()}
    reg [15:0] rcnt = 0; wire rst = ~&rcnt; always @(posedge clk) if (rst) rcnt <= rcnt + 1'b1;
    reg resp_a = 1'b0, resp_s = 1'b0; always @(posedge clk) begin resp_a <= RESP; resp_s <= resp_a; end
    reg [31:0] now = 32'd0; always @(posedge clk) now <= now + 1'b1;
    reg [31:0] lf = 32'hACE1BEEF; always @(posedge clk) lf <= {{lf[30:0], lf[31] ^ lf[21] ^ lf[1] ^ lf[0]}};
    reg [31:0] lg = 32'h1BADB002; always @(posedge clk) lg <= {{lg[30:0], lg[31] ^ lg[21] ^ lg[1] ^ lg[0]}};
    function [31:0] wval(input [3:0] i); begin case (i) {wcase} default: wval = 32'd1; endcase end endfunction
    {cgdecl}
    reg stim_r = 1'b0; assign STIM = stim_r;
    reg storm_r = 1'b0; assign STORMP = storm_r;
    reg [3:0] st = 4'd0, wi = 4'd0; reg [31:0] cnt = 32'd0, pn = 32'd0, pre_hit = 32'd0, pre_n = 32'd0, pre_t = 32'd0; reg ans0 = 1'b0;
    localparam S_WARM = 0, S_PRE = 1, S_GAP = 2, S_HI = 3, S_WATCH = 4, S_DONE = 7;
    wire storm_on = (STORM != 0) && (st >= S_GAP) && (st != S_DONE);
    reg [31:0] sc = 32'd0;
    always @(posedge clk) begin
        if (!storm_on) sc <= 32'd0;
        else if (sc == 0) begin storm_r <= ~storm_r; sc <= SPER + {{21'd0, lg[SRND-1:0]}}; end
        else sc <= sc - 1'b1;
    end
    wire caught = (resp_s != ans0);
    always @(posedge clk) begin
        case (st)
            S_WARM: if (!rst && now > WARM) begin st <= S_PRE; pre_t <= 32'd0; end
            S_PRE: begin
                pre_t <= pre_t + 1'b1;
                if (pre_t == 32'd0) begin ans0 <= resp_s; stim_r <= 1'b1; end
                if (pre_t == HALF) stim_r <= 1'b0;
                if (pre_t >= PRET) begin
                    pre_t <= 32'd0; pre_n <= pre_n + 1'b1;
                    if (resp_s != ans0) pre_hit <= pre_hit + 1'b1;
                    if (pre_n == 32'd7) begin
                        if (pre_hit + ((resp_s != ans0) ? 32'd1 : 32'd0) == 32'd8) begin st <= S_GAP; cnt <= {GAPMIN} + {{17'd0, lf[RAND_W-1:0]}}; wi <= 4'd0; pn <= 32'd0; end
                        else st <= S_DONE;
                    end
                end
            end
            S_GAP: if (cnt == 0) begin ans0 <= resp_s; stim_r <= 1'b1; cnt <= wval(wi) - 1'b1; st <= S_HI; end else cnt <= cnt - 1'b1;
            S_HI: begin if (cnt == 0) begin stim_r <= 1'b0; cnt <= {WATCH}; st <= S_WATCH; end else cnt <= cnt - 1'b1; end
            S_WATCH: begin
                if (cnt == 0) begin
                    case (wi) {cginc} default: ; endcase
                    cnt <= {GAPMIN} + {{17'd0, lf[RAND_W-1:0]}};
                    if (pn + 1 == NP) begin pn <= 32'd0; if (wi == 4'd{NW - 1}) st <= S_DONE; else begin wi <= wi + 1'b1; st <= S_GAP; end end
                    else begin pn <= pn + 1'b1; st <= S_GAP; end
                end else cnt <= cnt - 1'b1;
            end
            default: ;
        endcase
    end
    wire done = (st == S_DONE);
    wire [7:0] res_c = (pre_hit != 32'd8) ? "L" : "P";
    wire [8*{LEN}-1:0] line = {{{line}}};
    reg [7:0] ci = 8'd0; reg [31:0] rep = 32'd0; reg sending = 1'b0; reg start = 1'b0; wire busy;
    board_uart_tx #(.CPB(CPB)) T (.clk(clk), .start(start), .data(line[(({LEN}-1)-ci)*8 +: 8]), .tx(UART_TX), .busy(busy));
    always @(posedge clk) begin
        start <= 1'b0;
        if (!done) begin sending <= 1'b0; ci <= 8'd0; rep <= 32'd0; end
        else if (!sending) begin if (rep >= REPEAT || rep == 0) begin sending <= 1'b1; ci <= 8'd0; rep <= 32'd1; end else rep <= rep + 1'b1; end
        else if (start) ci <= ci + 1'b1;
        else if (!busy) begin if (ci == {LEN}) sending <= 1'b0; else start <= 1'b1; end
    end
    reg [24:0] hb = 25'd0; always @(posedge clk) hb <= hb + 1'b1;
    assign LED0_N = ~hb[24]; assign LED1_N = ~(done && pre_hit == 32'd8); assign LED2_N = ~(done && pre_hit != 32'd8); assign LED3_N = ~done;
    assign LED4_N = ~stim_r; assign LED5_N = ~resp_s;
endmodule
`default_nettype wire
"""
    return v, LEN


TB = """`timescale 1ns / 1ps
module tb;
    reg clk = 0; always #18.5 clk = ~clk;
    wire tx, stim, stormp, l0, l1, l2, l3, l4, l5; reg resp = 0; integer toggles = 0;
    pe_top #(.NAME("%(name)s"), .STORM(%(storm)d), .NP(%(np)d), .WARM(2000), .REPEAT(100000000), .PRET(30000), .HALF(15000), .RAND_W(10)) dut (.BOARD_CLK(clk), .UART_TX(tx), .RESP(resp), .STIM(stim), .STORMP(stormp), .LED0_N(l0), .LED1_N(l1), .LED2_N(l2), .LED3_N(l3), .LED4_N(l4), .LED5_N(l5));
    always @(posedge stim) begin #1500 resp = ~resp; end          // stand-in for the ESP32: toggles 1.5 us after every rising edge
    always @(stormp) toggles = toggles + 1;
    integer i; reg [7:0] b;
    initial begin
        forever begin
            @(negedge tx); #(%(half)d); b = 0;
            for (i = 0; i < 8; i = i + 1) begin #(%(bit)d); b = {tx, b[7:1]}; end
            #(%(bit)d); $write("%%c", b);
            if (b == 8'h0A) begin $display("STORMTOGGLES %%0d", toggles); $finish; end
        end
    end
    initial begin #(%(limit)d); $display("TIMEOUT"); $finish; end
endmodule
"""


def parse(line):
    m = re.match(r"UCW (\S+) res=(\w) np=([0-9A-F]{8}) pre=([0-9A-F]{8})", line)
    d = {"name": m.group(1), "res": m.group(2), "np": int(m.group(3), 16), "pre": int(m.group(4), 16)}
    d["w"] = [int(re.search(r" w%d=([0-9A-F]{8})" % i, line).group(1), 16) for i in range(NW)]
    return d


def sim(work, name, storm, np_):
    wd = os.path.join(work, "sim_" + name)
    shutil.rmtree(wd, ignore_errors=True)
    os.makedirs(wd)
    open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
    open(os.path.join(wd, "pe_top.v"), "w").write(open(os.path.join(work, "pe_top.v")).read())
    per = GAPMIN + 1024 + max(WIDTHS) + WATCH + 10
    limit = (NW * np_ * per + 2000 + 8 * 30000 + 400000) * 38
    open(os.path.join(wd, "tb.v"), "w").write(TB % dict(name=name, storm=storm, np=np_, half=int(bt.CPB * 37.037 / 2), bit=int(bt.CPB * 37.037), limit=limit))
    r = subprocess.run(["iverilog", "-g2012", "-o", "sim.vvp", "tb.v", "pe_top.v", "board_uart_tx.v"], cwd=wd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("iverilog: " + r.stderr[-1500:])
    r = subprocess.run(["vvp", "sim.vvp"], cwd=wd, capture_output=True, text=True, timeout=20000)
    line = next((ln for ln in r.stdout.splitlines() if ln.startswith("UCW")), "")
    tog = next((int(ln.split()[1]) for ln in r.stdout.splitlines() if ln.startswith("STORMTOGGLES")), -1)
    if not line:
        raise SystemExit("simulation printed no UCW line:\n" + r.stdout[-800:])
    return line.strip(), tog


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "board_tests_esp32_pulse"))
    ap.add_argument("--no-pnr", action="store_true")
    ap.add_argument("--sim-only", action="store_true")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--sim-np", type=int, default=6)
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(os.path.join(out, "groups"), exist_ok=True)
    work = tempfile.mkdtemp(prefix="bpe_")
    v, LEN = top_v()
    open(os.path.join(work, "pe_top.v"), "w").write(v)
    meta = {"line_bytes": LEN, "widths_clk": WIDTHS, "np": NP, "builds": {}}
    for name, storm in (("pe_quiet", 0), ("pe_storm", 1)):
        sl, tog = sim(work, name, storm, a.sim_np)
        d = parse(sl)
        print("SIM", sl, "| storm pin toggles:", tog, flush=True)
        if d["res"] != "P" or d["pre"] != 8 or any(x != a.sim_np for x in d["w"]) or (storm == 0) != (tog == 0):
            raise SystemExit(f"{name}: simulation not clean: {sl}")
        meta["builds"][name] = {"sim_line": sl, "storm": storm}
        if a.sim_only:
            continue
        wd = os.path.join(work, "syn_" + name)
        os.makedirs(wd)
        txt = open(os.path.join(work, "pe_top.v")).read().replace('parameter [63:0] NAME = "pe_quiet", parameter integer STORM = 0', f'parameter [63:0] NAME = "{name}", parameter integer STORM = {storm}')
        open(os.path.join(wd, "pe_top.v"), "w").write(txt)
        open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
        open(os.path.join(wd, "g.cst"), "w").write(CST)
        s = subprocess.run(["yosys", "-q", "-l", "y.log", "-p", "read_verilog -sv pe_top.v board_uart_tx.v; hierarchy -top pe_top; synth_gowin -top pe_top -nowidelut -json g.json"], cwd=wd, capture_output=True, text=True, timeout=3000)
        if s.returncode:
            raise SystemExit("yosys: " + (s.stderr or s.stdout)[-800:])
        if not a.no_pnr:
            p = subprocess.run(["yowasp-nextpnr-himbaechel-gowin", "--device", bt.DEVICE, "--vopt", "family=GW2A-18C", "--vopt", "cst=g.cst", "--seed", str(a.seed), "--json", "g.json",
                                "--write", "g_r.json", "--report", "g_rep.json", "--freq", "27"], cwd=wd, capture_output=True, text=True, timeout=7000)
            if p.returncode:
                raise SystemExit("nextpnr: " + (p.stdout[-500:] + p.stderr[-600:]))
            rep = json.load(open(os.path.join(wd, "g_rep.json")))
            fmax = rep["fmax"]["clk"]["achieved"] if "clk" in rep["fmax"] else min(x["achieved"] for x in rep["fmax"].values())
            meta["builds"][name].update(fmax_mhz=round(fmax, 1), lut4=rep["utilization"]["LUT4"]["used"], dff=rep["utilization"]["DFF"]["used"])
            if fmax < 27:
                raise SystemExit(f"{name}: timing NOT met at 27 MHz (Fmax {fmax:.1f})")
            g = subprocess.run(["gowin_pack", "-d", bt.DEVICE, "-o", os.path.abspath(os.path.join(out, "groups", name + ".fs")), "-s", "g.cst", "g_r.json"], cwd=wd, capture_output=True, text=True)
            if g.returncode:
                raise SystemExit("gowin_pack: " + g.stderr[-400:])
            shutil.copy(os.path.join(wd, "g.cst"), os.path.join(out, "groups", name + ".cst"))
        print(name, {k: x for k, x in meta["builds"][name].items() if k != "sim_line"}, flush=True)
    shutil.copy(os.path.join(work, "pe_top.v"), os.path.join(out, "pe_top_generated.v"))
    json.dump(meta, open(os.path.join(out, "pulse_esp32_meta.json"), "w"), indent=1)
    print("done:", out)


if __name__ == "__main__":
    main()
