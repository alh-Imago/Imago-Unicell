#!/usr/bin/env python3
"""tools/board_direct_pulse_t4_v1.py -- ledger #1224: test T4 (pulse width at the edge), cloned from tools/board_direct_latency_v2.py (T2).

How short can a pulse on an input pin be before the design no longer sees it?
The chip drives a pulse of a chosen width on STIM (Tang pin 86); Alan's T2 jumper (86 -> 72) feeds it into sensor input 1. The direct-mode unit (sd_unit_v1, the same RTL as T2/T3)
samples that pin once per 1 ms (27,000 clocks). A pulse is "caught" if the design's live result became non-zero at any time from the rising edge until 28,000 clocks after the falling edge.
Twelve widths, NP pulses each, in this order (27 MHz clocks / time): 54000 (2 ms), 27000 (1 ms), 20250 (750 us), 13500 (500 us), 6750 (250 us), 2700 (100 us), 1350 (50 us), 540 (20 us), 270 (10 us), 135 (5 us), 54 (2 us), 27 (1 us).
Before every pulse the chip waits 60,000 + a random 0..2^GAPW clocks (so the pulse lands at a random point between two samples) and checks the result is zero (stale= counts when it is not).
Expectation to be tested, not assumed: a sampler that looks once per 1 ms sees a pulse of width W with probability min(1, W / 27,000).
Pre-flight as in T2: pin 86 toggled slowly 16 times, pin 72 must follow (pre=), else res=L. Builds: pls_idle and pls_busy (24 free-running xorshift32 lanes).
Usage: python3 tools/board_direct_pulse_t4_v1.py [--out fpga/board_tests_pulse] [--no-pnr] [--seed N] [--sim-only]
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import sd_unit_top_v1 as U  # noqa: E402
import board_tests_v1 as bt  # noqa: E402
import board_direct_latency_v2 as L2  # noqa: E402  (hexfn, CST, ICM, U_TOP, STORM_LANES reused unchanged)

WIDTHS = [54000, 27000, 20250, 13500, 6750, 2700, 1350, 540, 270, 135, 54, 27]
NW = len(WIDTHS)
NP = 512
GAPMIN = 60000
WATCH = 28000


def top_v(ins, outs):
    conn = ", ".join([f".in_{p}_data(lane_data[{j}*32 +: 32]), .in_{p}_valid(lane_valid[{j}]), .in_{p}_ack(lane_ack[{j}])" for j, p in enumerate(ins)] +
                     [f".out_{p}_data(out_data[{k}*32 +: 32]), .out_{p}_valid(out_valid[{k}]), .out_{p}_ack(out_ack[{k}])" for k, p in enumerate(outs)])
    Ln, O = len(ins), len(outs)
    st = []
    for i in range(L2.STORM_LANES):
        seed = (0x9E3779B9 * (i + 1)) & 0xFFFFFFFF or 1
        st.append(f"    reg [31:0] s{i} = 32'h{seed:08X}; wire [31:0] a{i} = s{i} ^ (s{i} << 13); wire [31:0] b{i} = a{i} ^ (a{i} >> 17); wire [31:0] c{i} = b{i} ^ (b{i} << 5);")
        st.append(f"    always @(posedge clk) if (STORM != 0) s{i} <= c{i};")
    fold = " ^ ".join(f"s{i}" for i in range(L2.STORM_LANES))
    wcase = " ".join(f"4'd{i}: wval = 32'd{w};" for i, w in enumerate(WIDTHS))
    cgdecl = " ".join(f"reg [31:0] cg{i} = 32'd0;" for i in range(NW))
    cginc = " ".join(f"4'd{i}: if (seen_now) cg{i} <= cg{i} + 1'b1;" for i in range(NW))
    parts = [('"UCP "', 4), ("NAME", 8), ('" res="', 5), ("res_c", 1), ('" np="', 4), ("h8(NP)", 8), ('" stale="', 7), ("h8(stale)", 8), ('" pre="', 5), ("h8(pre_hit)", 8)]
    for i in range(NW):
        tag = f' w{i}='
        parts += [(f'"{tag}"', len(tag)), (f"h8(cg{i})", 8)]
    parts += [('" chk="', 5), ("h8(chk)", 8), ('"\\015\\n"', 2)]
    line = ", ".join(e for e, _ in parts)
    LEN = sum(n for _, n in parts)
    v = f"""// pls_top.v -- GENERATED by tools/board_direct_pulse_t4_v1.py (ledger #1224). T4: pulse width at the input pin. Do not hand-edit.
`default_nettype none
module pls_top #(parameter [63:0] NAME = "pls_idle", parameter integer STORM = 0, parameter integer NP = {NP}, parameter integer GAPW = 17,
                 parameter integer CPB = {bt.CPB}, parameter integer WARM = 200000, parameter integer REPEAT = 40000000, parameter integer PRET = 4000000, parameter integer PRED = 100000) (
    input  wire BOARD_CLK, output wire UART_TX, input wire SENS0, output wire STIM,
    output wire LED0_N, output wire LED1_N, output wire LED2_N, output wire LED3_N, output wire LED4_N, output wire LED5_N
);
    wire clk = BOARD_CLK;
{L2.hexfn()}
    reg [15:0] rcnt = 0; wire rst = ~&rcnt; always @(posedge clk) if (rst) rcnt <= rcnt + 1'b1;
    reg cfg_done = 1'b0, cfg_valid = 1'b0;
    always @(posedge clk) begin cfg_valid <= 1'b0; if (rst) cfg_done <= 1'b0; else if (!cfg_done) begin cfg_valid <= 1'b1; cfg_done <= 1'b1; end end
    wire [{Ln}*32-1:0] lane_data; wire [{Ln - 1}:0] lane_valid, lane_ack;
    wire [{O}*32-1:0] out_data;  wire [{O - 1}:0] out_valid, out_ack;
    wire ready_line, direct_on, live_nz, live_two; wire [15:0] live_amt;
    sd_unit_v1 #(.LANES({Ln}), .OUTS({O}), .AW(10), .INIT_DIV(34), .FAST_DIV(2), .DESIGN_ID(32'h54524545), .NSENS(2), .DIRECT_RAW(0), .DIRECT_DEFAULT(1), .SENS_INVERT(0)) U (
        .clk(clk), .rst(rst), .sd_clk(), .sd_mosi(), .sd_miso(1'b1), .sd_cs_n(),
        .spi_sclk(1'b0), .spi_cs_n(1'b1), .spi_mosi(1'b0), .spi_miso(),
        .lane_data(lane_data), .lane_valid(lane_valid), .lane_ack(lane_ack), .out_data(out_data), .out_valid(out_valid), .out_ack(out_ack), .ready_line(ready_line),
        .sens_pins({{1'b0, SENS0}}), .direct_on(direct_on), .live_nz(live_nz), .live_two(live_two), .live_amt(live_amt));
    {L2.U_TOP} D (.clk(clk), .rst(rst), .cfg_valid(cfg_valid), {conn});

    reg [31:0] now = 32'd0; always @(posedge clk) now <= now + 1'b1;
{chr(10).join(st)}
    (* keep *) reg [31:0] chk = 32'd0;
    always @(posedge clk) if (STORM != 0) chk <= chk ^ ({fold});
    reg [31:0] lf = 32'hACE1BEEF; always @(posedge clk) lf <= {{lf[30:0], lf[31] ^ lf[21] ^ lf[1] ^ lf[0]}};

    function [31:0] wval(input [3:0] i); begin case (i) {wcase} default: wval = 32'd1; endcase end endfunction
    {cgdecl}
    reg stim_r = 1'b0; assign STIM = stim_r;
    reg [3:0] st = 4'd0, wi = 4'd0; reg [31:0] cnt = 32'd0, pn = 32'd0, stale = 32'd0; reg seen = 1'b0;
    wire seen_now = seen | (live_amt != 16'd0);
    localparam S_WARM = 0, S_GAP = 1, S_RGO = 2, S_HI = 3, S_WATCH = 4, S_DONE = 7, S_PRE = 8;
    reg [31:0] pre_hit = 32'd0, pre_n = 32'd0, pre_t = 32'd0;
    always @(posedge clk) begin
        case (st)
            S_WARM: if (!rst && now > WARM) begin st <= S_PRE; pre_t <= 32'd0; end
            S_PRE: begin
                pre_t <= pre_t + 1'b1;
                if (pre_t == 32'd0) stim_r <= ~stim_r;
                if (pre_t == PRED) begin if (SENS0 == stim_r) pre_hit <= pre_hit + 1'b1; pre_n <= pre_n + 1'b1; end
                if (pre_t >= PRET) begin pre_t <= 32'd0; if (pre_n == 32'd16) begin if (pre_hit == 32'd16) begin stim_r <= 1'b0; st <= S_GAP; cnt <= {GAPMIN} + {{15'd0, lf[GAPW-1:0]}}; wi <= 4'd0; pn <= 32'd0; end else st <= S_DONE; end end
            end
            S_GAP: if (cnt == 0) begin if (live_amt != 16'd0) stale <= stale + 1'b1; st <= S_RGO; end else cnt <= cnt - 1'b1;
            S_RGO: begin stim_r <= 1'b1; cnt <= wval(wi) - 1'b1; seen <= 1'b0; st <= S_HI; end
            S_HI: begin
                if (live_amt != 16'd0) seen <= 1'b1;
                if (cnt == 0) begin stim_r <= 1'b0; cnt <= {WATCH}; st <= S_WATCH; end else cnt <= cnt - 1'b1;
            end
            S_WATCH: begin
                if (live_amt != 16'd0) seen <= 1'b1;
                if (cnt == 0) begin
                    case (wi) {cginc} default: ; endcase
                    cnt <= {GAPMIN} + {{15'd0, lf[GAPW-1:0]}};
                    if (pn + 1 == NP) begin pn <= 32'd0; if (wi == 4'd{NW - 1}) st <= S_DONE; else begin wi <= wi + 1'b1; st <= S_GAP; end end
                    else begin pn <= pn + 1'b1; st <= S_GAP; end
                end else cnt <= cnt - 1'b1;
            end
            default: ;
        endcase
    end
    wire done = (st == S_DONE);
    wire [7:0] res_c = (pre_hit != 32'd16) ? "L" : ((stale == 0) ? "P" : "F");

    wire [8*{LEN}-1:0] line = {{{line}}};
    reg [7:0] ci = 8'd0; reg [31:0] rep = 32'd0; reg sending = 1'b0; reg start = 1'b0; wire busy;
    board_uart_tx #(.CPB(CPB)) T (.clk(clk), .start(start), .data(line[(({LEN}-1)-ci)*8 +: 8]), .tx(UART_TX), .busy(busy));
    always @(posedge clk) begin
        start <= 1'b0;
        if (!done) begin sending <= 1'b0; ci <= 8'd0; rep <= 32'd0; end
        else if (!sending) begin if (rep >= REPEAT || rep == 0) begin sending <= 1'b1; ci <= 8'd0; rep <= 32'd1; end else rep <= rep + 1'b1; end
        else if (start) ci <= ci + 1'b1;
        else if (!busy) begin
            if (ci == {LEN}) begin sending <= 1'b0; end
            else start <= 1'b1;
        end
    end
    reg [24:0] hb = 25'd0; always @(posedge clk) hb <= hb + 1'b1;
    assign LED0_N = ~hb[24]; assign LED1_N = ~(done && stale == 0 && pre_hit == 32'd16); assign LED2_N = ~(done && (stale != 0 || pre_hit != 32'd16)); assign LED3_N = ~done;
    assign LED4_N = ~stim_r; assign LED5_N = ~SENS0;
endmodule
`default_nettype wire
"""
    return v, LEN


TB = """`timescale 1ns / 1ps
module tb;
    reg clk = 0; always #18.5 clk = ~clk;
    wire tx, stim, l0, l1, l2, l3, l4, l5;
    pls_top #(.NAME("%(name)s"), .STORM(%(storm)d), .NP(%(np)d), .GAPW(%(gapw)d), .WARM(200000), .REPEAT(100000000), .PRET(20000), .PRED(500)) dut (.BOARD_CLK(clk), .UART_TX(tx), .SENS0(stim), .STIM(stim), .LED0_N(l0), .LED1_N(l1), .LED2_N(l2), .LED3_N(l3), .LED4_N(l4), .LED5_N(l5));
    integer i; reg [7:0] b;
    initial begin
        forever begin
            @(negedge tx);
            #(%(half)d);
            b = 0;
            for (i = 0; i < 8; i = i + 1) begin #(%(bit)d); b = {tx, b[7:1]}; end
            #(%(bit)d);
            $write("%%c", b);
            if (b == 8'h0A) begin $display("END"); $finish; end
        end
    end
    initial begin #(%(limit)d); $display("TIMEOUT"); $finish; end
endmodule
"""


def parse(line):
    m = re.match(r"UCP (\S+) res=(\w) np=([0-9A-F]{8}) stale=([0-9A-F]{8}) pre=([0-9A-F]{8})", line)
    d = {"name": m.group(1), "res": m.group(2), "np": int(m.group(3), 16), "stale": int(m.group(4), 16), "pre": int(m.group(5), 16)}
    d["w"] = [int(re.search(r" w%d=([0-9A-F]{8})" % i, line).group(1), 16) for i in range(NW)]
    d["chk"] = int(re.search(r"chk=([0-9A-F]{8})", line).group(1), 16)
    return d


def sim(work, files, name, storm, np_, gapw):
    wd = os.path.join(work, "sim_" + name)
    shutil.rmtree(wd, ignore_errors=True)
    os.makedirs(wd)
    open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
    per = GAPMIN + (1 << gapw) + max(WIDTHS) + WATCH + 10
    limit = (NW * np_ * per + 200000 + 20000 * 40 + 400000) * 38
    open(os.path.join(wd, "tb.v"), "w").write(TB % dict(name=name, storm=storm, np=np_, gapw=gapw, half=int(bt.CPB * 37.037 / 2), bit=int(bt.CPB * 37.037), limit=limit))
    r = subprocess.run(["iverilog", "-g2012", "-o", "sim.vvp", "tb.v", "board_uart_tx.v"] + files, cwd=wd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("iverilog: " + r.stderr[-1500:])
    r = subprocess.run(["vvp", "sim.vvp"], cwd=wd, capture_output=True, text=True, timeout=20000)
    line = next((ln for ln in r.stdout.splitlines() if ln.startswith("UCP")), "")
    if not line:
        raise SystemExit("simulation printed no UCP line:\n" + r.stdout[-800:])
    return line.strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "board_tests_pulse"))
    ap.add_argument("--no-pnr", action="store_true")
    ap.add_argument("--sim-only", action="store_true")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--sim-np", type=int, default=6)
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(os.path.join(out, "groups"), exist_ok=True)
    work = tempfile.mkdtemp(prefix="bpls_")
    ud = os.path.join(work, "unit")
    top, ins, outs = U.build(L2.ICM, ud, 2, 1)
    assert top == L2.U_TOP, top
    flist = [os.path.join(ud, p) for p in open(os.path.join(ud, "FILES.txt")).read().split() if p != "unit_top.v"]
    v, LEN = top_v(ins, outs)
    open(os.path.join(work, "pls_top.v"), "w").write(v)
    files = [os.path.join(work, "pls_top.v")] + flist
    meta = {"line_bytes": LEN, "widths_clk": WIDTHS, "np": NP, "gapmin": GAPMIN, "watch": WATCH, "period_ns": L2.PERIOD_NS, "builds": {}}
    for name, storm in (("pls_idle", 0), ("pls_busy", 1)):
        sl = sim(work, files, name, storm, a.sim_np, 12)
        d = parse(sl)
        print("SIM", sl, flush=True)
        if d["res"] != "P" or d["np"] != NP and False or d["pre"] != 16 or d["stale"] != 0:
            raise SystemExit(f"{name}: simulation not clean: {sl}")
        if d["w"][0] != a.sim_np:
            raise SystemExit(f"{name}: the 2 ms pulses were not all caught in simulation: {sl}")
        meta["builds"][name] = {"sim_line": sl, "storm": storm, "sim_np": a.sim_np}
        if a.sim_only:
            continue
        wd = os.path.join(work, "syn_" + name)
        os.makedirs(wd)
        txt = open(os.path.join(work, "pls_top.v")).read().replace('parameter [63:0] NAME = "pls_idle", parameter integer STORM = 0', f'parameter [63:0] NAME = "{name}", parameter integer STORM = {storm}')
        open(os.path.join(wd, "pls_top.v"), "w").write(txt)
        open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
        names = []
        for f in flist:
            shutil.copy(f, os.path.join(wd, os.path.basename(f)))
            names.append(os.path.basename(f))
        open(os.path.join(wd, "g.cst"), "w").write(L2.CST)
        fl = ["pls_top.v", "board_uart_tx.v"] + names
        s = subprocess.run(["yosys", "-q", "-l", "y.log", "-p", "read_verilog -sv %s; hierarchy -top pls_top; synth_gowin -top pls_top -nowidelut -json g.json" % " ".join(fl)], cwd=wd, capture_output=True, text=True, timeout=3000)
        if s.returncode:
            raise SystemExit("yosys: " + (s.stderr or s.stdout)[-800:])
        if not a.no_pnr:
            p = subprocess.run(["yowasp-nextpnr-himbaechel-gowin", "--device", bt.DEVICE, "--vopt", "family=GW2A-18C", "--vopt", "cst=g.cst", "--seed", str(a.seed), "--json", "g.json",
                                "--write", "g_r.json", "--report", "g_rep.json", "--freq", "27"], cwd=wd, capture_output=True, text=True, timeout=7000)
            if p.returncode:
                raise SystemExit("nextpnr: " + (p.stdout[-500:] + p.stderr[-600:]))
            rep = json.load(open(os.path.join(wd, "g_rep.json")))
            fmax = rep["fmax"]["clk"]["achieved"] if "clk" in rep["fmax"] else min(x["achieved"] for x in rep["fmax"].values())
            u = rep["utilization"]
            meta["builds"][name].update(fmax_mhz=round(fmax, 1), lut4=u["LUT4"]["used"], dff=u["DFF"]["used"])
            if fmax < 27:
                raise SystemExit(f"{name}: timing NOT met at 27 MHz (Fmax {fmax:.1f})")
            g = subprocess.run(["gowin_pack", "-d", bt.DEVICE, "-o", os.path.abspath(os.path.join(out, "groups", name + ".fs")), "-s", "g.cst", "g_r.json"], cwd=wd, capture_output=True, text=True)
            if g.returncode:
                raise SystemExit("gowin_pack: " + g.stderr[-400:])
            shutil.copy(os.path.join(wd, "g.cst"), os.path.join(out, "groups", name + ".cst"))
        print(name, {k: v for k, v in meta["builds"][name].items() if k != "sim_line"}, flush=True)
    b = meta["builds"]
    if not a.sim_only and b["pls_busy"].get("dff") and b["pls_idle"].get("dff"):
        extra = b["pls_busy"]["dff"] - b["pls_idle"]["dff"]
        print("flip-flops added by the busy build:", extra, "(expected about", L2.STORM_LANES * 32 + 32, ")")
        if extra < L2.STORM_LANES * 32:
            raise SystemExit("the busy build did not keep its load lanes: synthesis deleted them")
    shutil.copy(os.path.join(work, "pls_top.v"), os.path.join(out, "pls_top_generated.v"))
    json.dump(meta, open(os.path.join(out, "pulse_meta.json"), "w"), indent=1)
    print("done:", out)


if __name__ == "__main__":
    main()
