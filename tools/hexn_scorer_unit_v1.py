#!/usr/bin/env python3
"""tools/hexn_scorer_unit_v1.py -- Hex-N (new file 1 Nov 2026): the small unit (SD card + ESP32 SPI, Tang Nano 20K) with the BATCH SCORER (fpga/verilog/hexn_scorer_v1.v) as its design.
A clone of the wrapper part of tools/sd_unit_top_v1.py (ledger #1036, left untouched): the same blocks and pins, with hexn_scorer_v1 in place of a generated flex design.

    python3 tools/hexn_scorer_unit_v1.py --output build_dir

Writes build_dir/unit_top.v, unit_top.cst, FILES.txt, lanes.json and rtl/ (copies of the sources). NOT run on a board."""
import argparse, json, os, shutil, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import sd_unit_top_v1 as U
RTL = U.RTL + ["hexn_scorer_v1.v"]

def build(out, fast_div=2):
    os.makedirs(os.path.join(out, "rtl"), exist_ok=True)
    for f in RTL: shutil.copy(os.path.join(ROOT, "fpga", "verilog", f), os.path.join(out, "rtl", f))
    v = f"""// unit_top.v -- GENERATED by tools/hexn_scorer_unit_v1.py (Hex-N). The batch scorer behind the SD-card + SPI small unit, Tang Nano 20K pins. Do not hand-edit.
`default_nettype none
module unit_top #(parameter INIT_DIV = 34, parameter FAST_DIV = {fast_div}, parameter RSTW = 16) (
    input  wire BOARD_CLK, input wire KEY_S1,
    output wire SD_CLK, output wire SD_CMD, input wire SD_DAT0, output wire SD_DAT3,
    input  wire SPI_SCLK, input wire SPI_CS_N, input wire SPI_MOSI, output wire SPI_MISO, output wire READY,
    output wire [5:0] LED_N
);
    wire clk = BOARD_CLK;
    reg [RSTW-1:0] rcnt = 0;
    wire rst = ~&rcnt;
    reg [1:0] key_q = 2'b00; always @(posedge clk) key_q <= {{key_q[0], KEY_S1}};
    wire key_down = key_q[1];
    always @(posedge clk) if (key_down) rcnt <= 0; else if (rst) rcnt <= rcnt + 1'b1;
    wire [31:0] lane_data; wire lane_valid, lane_ack;
    wire [31:0] out_data;  wire out_valid, out_ack;
    wire ready_line;
    sd_unit_v1 #(.LANES(1), .OUTS(1), .AW(10), .INIT_DIV(INIT_DIV), .FAST_DIV(FAST_DIV)) U (
        .clk(clk), .rst(rst), .sd_clk(SD_CLK), .sd_mosi(SD_CMD), .sd_miso(SD_DAT0), .sd_cs_n(SD_DAT3),
        .spi_sclk(SPI_SCLK), .spi_cs_n(SPI_CS_N), .spi_mosi(SPI_MOSI), .spi_miso(SPI_MISO),
        .lane_data(lane_data), .lane_valid(lane_valid), .lane_ack(lane_ack), .out_data(out_data), .out_valid(out_valid), .out_ack(out_ack), .ready_line(ready_line));
    hexn_scorer_v1 D (.clk(clk), .rst(rst), .in_data(lane_data), .in_valid(lane_valid), .in_ack(lane_ack), .out_data(out_data), .out_valid(out_valid), .out_ack(out_ack));
    assign READY = ready_line;
    // LEDs as in the CORDIC unit: LED0 heartbeat; LED1 CS seen; LED2 SCLK seen; LED3 SD card up; LED4 a 1 seen on MOSI while CS low; LED5 unused
    reg [24:0] hb = 25'd0; reg seen_cs = 1'b0, seen_clk = 1'b0, seen_mosi = 1'b0;
    always @(posedge clk) begin hb <= hb + 1'b1; if (key_down) begin seen_cs <= 1'b0; seen_clk <= 1'b0; seen_mosi <= 1'b0; end else begin if (!SPI_CS_N) seen_cs <= 1'b1; if (SPI_SCLK) seen_clk <= 1'b1; if (!SPI_CS_N && SPI_MOSI) seen_mosi <= 1'b1; end end
    assign LED_N = ~{{1'b0, seen_mosi, ready_line, seen_clk, seen_cs, hb[24]}};
endmodule
`default_nettype wire
"""
    open(os.path.join(out, "unit_top.v"), "w").write(v)
    cst = ["// GENERATED by tools/hexn_scorer_unit_v1.py -- same pins as the CORDIC unit (docs/man/tang-nano-20k.man.json). NOT checked on a board."]
    for name, pin in U.PINS.items():
        cst.append(f'IO_LOC "{name}" {pin};')
        if name in ("BOARD_CLK", "KEY_S1"): cst.append(f'IO_PORT "{name}" IO_TYPE=LVCMOS33 PULL_MODE=NONE;')
        elif name.startswith("SD_"): cst.append(f'IO_PORT "{name}" IO_TYPE=LVCMOS33 PULL_MODE=UP;')
        elif name.startswith("SPI_") and name != "SPI_MISO": cst.append(f'IO_PORT "{name}" IO_TYPE=LVCMOS33 PULL_MODE=DOWN;' if name == "SPI_SCLK" else f'IO_PORT "{name}" IO_TYPE=LVCMOS33 PULL_MODE=UP;')
        else: cst.append(f'IO_PORT "{name}" IO_TYPE=LVCMOS33 DRIVE=8;')
    open(os.path.join(out, "unit_top.cst"), "w").write("\n".join(cst) + "\n")
    open(os.path.join(out, "FILES.txt"), "w").write("\n".join([os.path.join("rtl", f) for f in RTL] + ["unit_top.v"]) + "\n")
    json.dump({"design_top": "hexn_scorer_v1", "lanes": 1, "outs": 1, "words": "top nibble 0..11 SCORE (8 bins x 4 bits, sensor 7 in the top nibble), 12 LOAD (class [24], addr [22:16], weight [7:0]), 13 BIAS [15:0]; result {pred, 3'b0, s1[11:0] at 27:16, s0[11:0] at 11:0}"},
              open(os.path.join(out, "lanes.json"), "w"), indent=1)
if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--output", required=True); ap.add_argument("--sd-fast-div", type=int, default=2); a = ap.parse_args()
    build(a.output, a.sd_fast_div); print("wrote", a.output)
