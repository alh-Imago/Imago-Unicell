#!/usr/bin/env python3
"""kintex_freeze_pack_v2.py -- builds fpga/kintex7_tests/k7_freeze_dbg/ (ledger #1247). Clone of the v1 freeze kit (tools/kintex_freeze_pack_v1.py, #1243) with the
HIDDEN state of every cell added to the scan: the cells are the debug clones made by tools/cell_debug_clone_v1.py (adder_cell_v4f / ram_cell_v4d and their shells),
which bring out a_reg, out_buffer / data_reg, init_data, addon_config, masks, pending_ack and the flags on one extra port. The scan is now 84 words (2688 bits):
  words 0..31   exactly as v1 (header, then the cells' visible state)     words 32..83  13 cells x 4 words of hidden state (cell n at 32+4n .. 35+4n)
"""
import json
import os
import re
import shutil
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kintex_freeze_pack_v1 as p1  # noqa: E402

ROOT = p1.ROOT
OUT = os.path.join(ROOT, "fpga", "kintex7_tests", "k7_freeze_dbg")
NAME = "k7_freeze_v2"
VDIR = os.path.join(ROOT, "fpga", "verilog")
NW = 84
CELLS = ["adder_cell_v4f", "adder_shell_v1f", "ram_cell_v4d", "ram_shell_v1d"]
ADDONS = ["adder_v1.sv", "invert_addon_v1.sv", "nibble_mask_addon_v1.sv", "shift_lane_addon_v1.sv"]


def rep(text, old, new, count=1):
    assert text.count(old) == count, (old, text.count(old))
    return text.replace(old, new)


def main():
    if os.path.isdir(OUT):
        for entry in os.listdir(OUT):
            if entry == "results":
                continue
            full = os.path.join(OUT, entry)
            shutil.rmtree(full) if os.path.isdir(full) else os.remove(full)
    os.makedirs(os.path.join(OUT, "rtl"), exist_ok=True)
    SRC = p1.SRC
    for f in ADDONS:
        shutil.copy(os.path.join(SRC, "rtl", f), os.path.join(OUT, "rtl", f))
    for c in CELLS:
        shutil.copy(os.path.join(VDIR, c + ".v"), os.path.join(OUT, "rtl", c + ".sv"))
    # grid: v1 transformation, then swap to the debug cells and bring out dbg
    grid, cells = p1.make_grid(open(os.path.join(SRC, "rtl", "std_tree4.sv")).read())
    grid = rep(grid, "adder_shell_v1e #(", "adder_shell_v1f #(", 3)
    grid = rep(grid, "ram_shell_v1 #(", "ram_shell_v1d #(", 10)
    grid = re.sub(r"\.status_data_valid\(sdv\[(\d+)\]\)", lambda m: ".dbg_state(dbg[%s*128 +: 128]), .status_data_valid(sdv[%s])" % (m.group(1), m.group(1)), grid)
    assert grid.count(".dbg_state(") == 13
    grid = rep(grid, "input  wire freeze, output wire [831:0] snap", "input  wire freeze, output wire [831:0] snap, output wire [1663:0] dbg")
    open(os.path.join(OUT, "rtl", "std_tree4_frz.sv"), "w").write(
        "// std_tree4_frz.sv (v2) -- GENERATED by tools/kintex_freeze_pack_v2.py (ledger #1247) from std_tree4.sv (Tang grid, ledger #1116): freeze line, snapshot port, and hidden-state port from the debug cells.\n" + grid)
    rows, exp, want = p1.load_schedule(open(os.path.join(SRC, "rtl", "board_top_std_tree4.sv")).read())
    case = "\n".join("        8'd%s: begin lt_ = 32'd%s; lc_ = 16'd%s; lw_ = 32'd%s; end" % r for r in rows)
    # top
    top = p1.TOP_V
    top = rep(top, "reg [1023:0] jsr = 1024'd0;", "reg [2687:0] jsr = 2688'd0;")
    top = rep(top, "wire [1023:0] jsnap;", "wire [2687:0] jsnap;")
    top = rep(top, "jsr <= {j_tdi, jsr[1023:1]};", "jsr <= {j_tdi, jsr[2687:1]};")
    top = rep(top, "wire [831:0] snap;", "wire [831:0] snap; wire [1663:0] dbg;")
    top = rep(top, ".freeze(frozen), .snap(snap));", ".freeze(frozen), .snap(snap), .dbg(dbg));")
    top = rep(top, "assign jsnap = {snap, T_lat, lastw, sig, hw2, t, 32'h46525A31};", "assign jsnap = {dbg, snap, T_lat, lastw, sig, hw2, t, 32'h46525A32};")
    top = rep(top, "// Freeze-and-read of the Tang std_tree4 grid on the Kintex card (XC7K480T), over JTAG USER1 (BSCANE2, 1024-bit register).",
              "// Freeze-and-read (v2, hidden state) of the Tang std_tree4 grid on the Kintex card (XC7K480T), over JTAG USER1 (BSCANE2, 2688-bit register).\n"
              "// words 32..83: the HIDDEN state of the 13 cells, 4 words each (cell n at 32+4n..35+4n), from the debug cells (layout in tools/cell_debug_clone_v1.py).\n"
              "// Magic word 0 is 'FRZ2' (0x46525A32).")
    top = rep(top, "// SCAN LAYOUT (LSB first, 32 words of 32 bits; word 0 leaves first)", "// SCAN LAYOUT (LSB first, 84 words of 32 bits; word 0 leaves first)")
    top = top.replace("46525A31", "46525A32").replace("(\"FRZ1\")", "(\"FRZ2\")")
    top = top.replace("NAME", NAME).replace("LOADROWS", case).replace("NLOADS", str(len(rows))).replace("NWANT", str(want))
    open(os.path.join(OUT, NAME + ".v"), "w").write(top)
    # testbench
    tb = p1.TB
    tb = rep(tb, "    reg [831:0] ref_snap [0:2200];", "    reg [831:0] ref_snap [0:2200];\n    reg [1663:0] ref_dbg [0:2200];\n    reg [1663:0] got_dbg;")
    tb = rep(tb, "if (B.started && B.t < 2200) ref_snap[B.t] <= B.dut.snap;", "if (B.started && B.t < 2200) begin ref_snap[B.t] <= B.dut.snap; ref_dbg[B.t] <= B.dut.dbg; end")
    tb = tb.replace("[1023:0]", "[2687:0]").replace("1024'd0", "2688'd0").replace("i < 1024", "i < 2688")
    tb = tb.replace("46525A31", "46525A32")
    tb = rep(tb, "            got = rx[1023:192];".replace("1023", "1023"), "            got = rx[1023:192]; got_dbg = rx[2687:1024];\n"
                                                                      "            check(got_dbg === ref_dbg[T+1], \"hidden state equals the free-running reference at T+1\");")
    tb = rep(tb, '            check(rx[1023:192] === got, "frozen state is steady between reads");',
             '            check(rx[1023:192] === got && rx[2687:1024] === got_dbg, "frozen state (visible and hidden) is steady between reads");')
    tb = rep(tb, '        check(rx[88] === 1\'b0, "not frozen");',
             '''        check(rx[88] === 1'b0, "not frozen");
        // layout check of the hidden words against the configuration the Tang schedule loads (independent of the reference copy)
        check(rx[1024 + 128*9 + 64 +: 6] === 6'd2 && rx[1024 + 128*9 + 64 + 6 +: 6] === 6'd9, "cell 9 (adder) masks: downstream 2, upstream 9");
        check(rx[1024 + 128*9 + 96 + 3] === 1'b1, "cell 9 join_mode flag set");
        check(rx[1024 + 128*11 + 64 +: 6] === 6'd4, "cell 11 (adder) downstream mask 4");
        check(rx[1024 + 128*12 + 96 + 6 +: 6] === 6'd8 && rx[1024 + 128*12 + 96 + 17] === 1'b1, "cell 12 (exit ram) upstream mask 8 and fixed_mode");
        check(rx[1024 + 128*12 +: 32] === expm[5], "cell 12 data_reg holds the last result");
        check(rx[1024 + 128*0 +: 32] === 32'h80000288, "cell 0 (lane_0.in) data_reg holds the last word loaded into it (2147484296)");''')
    tb = rep(tb, "input [255:0] what", "input [1023:0] what")
    tb = tb.replace("tb_NAME", "tb_" + NAME)
    tb = tb.replace("NAME", NAME).replace("EXPINIT", "\n".join("        expm[%s] = 32'h%s;" % e for e in exp[:8]))
    open(os.path.join(OUT, "tb_%s.v" % NAME), "w").write(tb)
    # board files
    shutil.copy(os.path.join(SRC, "k7_tree4_jtag_v1.xdc"), os.path.join(OUT, NAME + ".xdc"))
    shutil.copy(os.path.join(SRC, "k7_ft232h.cfg"), os.path.join(OUT, "k7_ft232h.cfg"))
    srcs = " ".join("rtl/" + f for f in ["std_tree4_frz.sv"] + [c + ".sv" for c in CELLS] + ADDONS)
    mk = open(os.path.join(SRC, "Makefile")).read()
    mk = re.sub(r"ADDITIONAL_SOURCES = .*", "ADDITIONAL_SOURCES = " + srcs, mk)
    mk = mk.replace("k7_tree4_jtag_v1", NAME)
    mk = re.sub(r"sim:\n.*", "sim:\n\tiverilog -g2012 -o sim.vvp tb_%s.v %s.v %s && vvp sim.vvp" % (NAME, NAME, srcs), mk, flags=re.S)
    mk = mk.replace("# k7_tree4_jtag_v1: self-check of the Tang std_tree4 design on the Kintex card, through the openXC7 flow.",
                    "# %s: freeze the Tang std_tree4 grid on the Kintex card and read the cells' VISIBLE AND HIDDEN state over JTAG (ledger #1247)." % NAME)
    open(os.path.join(OUT, "Makefile"), "w").write(mk)
    json.dump([{"cell": n, "name": c.split(" (")[0].strip(), "kind": k, "comment": c} for n, c, k in cells], open(os.path.join(OUT, "cells.json"), "w"), indent=1)
    tcl = p1.TCL.replace("{$i < 32}", "{$i < %d}" % NW).replace("Every scan is 32 words of 32 bits.", "Every scan is %d words of 32 bits." % NW)
    assert "$i < %d" % NW in tcl
    files = [("freeze_lib.tcl", tcl), ("freeze_read.sh", p1.SH_READ), ("freeze_at.sh", p1.SH_AT), ("freeze_release.sh", p1.SH_REL),
             ("freeze_sweep.sh", p1.SH_SWEEP), ("freeze_busy.sh", p1.SH_BUSY), ("decode_freeze.py", DECODE), ("README.md", README)]
    for fn, txt in files:
        open(os.path.join(OUT, fn), "w").write(txt)
    print("wrote", OUT)


DECODE = r'''#!/usr/bin/env python3
"""decode_freeze.py LOG [CSV] -- decode "SNAP <T> <84 words>" lines (v2: visible AND hidden cell state). Layouts: k7_freeze_v2.v and tools/cell_debug_clone_v1.py."""
import json
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
cells = json.load(open(os.path.join(here, "cells.json")))
text = open(sys.argv[1]).read()
csv = open(sys.argv[2], "w") if len(sys.argv) > 2 else None
if csv:
    csv.write("T_asked,t_held,frozen,cell,name,kind,word_hex,fire_nsew,data_valid,a_arrived,"
              "hid0_hex,hid1_hex,hid2_hex,hid3_hex,down_mask,up_mask,pending_ack,armed,flags_hex\n")
found = 0
for m in re.finditer(r"SNAP\s+(\S+)\s+((?:[0-9a-fA-F]{8}\s*){84})", text):
    found += 1
    T = m.group(1)
    w = [int(x, 16) for x in m.group(2).split()]
    magic, t, fl, sig, last, tl = w[:6]
    frozen = (fl >> 24) & 1
    print("T asked %s: magic %08X %s | run count t=%d | frozen=%d | results so far %d | run %d | signature %08X | last result %08X | T in force %08X"
          % (T, magic, "OK" if magic == 0x46525A32 else "WRONG", t, frozen, fl & 0xFFFF, (fl >> 16) & 0xFF, sig, last, tl))
    for c in cells:
        n = c["cell"]
        word, st = w[6 + 2 * n], w[7 + 2 * n]
        h0, h1, h2, h3 = w[32 + 4 * n: 36 + 4 * n]
        fire = format((st >> 2) & 0xF, "04b")
        dv, aa = (st >> 1) & 1, st & 1
        if c["kind"] == "adder":
            down, up, sdown, pend = h2 & 63, (h2 >> 6) & 63, (h2 >> 12) & 63, (h2 >> 18) & 15
            flags = [x for x, b in (("a_arrived", 0), ("data_valid", 1), ("subtract", 2), ("join", 3), ("second_output", 4), ("carry_held", 5),
                                      ("delivering_carry", 6), ("phase1_offered", 7), ("armed", 8), ("prog_done", 9)) if (h3 >> b) & 1]
            armed = (h3 >> 8) & 1
            hid = "a_reg %08X  out_buffer %08X  down %02d up %02d 2nd_down %02d pend %s  [%s]" % (h0, h1, down, up, sdown, format(pend, "04b"), " ".join(flags))
        else:
            down, up, pend = h3 & 63, (h3 >> 6) & 63, (h3 >> 12) & 15
            flags = [x for x, b in (("data_valid", 16), ("fixed", 17), ("armed", 18), ("prog_done", 19)) if (h3 >> b) & 1]
            armed = (h3 >> 18) & 1
            hid = "data_reg %08X  init %08X  addon %05X  down %02d up %02d pend %s  [%s]" % (h0, h1, h2 & 0xFFFFF, down, up, format(pend, "04b"), " ".join(flags))
        print("   C%-2d %-16s %-5s out %08X fire=%s dv=%d aa=%d | %s" % (n, c["name"], c["kind"], word, format((st >> 2) & 0xF, "04b"), dv, aa, hid))
        if csv:
            csv.write("%s,%d,%d,%d,%s,%s,%08X,%s,%d,%d,%08X,%08X,%08X,%08X,%d,%d,%s,%d,%s\n" % (
                T, t, frozen, n, c["name"], c["kind"], word, fire, dv, aa, h0, h1, h2, h3, down, up, format(pend, "04b"), armed, " ".join(flags)))
if not found:
    sys.exit("no SNAP lines with 84 words found in the log")
'''

README = r"""# k7_freeze_v2 -- freeze the Tang tree on the Kintex card and read the cells' VISIBLE AND HIDDEN state over JTAG (ledger #1247)

Clone of the freeze kit k7_freeze (#1243-#1246, proven on the card: 341 frames equal to the simulation). Same driver, same freeze, same commands; the
differences are the cells and the size of the scan.

**New: the hidden state.** The cells are debug clones (`adder_cell_v4f`, `ram_cell_v4d` and their shells; made by `tools/cell_debug_clone_v1.py`,
behaviour identical, one extra output port each). For each of the 13 cells the scan now carries, besides the visible output word and flags:
* **adder:** the waiting first operand `a_reg`, `out_buffer`, downstream / upstream / second-downstream masks, `pending_ack`, subtract / join / second-output flags, carry state, phase, `armed`.
* **RAM:** the stored word `data_reg`, `init_data`, the 20-bit `addon_config`, the masks, `pending_ack`, `data_valid`, `fixed_mode`, `armed`.
Still not read: the shell's own wiring (combinational) and anything outside the 13 cells (the driver's counters are in the header words).

## Do this (same as the earlier kit; this is a different folder and a different bitstream)
1. Copy this folder into `demo-projects` (next to `k7_freeze`, so `../openXC7.mk` is found). In the openXC7 Nix shell: `make`, then `make program JTAG_LINK="-c ft232"`.
2. From a **plain terminal**, in this folder, one command per line:
   * `nix shell nixpkgs#openocd --command sh freeze_read.sh`           (pure read; expects magic 46525A32 "FRZ2")
   * `nix shell nixpkgs#openocd --command sh freeze_at.sh 346`
   * `nix shell nixpkgs#openocd --command sh freeze_release.sh`
   * `nix shell nixpkgs#openocd --command sh freeze_sweep.sh 0 1700 5`   (writes sweep.csv with the hidden columns)
   * `nix shell nixpkgs#openocd --command sh freeze_busy.sh`              (every count over the busy stretches)
3. Send back the logs / csv files.

## Checked in simulation (not on the card)
`make sim` (iverilog): the frozen snapshot, visible and hidden, equals an unfrozen copy at count T+1 at 24 counts; the hidden words agree with the configuration the
Tang schedule loads (adder masks 2 / 9 / 4, join mode, the exit cell's fixed mode and upstream mask 8, the exit word); release finishes the run with the Tang's signature.
"""

if __name__ == "__main__":
    main()
