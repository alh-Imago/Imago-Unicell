def sim_host(work, files, ph, cpb=8, nocfg=False):
    """A testbench that plays the PC: for each phase it sends the C frame and the D frame over the serial line and checks every reply against the Python-computed word."""
    tasks = []
    for i, p in enumerate(ph):
        cfgw = (p[3] << 135) | (p[2] << 5) | p[1]
        cb = " ".join(f"sendb(8'h{(cfgw >> (8 * (19 - j))) & 0xFF:02X});" for j in range(20))
        db = " ".join(f"sendb(8'h{(w >> (8 * (3 - j))) & 0xFF:02X});" for w in (A_WORD, B_WORD) for j in range(4))
        cframe = "" if (nocfg and i > 0) else f"sendb(8'h43); {cb} getb(rb); if (rb !== 8'h4B) begin bad = bad + 1; $display(\"phase {i}: no K (got %02X)\", rb); end"
        tasks.append(f"    {cframe}\n    sendb(8'h44); {db} getb(rb); got = 0;\n"
                     f"    if (rb !== 8'h52) begin bad = bad + 1; $display(\"phase {i}: no R (got %02X)\", rb); end else begin getb(rb); got[31:24] = rb; getb(rb); got[23:16] = rb; getb(rb); got[15:8] = rb; getb(rb); got[7:0] = rb;\n"
                     f"      $display(\"phase {i} {p[0]}: got %08X want {p[4]:08X} %s\", got, (got == 32'h{p[4]:08X}) ? \"ok\" : \"WRONG\"); if (got != 32'h{p[4]:08X}) bad = bad + 1; end")
    tb = f"""`timescale 1ns/1ps
module tbh;
  reg clk = 0; reg rx = 1; wire tx, l0, l1, l2, l3;
  board_top_{NAME}h #(.CPB({cpb})) dut (.BOARD_CLK(clk), .UART_RX(rx), .UART_TX(tx), .LED0_N(l0), .LED1_N(l1), .LED2_N(l2), .LED3_N(l3));
  always #5 clk = ~clk;
  integer bad = 0; reg [7:0] rb; reg [31:0] got;
  task sendb(input [7:0] b); integer i; begin
    rx = 0; repeat ({cpb}) @(posedge clk);
    for (i = 0; i < 8; i = i + 1) begin rx = b[i]; repeat ({cpb}) @(posedge clk); end
    rx = 1; repeat ({cpb} * 2) @(posedge clk); end endtask
  task getb(output [7:0] b); integer i; begin
    @(negedge tx); repeat ({cpb} + {cpb} / 2) @(posedge clk); b = 0;
    for (i = 0; i < 8; i = i + 1) begin b[i] = tx; repeat ({cpb}) @(posedge clk); end end endtask
  initial begin
    repeat (400) @(posedge clk);
{chr(10).join(tasks)}
    if (bad == 0) $display("UCMH PASS"); else $display("UCMH FAIL %0d", bad);
    $finish;
  end
  initial begin #2000000000; $display("SIMTIMEOUT"); $finish; end
endmodule
"""
    open(os.path.join(work, "tbh.v"), "w").write(tb)
    c = subprocess.run(["iverilog", "-g2012", "-o", "tbh.vvp", "tbh.v"] + files, cwd=work, capture_output=True, text=True)
    if c.returncode:
        raise SystemExit("iverilog: " + c.stderr[:800])
    return subprocess.run(["vvp", "tbh.vvp"], cwd=work, capture_output=True, text=True, timeout=3000).stdout


def simulate(work, files):
    tb = f"""`timescale 1ns/1ps
module tbb;
  reg clk = 0; wire tx, l0, l1, l2, l3;
  board_top_{NAME} #(.CPB(8), .SETTLE(2000)) dut (.BOARD_CLK(clk), .UART_TX(tx), .LED0_N(l0), .LED1_N(l1), .LED2_N(l2), .LED3_N(l3));
  always #5 clk = ~clk;
  reg [7:0] b; integer i, lines = 0;
  initial begin
    forever begin
      @(negedge tx);
      repeat (4) @(posedge clk);
      for (i = 0; i < 8; i = i + 1) begin repeat (8) @(posedge clk); b[i] = tx; end
      repeat (8) @(posedge clk);
      $write("%c", b);
      if (b == 8'h0A) begin lines = lines + 1; if (lines >= 2) $finish; end
    end
  end
  initial begin #400000000; $display("SIMTIMEOUT"); $finish; end
endmodule
"""
    open(os.path.join(work, "tbb.v"), "w").write(tb)
    c = subprocess.run(["iverilog", "-g2012", "-o", "tbb.vvp", "tbb.v"] + files, cwd=work, capture_output=True, text=True)
    if c.returncode:
        raise SystemExit("iverilog: " + c.stderr[:800])
    return subprocess.run(["vvp", "tbb.vvp"], cwd=work, capture_output=True, text=True, timeout=3000).stdout


def cst_host():
    return bt.cst() + 'IO_LOC "UART_RX" 70;\nIO_PORT "UART_RX" IO_TYPE=LVCMOS33 PULL_MODE=UP;\n'


def pnr_and_pack(work, out, name, top, files, seed, meta):
    s = subprocess.run(["yosys", "-q", "-p", f"read_verilog -sv {' '.join(files)}; hierarchy -check -top {top}; synth_gowin -top {top} -nowidelut -json {name}.json; tee -o {name}.stat stat"],
                       cwd=work, capture_output=True, text=True, timeout=3000)
    if s.returncode:
        raise SystemExit("yosys: " + s.stderr[-600:])
    p = subprocess.run(["yowasp-nextpnr-himbaechel-gowin", "--device", bt.DEVICE, "--vopt", "family=GW2A-18C", "--vopt", f"cst={name}.cst", "--seed", str(seed), "--json", f"{name}.json",
                        "--write", f"{name}_r.json", "--report", f"{name}_rep.json", "--freq", "27"], cwd=work, capture_output=True, text=True, timeout=6000)
    open(os.path.join(out, name + ".pnr.log"), "w").write(p.stdout[-6000:] + p.stderr[-6000:])
    if p.returncode:
        raise SystemExit("nextpnr: " + p.stderr[-800:])
    rep = json.load(open(os.path.join(work, name + "_rep.json")))
    fmax = rep["fmax"]["clk"]["achieved"] if "clk" in rep["fmax"] else min(v["achieved"] for v in rep["fmax"].values())
    u = rep["utilization"]
    meta.update(fmax_mhz=round(fmax, 1), utilization={k: dict(used=v["used"], available=v["available"]) for k, v in u.items() if v.get("used")})
    print("%s: place and route Fmax %.1f MHz (target 27); used: %s" % (name, fmax, {k: "%d/%d" % (v["used"], v["available"]) for k, v in u.items() if v.get("used")}))
    if fmax < 27:
        raise SystemExit("timing NOT met at 27 MHz; no bitstream written")
    g = subprocess.run(["gowin_pack", "-d", bt.DEVICE, "-o", os.path.join(out, name + ".fs"), "-s", os.path.join(work, name + ".cst"), f"{name}_r.json"], cwd=work, capture_output=True, text=True)
    if g.returncode:
        raise SystemExit("gowin_pack: " + g.stderr[-500:])
    print("bitstream:", os.path.join(out, name + ".fs"))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "board_tests_mutability"))
    ap.add_argument("--keep", default="adder,accum,mul")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--no-pnr", action="store_true")
    ap.add_argument("--only", choices=["self", "host"], help="build just one of the two bitstreams")
    ap.add_argument("--mutant", default="none", choices=["none", "nocfg", "wrongexp"], help="simulation self-check only: break the test on purpose and confirm it reports FAIL (nothing is written)")
    a = ap.parse_args()
    keep = [k for k in a.keep.split(",") if k]
    if "adder" not in keep or "mul" not in keep:
        raise SystemExit("this test needs the adder and the mul in the carrier")
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    work = os.path.join(out, "_work")
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(work)
    ph = phases()
    if a.mutant == "wrongexp":
        ph[2] = ph[2][:4] + (ph[2][4] ^ 1,)
    carrier_v, removed = sub.make(keep)
    open(os.path.join(work, "carrier_sub.v"), "w").write(carrier_v)
    open(os.path.join(work, "board_uart_tx.v"), "w").write(bt.UART_V)
    open(os.path.join(work, "board_uart_rx.v"), "w").write(UART_RX_V)
    deps = vd.deps("unicell_vix_carrier_v1m", [work, os.path.join(ROOT, "fpga", "verilog")])
    meta = dict(name=NAME, cores_in_carrier=sorted(keep), cores_removed=removed, operands=[A_WORD, B_WORD],
                phases=[dict(label=p[0], core_select=p[1], core_cfg=p[2], addon_cfg=p[3], expected=p[4],
                             cfg_word_hex="%040X" % ((p[3] << 135) | (p[2] << 5) | p[1])) for p in ph])
    ok = True
    variants = [v for v in ("self", "host") if a.only in (None, v)]
    if "self" in variants:
        top = "board_top_" + NAME
        open(os.path.join(work, top + ".v"), "w").write(wrapper(ph, bt.CPB, bt.SETTLE, mutant=a.mutant if a.mutant != "wrongexp" else "none"))
        files = [os.path.join(work, "board_uart_tx.v"), os.path.join(work, top + ".v")] + deps
        sim = simulate(work, files)
        line = next((l for l in sim.splitlines() if l.startswith("UCM")), "")
        print("self-running, simulated:", line.strip() or sim[-400:])
        if a.mutant != "none":
            caught = " res=F " in line + " "
            print("  MUTANT %s -> %s" % (a.mutant, "caught (FAIL reported)" if caught else "NOT CAUGHT"))
            ok = ok and caught
        else:
            if " res=P " not in line + " ":
                raise SystemExit("the self-running wrapper did NOT pass in simulation; no bitstream written")
            meta["self_sim_line"] = line.strip()
            open(os.path.join(out, NAME + ".cst"), "w").write(bt.cst())
            shutil.copy(os.path.join(out, NAME + ".cst"), os.path.join(work, NAME + ".cst"))
            shutil.copy(os.path.join(work, top + ".v"), os.path.join(out, NAME + ".v"))
            if not a.no_pnr:
                pnr_and_pack(work, out, NAME, top, files, a.seed, meta.setdefault("self_build", {}))
    if "host" in variants:
        name = NAME + "h"
        top = "board_top_" + name
        open(os.path.join(work, top + ".v"), "w").write(wrapper_host(bt.CPB))
        files = [os.path.join(work, "board_uart_tx.v"), os.path.join(work, "board_uart_rx.v"), os.path.join(work, top + ".v")] + deps
        sim = sim_host(work, files, ph, nocfg=(a.mutant == "nocfg"))
        verdict = next((l for l in sim.splitlines() if l.startswith("UCMH")), "no verdict: " + sim[-300:])
        print("host-driven, simulated (the testbench plays the PC):")
        print("  " + "\n  ".join(l for l in sim.splitlines() if l.startswith("phase")))
        print("  " + verdict)
        if a.mutant != "none":
            caught = "FAIL" in verdict
            print("  MUTANT %s -> %s" % (a.mutant, "caught (FAIL reported)" if caught else "NOT CAUGHT"))
            ok = ok and caught
        else:
            if "PASS" not in verdict:
                raise SystemExit("the host-driven wrapper did NOT pass in simulation; no bitstream written")
            meta["host_sim"] = verdict
            open(os.path.join(out, name + ".cst"), "w").write(cst_host())
            shutil.copy(os.path.join(out, name + ".cst"), os.path.join(work, name + ".cst"))
            shutil.copy(os.path.join(work, top + ".v"), os.path.join(out, name + ".v"))
            if not a.no_pnr:
                pnr_and_pack(work, out, name, top, files, a.seed, meta.setdefault("host_build", {}))
    if a.mutant == "none":
        json.dump(meta, open(os.path.join(out, NAME + ".json"), "w"), indent=1)
        shutil.copy(os.path.join(work, "carrier_sub.v"), os.path.join(out, "unicell_vix_carrier_v1m.v"))
    shutil.rmtree(work, ignore_errors=True)
    if not ok:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
