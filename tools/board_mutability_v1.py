NAME = "mutability1"
A_WORD, B_WORD = 0x12345600, 0x78
M32 = 0xFFFFFFFF
SEL_ADDER, SEL_MUL = 1, 9
DOWN_E, UP_N = 0b000100, 0b000001
BASE = DOWN_E | (UP_N << 6)               # adder / mul cfg: downstream east, upstream north


def addon(en_shift=0, right=0, amt=0, mask_en=0, nib=0, inv=0):
    return (en_shift << 14) | (right << 15) | (amt << 9) | (mask_en << 8) | nib | (inv << 19)


def phases():
    """(label, core_select, core_cfg128, addon20, expected word). Expected values come from the operands, not from any simulation of the hardware."""
    s = (A_WORD + B_WORD) & M32
    keep = ~(0xFF) & M32                                         # nibbles 0 and 1 zeroed
    return [
        ("adder add", SEL_ADDER, BASE, 0, s),
        ("adder subtract", SEL_ADDER, BASE | (1 << 12), 0, (A_WORD - B_WORD) & M32),
        ("add + invert", SEL_ADDER, BASE, addon(inv=1), (~s) & M32),
        ("add + shift right 8", SEL_ADDER, BASE, addon(en_shift=1, right=1, amt=8), s >> 8),
        ("add + nibble mask 03", SEL_ADDER, BASE, addon(mask_en=1, nib=0x03), s & keep),
        ("core changed to mul", SEL_MUL, BASE, 0, (A_WORD * B_WORD) & M32),
        ("back to adder add", SEL_ADDER, BASE, 0, s),
    ]


