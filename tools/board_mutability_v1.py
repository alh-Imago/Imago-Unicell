"""tools/board_mutability_v1.py -- ledger #1086: TEST 1 of the mutability proof for the Tang Nano 20K (Alan, 12 Oct 2026).

The question: can ONE bitstream be reconfigured while it is running, without re-synthesising, so that the SAME input data gives a DIFFERENT result because the core's
configuration changed?  The device under test is the VIX carrier cut down to the maths cores (tools/make_carrier_subset_v1.py; the full carrier is far bigger), wrapped in a small
self-checking sequencer. After power-up the sequencer runs seven phases on that one bitstream. Every phase writes a new carrier configuration (the live cfg path: cfg_valid +
cfg_data[159:0], the same one the carrier testbenches use), sends the SAME two operands (A = 0x12345600, then B = 0x78) in on the north face, takes the result from the east face, and
stores it:

  0  adder, add                         -> A + B           (the first core, as the first test asks)
  1  adder, subtract mode               -> A - B           (core setting changed)
  2  adder, add, add-on INVERT          -> ~(A + B)        (shared add-on chain changed)
  3  adder, add, add-on SHIFT RIGHT 8   -> (A + B) >> 8
  4  adder, add, add-on NIBBLE MASK     -> (A + B) with nibbles 0 and 1 zeroed
  5  the core itself changed to MUL     -> low word of A * B
  6  back to the adder, add (as phase 0)-> A + B again: the change is reversible

The expected words are computed here in Python from the operands, never read from the hardware. The wrapper compares each stored result with its expected word and prints ONE line on the
USB serial port (pin 69, 115200 baud, repeated); LEDs: LED1 on = all seven right, LED2 on = a phase was wrong or timed out, LED3 on = finished (LEDs are active low).

  python3 tools/board_mutability_v1.py [--out DIR] [--keep adder,accum,mul] [--seed N] [--no-pnr]
"""
