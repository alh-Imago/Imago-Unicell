def make_grid(src_text):
    """Return (new grid text, [(cell index, name comment, kind)])."""
    text = src_text.replace("module std_tree4 (", "module std_tree4_frz (", 1)
    text = text.replace("    output wire [15:0] ext_fire, output wire [511:0] ext_data_out\n);",
                        "    output wire [15:0] ext_fire, output wire [511:0] ext_data_out,\n"
                        "    input  wire freeze, output wire [831:0] snap\n);\n"
                        "    wire [12:0] sdv; wire [12:0] saa;", 1)
    assert "input  wire freeze" in text
    text = text.replace(".freeze_in_n(1'b0)", ".freeze_in_n(freeze)")
    pat = re.compile(r"(ram_shell_v1|adder_shell_v1e) #\(\.CELL_ID\(16'h([0-9a-f]+)\)\) C(\d+) \(   // ([^\n]*)\n")
    parts = pat.split(text)
    out = [parts[0]]
    cells = []
    extra = []
    i = 1
    while i < len(parts):
        kind, hexid, num, comment, body = parts[i:i + 5]
        n = int(num)
        assert int(hexid, 16) == n
        body = body.replace(".status_data_valid()", ".status_data_valid(sdv[%d])" % n, 1)
        if ".status_a_arrived()" in body:
            body = body.replace(".status_a_arrived()", ".status_a_arrived(saa[%d])" % n, 1)
        else:
            extra.append("    assign saa[%d] = 1'b0;\n" % n)
        out.append("%s #(.CELL_ID(16'h%s)) C%s (   // %s\n%s" % (kind, hexid, num, comment, body))
        cells.append((n, comment, "adder" if kind == "adder_shell_v1e" else "ram"))
        i += 5
    text = "".join(out)
    assert len(cells) == 13
    snap = "    assign snap = {" + ", ".join(
        "{26'b0, f%d_n, f%d_s, f%d_e, f%d_w, sdv[%d], saa[%d]}, d%d_n" % (n, n, n, n, n, n, n) for n in range(12, -1, -1)) + "};\n"
    # snap slot n: bits [64n+31:64n] = d_n, [64n+63:64n+32] = status word
    text = text.replace("endmodule", "".join(extra) + snap + "endmodule")
    return text, cells


def load_schedule(board_top_text):
    rows = re.findall(r"8'd(\d+): begin lt = 32'd(\d+); lc = 16'd(\d+); lw = 32'd(\d+); end", board_top_text)
    exp = re.findall(r"expm\[(\d+)\] = 32'h([0-9A-Fa-f]+)", board_top_text)
    want = re.search(r"wire \[15:0\] want = 16'd(\d+);", board_top_text)
    return rows, exp, int(want.group(1))


