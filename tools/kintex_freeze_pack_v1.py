def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(os.path.join(OUT, "rtl"))
    # cell files and the Tang grid / top, unchanged copies from the previous kit (same files that ran on the card)
    for f in CELL_FILES:
        shutil.copy(os.path.join(SRC, "rtl", f), os.path.join(OUT, "rtl", f))
    grid_src = open(os.path.join(SRC, "rtl", "std_tree4.sv")).read()
    grid, cells = make_grid(grid_src)
    open(os.path.join(OUT, "rtl", "std_tree4_frz.sv"), "w").write(
        "// std_tree4_frz.sv -- GENERATED by tools/kintex_freeze_pack_v1.py (ledger #1243) from std_tree4.sv (Tang grid, ledger #1116): freeze line + snapshot port.\n"
        + grid)
    rows, exp, want = load_schedule(open(os.path.join(SRC, "rtl", "board_top_std_tree4.sv")).read())
    assert len(rows) == 24 and want == 6 and len(exp) >= 6, (len(rows), want, len(exp))
    case = "\n".join("        8'd%s: begin lt_ = 32'd%s; lc_ = 16'd%s; lw_ = 32'd%s; end" % r for r in rows)
    top = TOP_V.replace("NAME", NAME).replace("LOADROWS", case).replace("NLOADS", str(len(rows))).replace("NWANT", str(want))
    open(os.path.join(OUT, NAME + ".v"), "w").write(top)
    expinit = "\n".join("        expm[%s] = 32'h%s;" % e for e in exp[:8])
    open(os.path.join(OUT, "tb_%s.v" % NAME), "w").write(TB.replace("NAME", NAME).replace("EXPINIT", expinit))
    # board files from the previous kit
    shutil.copy(os.path.join(SRC, "k7_tree4_jtag_v1.xdc"), os.path.join(OUT, NAME + ".xdc"))
    shutil.copy(os.path.join(SRC, "k7_ft232h.cfg"), os.path.join(OUT, "k7_ft232h.cfg"))
    srcs = " ".join("rtl/" + f for f in ["std_tree4_frz.sv"] + CELL_FILES)
    mk = open(os.path.join(SRC, "Makefile")).read()
    mk = re.sub(r"ADDITIONAL_SOURCES = .*", "ADDITIONAL_SOURCES = " + srcs, mk)
    mk = mk.replace("k7_tree4_jtag_v1", NAME).replace("k7_tree4_jtag_v1.xdc", NAME + ".xdc")
    mk = re.sub(r"sim:\n.*", "sim:\n\tiverilog -g2012 -o sim.vvp tb_%s.v %s.v %s && vvp sim.vvp" % (NAME, NAME, srcs), mk, flags=re.S)
    mk = mk.replace("# k7_tree4_jtag_v1: self-check of the Tang std_tree4 design on the Kintex card, through the openXC7 flow.",
                    "# %s: freeze the Tang std_tree4 grid on the Kintex card and read its cells over JTAG (ledger #1243)." % NAME)
    open(os.path.join(OUT, "Makefile"), "w").write(mk)
    json.dump([{"cell": n, "name": c.split(" (")[0].strip(), "kind": k, "comment": c} for n, c, k in cells],
              open(os.path.join(OUT, "cells.json"), "w"), indent=1)
    for fn, txt in (("freeze_lib.tcl", TCL), ("freeze_read.sh", SH_READ), ("freeze_at.sh", SH_AT), ("freeze_release.sh", SH_REL),
                    ("freeze_sweep.sh", SH_SWEEP), ("decode_freeze.py", DECODE), ("README.md", README)):
        open(os.path.join(OUT, fn), "w").write(txt)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
