#!/usr/bin/env python3
"""kintex_carrier_scale_v1.py -- SIZE and SPEED test of the FULL VIXeN carrier on the Kintex-7 card (ledger #1319).

Makes one openXC7 project folder per size N: a grid of N complete VIXeN carriers (`unicell_vixen_v1`, every core in it), wired face to face like the real grids,
on the ypcb-00338 card pins (CLK, LED0-2). The Makefile has the same shape as the Bench's runner folders: copy or generate the folder INSIDE demo-projects
(next to blinky-ypcb003381p1, so ../openXC7.mk is found), then `make` in the openXC7 shell.

What it measures: how many full carriers place and route on the XC7K480T (the size test) and the clock nextpnr says the design can reach at each size (the speed
test). Both are nextpnr results, i.e. estimates: they are not a clock measured on the card, and the design is NOT a working program (see below).

How nothing gets optimised away (the point of the design): synthesis deletes logic that cannot matter. So every input of every cell comes from a free-running
pseudo-random source (core select and configuration included; the configuration word changes all the time, so no core can be pruned as "never selected"), and
EVERY output bit of every cell (the ones that do not feed a neighbour as well) is folded by XOR into one register per cell, then into the LEDs. The fold costs a few
LUTs per cell (reported by the generator's own count); the sources are shared by all cells.

Not a function test: the cells are being reconfigured at random all the time, so the LEDs are noise. This is only a size and timing build. Use `--check` to
make the generator elaborate one small grid with iverilog (does it compile and run) and synthesise it with yosys (do the LUTs grow with N).

  python3 tools/kintex_carrier_scale_v1.py --sizes 1,4,9,16 --demo ~/openFPGALoader/build/demo-projects [--mhz 100]
  python3 tools/kintex_carrier_scale_v1.py --check
"""
import argparse
import math
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import verilog_deps_v1 as vd

FACES = "nsew"
OPP = {"n": "s", "s": "n", "e": "w", "w": "e"}
DELTA = {"n": (-1, 0), "s": (1, 0), "e": (0, 1), "w": (0, -1)}
CARRIER = "unicell_vixen_v1"


def grid_shape(n):
    cols = max(1, math.ceil(math.sqrt(n)))
    rows = math.ceil(n / cols)
    return rows, cols


def top_verilog(n, name):
    rows, cols = grid_shape(n)
    pos = {}
    for i in range(n):
        pos[(i // cols, i % cols)] = i
    L = []
    w = L.append
    w("// SPDX-License-Identifier: CERN-OHL-P-2.0")
    w("// %s.v -- GENERATED by tools/kintex_carrier_scale_v1.py (ledger #1319); do not hand-edit." % name)
    w("// %d full %s carriers in a %d x %d grid (row-major, the last row may be short). Size / timing build only: all inputs are pseudo-random, so the LEDs are noise." % (n, CARRIER, rows, cols))
    w("`default_nettype none")
    w("")
    w("module top (input wire CLK, output wire LED0, output wire LED1, output wire LED2);")
    w("    // ---- pseudo-random sources (never constant, so no part of a carrier can be pruned) ----")
    w("    reg [159:0] cfgw = 160'h0123456789ABCDEF0123456789ABCDEF01234567;   // the configuration word, shifting all the time")
    w("    reg [63:0]  pr   = 64'hACE1ACE1DEADBEEF;")
    w("    reg [31:0]  cnt  = 32'd0;")
    w("    always @(posedge CLK) begin")
    w("        cfgw <= {cfgw[158:0], cfgw[159] ^ cfgw[157] ^ cfgw[156] ^ cfgw[151] ^ cnt[3]};")
    w("        pr   <= {pr[62:0], pr[63] ^ pr[62] ^ pr[60] ^ pr[59]};")
    w("        cnt  <= cnt + 32'd1;")
    w("    end")
    w("    reg rst_r = 1'b1;")
    w("    always @(posedge CLK) rst_r <= (cnt[7:4] == 4'd0) && (cnt[31:8] == 24'd0);   // reset only in the first 16 clocks")
    w("    wire rst = rst_r;")
    w("    wire cfg_valid = (cnt[7:0] == 8'd0) | pr[5];")
    w("    wire [31:0] src32 = pr[31:0] ^ {pr[63:32]};")
    w("")
    for i in range(n):
        w("    wire [31:0] d%d_n, d%d_s, d%d_e, d%d_w; wire f%d_n, f%d_s, f%d_e, f%d_w; wire a%d_n, a%d_s, a%d_e, a%d_w;" % ((i,) * 12))
    w("")
    ext_cnt = [0]
    fold_bits = []
    for i in range(n):
        r, c = i // cols, i % cols
        ins = []
        for f in FACES:
            dr, dc = DELTA[f]
            j = pos.get((r + dr, c + dc))
            if j is None:
                k = ext_cnt[0]
                ext_cnt[0] += 1
                rot = (k * 5) % 32
                ins.append(".data_in_%s({src32[%d:0], src32[31:%d]} ^ cfgw[%d +: 32]), .arrived_%s(pr[%d]), .ack_in_%s(pr[%d])" % (f, rot - 1 if rot else 0, rot if rot else 0, (k * 7) % 128, f, (k * 3) % 64, f, (k * 3 + 1) % 64))
                if rot == 0:   # the slice above would be wrong for rot 0; use the plain word
                    ins[-1] = ".data_in_%s(src32 ^ cfgw[%d +: 32]), .arrived_%s(pr[%d]), .ack_in_%s(pr[%d])" % (f, (k * 7) % 128, f, (k * 3) % 64, f, (k * 3 + 1) % 64)
            else:
                o = OPP[f]
                ins.append(".data_in_%s(d%d_%s), .arrived_%s(f%d_%s), .ack_in_%s(a%d_%s)" % (f, j, o, f, j, o, f, j, o))
        outs = []
        for f in FACES:
            outs.append(".data_out_%s(d%d_%s), .fire_%s(f%d_%s), .ack_out_%s(a%d_%s)" % (f, i, f, f, i, f, f, i, f))
        w("    // cell %d at (%d,%d)" % (i, r, c))
        w("    wire rdy%d, pdone%d; wire [4:0] cs%d;" % (i, i, i))
        w("    wire [3:0] fz%d, po%d, pa%d, pk%d; wire [31:0] pd%d_n, pd%d_s, pd%d_e, pd%d_w;" % ((i,) * 8))
        w("    %s #(.CELL_ID(16'h%04x)) C%d (" % (CARRIER, i, i))
        w("        .clk(CLK), .rst(rst),")
        w("        .active_in_n(pr[40]), .active_in_s(pr[41]), .active_in_e(pr[42]), .active_in_w(pr[43]),")
        w("        .freeze_in_n(pr[44] & pr[45] & pr[46]), .freeze_in_s(pr[47] & pr[48] & pr[49]), .freeze_in_e(pr[50] & pr[51] & pr[52]), .freeze_in_w(pr[53] & pr[54] & pr[55]),")
        w("        .cfg_valid(cfg_valid), .cfg_data(cfgw ^ {5{src32}}),")
        w("        " + ", ".join(ins) + ",")
        w("        " + ", ".join(outs) + ",")
        w("        .ready_out(rdy%d), .ready_in_n(pr[20]), .ready_in_s(pr[21]), .ready_in_e(pr[22]), .ready_in_w(pr[23])," % i)
        w("        .program_in(pr[56] & pr[57]), .program_done(pdone%d)," % i)
        w("        .prog_data_in_n(src32 ^ 32'h1), .prog_data_in_s(src32 ^ 32'h2), .prog_data_in_e(src32 ^ 32'h4), .prog_data_in_w(src32 ^ 32'h8),")
        w("        .prog_arrived_in_n(pr[10]), .prog_arrived_in_s(pr[11]), .prog_arrived_in_e(pr[12]), .prog_arrived_in_w(pr[13]),")
        w("        .prog_ack_out_n(pk%d[0]), .prog_ack_out_s(pk%d[1]), .prog_ack_out_e(pk%d[2]), .prog_ack_out_w(pk%d[3])," % ((i,) * 4))
        w("        .freeze_out_n(fz%d[0]), .freeze_out_s(fz%d[1]), .freeze_out_e(fz%d[2]), .freeze_out_w(fz%d[3])," % ((i,) * 4))
        w("        .program_out_n(po%d[0]), .program_out_s(po%d[1]), .program_out_e(po%d[2]), .program_out_w(po%d[3])," % ((i,) * 4))
        w("        .prog_data_out_n(pd%d_n), .prog_data_out_s(pd%d_s), .prog_data_out_e(pd%d_e), .prog_data_out_w(pd%d_w)," % ((i,) * 4))
        w("        .prog_arrived_out_n(pa%d[0]), .prog_arrived_out_s(pa%d[1]), .prog_arrived_out_e(pa%d[2]), .prog_arrived_out_w(pa%d[3])," % ((i,) * 4))
        w("        .prog_ack_in_n(pr[14]), .prog_ack_in_s(pr[15]), .prog_ack_in_e(pr[16]), .prog_ack_in_w(pr[17]),")
        w("        .status_core_select(cs%d)" % i)
        w("    );")
        # every output bit of this cell folded by XOR, registered (neighbour-facing outputs are folded too: they are real loads either way)
        w("    reg fold%d = 1'b0;" % i)
        w("    always @(posedge CLK) fold%d <= ^{rdy%d, pdone%d, cs%d, fz%d, po%d, pa%d, pk%d, pd%d_n, pd%d_s, pd%d_e, pd%d_w, d%d_n, d%d_s, d%d_e, d%d_w, f%d_n, f%d_s, f%d_e, f%d_w, a%d_n, a%d_s, a%d_e, a%d_w};" % (((i,) * 24)))
        fold_bits.append("fold%d" % i)
        w("")
    w("    // ---- the LEDs: the XOR of every cell's fold bit, a second copy a clock later, and a heartbeat ----")
    w("    reg all_fold = 1'b0, all_fold2 = 1'b0;")
    # a registered tree so the fold itself is not the critical path
    groups = [fold_bits[k:k + 32] for k in range(0, len(fold_bits), 32)]
    for g, grp in enumerate(groups):
        w("    reg gf%d = 1'b0; always @(posedge CLK) gf%d <= ^{%s};" % (g, g, ", ".join(grp)))
    w("    always @(posedge CLK) begin all_fold <= ^{%s}; all_fold2 <= all_fold; end" % ", ".join("gf%d" % g for g in range(len(groups))))
    w("    assign LED0 = all_fold;")
    w("    assign LED1 = all_fold2 ^ cnt[26];")
    w("    assign LED2 = cnt[25];")
    w("endmodule")
    return "\n".join(L) + "\n"


def make_folder(n, demo, mhz, name_prefix="k7_scale_vixen_n"):
    name = "%s%03d" % (name_prefix, n)
    out = os.path.join(demo, name)
    os.makedirs(out, exist_ok=True)
    files = vd.deps(CARRIER, [os.path.join(ROOT, "fpga", "verilog")])
    srcs = []
    for f in files:
        p = f if os.path.isabs(f) else os.path.join(ROOT, f)
        shutil.copy(p, os.path.join(out, os.path.basename(p)))
        srcs.append(os.path.basename(p))
    proj = "k7_scale_vixen_n%d" % n
    open(os.path.join(out, proj + ".v"), "w").write(top_verilog(n, proj))
    period = 1000.0 / mhz
    open(os.path.join(out, proj + ".xdc"), "w").write(
        "## GENERATED by tools/kintex_carrier_scale_v1.py (ledger #1319): pins as in the runner folders (docs/man/kintex7-ypcb00338.xdc)\n"
        "set_property PACKAGE_PIN AA28 [get_ports CLK]\nset_property IOSTANDARD LVCMOS18 [get_ports CLK]\n"
        "create_clock -period %.3f -name sys_clk [get_ports CLK]\n" % period
        + "".join("set_property PACKAGE_PIN %s [get_ports LED%d]\nset_property IOSTANDARD LVCMOS18 [get_ports LED%d]\n" % (pin, k, k)
                  for k, pin in enumerate(("P30", "M30", "N30"))))
    others = [s for s in srcs]
    open(os.path.join(out, "Makefile"), "w").write(
        "# GENERATED by tools/kintex_carrier_scale_v1.py (ledger #1319). SIZE / TIMING build of %d full %s carriers; the design is not a program.\n"
        "# Sits in demo-projects/ next to blinky-ypcb003381p1 (../openXC7.mk). In the openXC7 shell:  make   -- then read the nextpnr utilisation and Fmax lines in build.log.\n"
        "# Load it ONLY if you want to see it configure; it does nothing useful on the card. SRAM only, never the flash.\n"
        "FAMILY  = kintex7\nPART    = xc7k480tffg1156-1\nBOARD   = ypcb003381p1\nPROJECT = %s\nTOP_MODULE = top\nXDC     = %s.xdc\n"
        "ADDITIONAL_SOURCES = %s\nCHIPDB  = ${KINTEX7_CHIPDB}\nPYPY3  ?= python3\n\ninclude ../openXC7.mk\n"
        % (n, CARRIER, proj, proj, " ".join(others)))
    rows, cols = grid_shape(n)
    open(os.path.join(out, "kit.json"), "w").write(
        '{\n "title": "%s -- SIZE/SPEED build: %d full %s carriers (%d x %d), target %g MHz; no function, ledger #1319",\n "card_id": "ypcb-00338-1p1-xc7k480t-01",\n "flow": "openxc7",\n "runner": false\n}\n'
        % (proj, n, CARRIER, rows, cols, mhz))
    open(os.path.join(out, "README.md"), "w").write(
        "# %s -- size and speed build of %d full VIXeN carriers\n\nGenerated by tools/kintex_carrier_scale_v1.py (ledger #1319). A %d x %d grid of complete `%s` cells, face to face, "
        "every input pseudo-random, every output folded to the LEDs. It does no useful work; it exists to see whether N full carriers place and route on the XC7K480T and what clock nextpnr reports.\n\n"
        "Build: in the openXC7 shell, in this folder: `make 2>&1 | tee build.log`. Then `python3 tools/kintex_carrier_scale_report_v1.py <demo-projects folder>` in the repo prints the table.\n"
        "Clock target in the .xdc: %g MHz (a stretch target; the result that matters is the Fmax nextpnr prints for sys_clk).\n" % (proj, n, rows, cols, CARRIER, mhz))
    return out, proj


def check(n=4):
    import tempfile
    tmp = tempfile.mkdtemp(prefix="k7scale_")
    out, proj = make_folder(n, tmp, 100)
    srcs = sorted(f for f in os.listdir(out) if f.endswith(".v"))
    tb = os.path.join(tmp, "tb.v")
    open(tb, "w").write("`timescale 1ns/1ps\nmodule tb; reg clk=0; always #5 clk=~clk; wire a,b,c; top t(.CLK(clk),.LED0(a),.LED1(b),.LED2(c));\n"
                        " initial begin #200000; $display(\"RAN %b%b%b\", a, b, c); $finish; end endmodule\n")
    exe = os.path.join(tmp, "s.vvp")
    r = subprocess.run(["iverilog", "-g2012", "-o", exe, tb] + [os.path.join(out, s) for s in srcs], capture_output=True, text=True)
    print("iverilog:", "compiled" if r.returncode == 0 else "FAILED\n" + r.stderr[:1500])
    if r.returncode == 0:
        r2 = subprocess.run(["vvp", exe], capture_output=True, text=True, timeout=600)
        print("simulation:", r2.stdout.strip().splitlines()[-2:] if r2.stdout.strip() else "no output")
    if shutil.which("yosys"):
        res = {}
        for k in sorted({1, 2, n}):
            o2, p2 = make_folder(k, tmp, 100)
            fl = [os.path.join(o2, s) for s in sorted(f for f in os.listdir(o2) if f.endswith(".v"))]
            st = os.path.join(tmp, "s%d.stat" % k)
            rr = subprocess.run(["yosys", "-q", "-p", "read_verilog -sv %s ; hierarchy -top top ; synth_xilinx -family xc7 -top top -flatten -noiopad ; tee -o %s stat" % (" ".join(fl), st)], capture_output=True, text=True)
            if rr.returncode:
                print("yosys N=%d FAILED: %s" % (k, rr.stderr[-400:]))
                continue
            lut = 0
            ff = 0
            for ln in open(st):
                t = ln.split()
                if len(t) == 2 and t[1].startswith("LUT") and t[0].isdigit():
                    lut += int(t[0])
                if len(t) == 2 and t[1].startswith("FD") and t[0].isdigit():
                    ff += int(t[0])
                if len(t) == 2 and t[0].startswith("LUT") and t[1].isdigit():
                    lut += int(t[1])
                if len(t) == 2 and t[0].startswith("FD") and t[1].isdigit():
                    ff += int(t[1])
            res[k] = (lut, ff)
            print("yosys 0.33 synth N=%d: %d LUT, %d FF" % (k, lut, ff))
        if len(res) >= 2:
            ks = sorted(res)
            print("per extra cell: %.0f LUT" % ((res[ks[-1]][0] - res[ks[0]][0]) / (ks[-1] - ks[0])))
    print("scratch folder:", tmp)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--sizes", default="1,4,9,16", help="comma list of N")
    ap.add_argument("--demo", default=None, help="the demo-projects folder to make the project folders in")
    ap.add_argument("--mhz", type=float, default=100.0, help="clock target written to the .xdc (default 100)")
    ap.add_argument("--check", action="store_true", help="elaborate and synthesise small grids here")
    a = ap.parse_args()
    if a.check:
        check()
        return
    if not a.demo:
        ap.error("--demo FOLDER is required (the demo-projects folder)")
    for n in [int(x) for x in a.sizes.split(",") if x.strip()]:
        out, proj = make_folder(n, a.demo, a.mhz)
        print("made", out)


if __name__ == "__main__":
    main()
