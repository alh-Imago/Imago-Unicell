#!/usr/bin/env python3
"""tools/board_serial_probe_v2.py -- ledger #1131 (a clone of board_serial_probe_v1.py, #1130, which is kept as it was): a bitstream with NO cells in it that only measures the serial line to the PC (Alan 13 Oct: the serial side is vital for confirming a save/load cycle of a mid-flight capture, and "the serial side can corrupt that data").
It streams framed ASCII lines for ever:   UCP seq=XXXX d=W0,W1,...,W7 crc=CCCCCCCC\\r\\n
  seq = 16-bit frame counter; W0..W7 = a fixed mixing function of (seq, k) (host recomputes them); crc = standard CRC-32 (zlib.crc32) of the text from 'U' to the last word digit.
Two variants: `serial_probe2_fast` (frames back to back: the worst case for the PC side) and `serial_probe2_gap` (about 10 ms of quiet between frames). The host checker (check_probe.py) reports frames received / valid / corrupt, missed frames (sequence gaps), and for corrupt frames how many bytes differ from the expected frame.
Loading is ONCE per variant, no reload on silence (a reload would hide a dropout). LEDs: LED0 heartbeat, LED3 steady on (running), LED1 TOGGLES every 64 frames the FPGA has sent (about every 0.6 s fast, 1.2 s gap): it shows the card is transmitting whatever the PC receives; LED2 unused.
  python3 tools/board_serial_probe_v2.py [--out DIR] [--seed N] [--no-pnr]"""
import argparse, json, os, re, shutil, subprocess, sys, tempfile, zlib
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import board_tests_v1 as bt

M = 0xFFFFFFFF


def mix(seq, k):
    x = (seq * 0x9E3779B1 + k * 0x85EBCA6B + 0x1234567) & M
    x ^= x >> 15
    x = (x * 0x2C1B3C6D) & M
    x ^= x >> 12
    return x & M


def frame(seq):
    body = "UCP seq=%04X d=%s" % (seq, ",".join("%08X" % mix(seq, k) for k in range(8)))
    return body + " crc=%08X\r\n" % (zlib.crc32(body.encode()) & M)


COVER = 86          # bytes covered by the CRC (0..85)
LEN = 101


def verilog(name, gap):
    body = []
    idx = 0
    for ch in "UCP seq=":
        body.append("        8'd%d: msg_byte = 8'h%02X;" % (idx, ord(ch))); idx += 1
    for j in range(4):
        body.append("        8'd%d: msg_byte = hexch((seq >> %d) & 4'hF);" % (idx, (3 - j) * 4)); idx += 1
    for ch in " d=":
        body.append("        8'd%d: msg_byte = 8'h%02X;" % (idx, ord(ch))); idx += 1
    for k in range(8):
        for j in range(8):
            body.append("        8'd%d: msg_byte = hexch((w%d >> %d) & 4'hF);" % (idx, k, (7 - j) * 4)); idx += 1
        if k < 7:
            body.append("        8'd%d: msg_byte = 8'h2C;" % idx); idx += 1
    assert idx == COVER, idx
    for ch in " crc=":
        body.append("        8'd%d: msg_byte = 8'h%02X;" % (idx, ord(ch))); idx += 1
    for j in range(8):
        body.append("        8'd%d: msg_byte = hexch((crcf >> %d) & 4'hF);" % (idx, (7 - j) * 4)); idx += 1
    body.append("        8'd%d: msg_byte = 8'h0D;" % idx); idx += 1
    body.append("        8'd%d: msg_byte = 8'h0A;" % idx); idx += 1
    assert idx == LEN, idx
    words = "\n".join("    wire [31:0] w%d = mix(seq, 4'd%d);" % (k, k) for k in range(8))
    return """// board_top_%(n)s.v -- GENERATED by tools/board_serial_probe_v2.py (ledger #1131); do not hand-edit.
`default_nettype none
`timescale 1ns / 1ps
module board_top_%(n)s #(parameter integer CPB = %(cpb)d, parameter integer SETTLE = 0, parameter integer TIMEOUT = 0, parameter integer GAP = %(gap)d) (
    input wire BOARD_CLK, output wire UART_TX, output wire LED0_N, output wire LED1_N, output wire LED2_N, output wire LED3_N);
    wire clk = BOARD_CLK;
    reg [15:0] seq = 16'd0; reg [31:0] crc = 32'hFFFFFFFF; reg [7:0] mi = 8'd0; reg [31:0] gapc = 32'd0; reg [1:0] ps = 2'd0;
    wire [31:0] crcf = ~crc;
    function [31:0] mix(input [15:0] s, input [3:0] k);
        reg [31:0] x;
        begin x = {16'd0, s} * 32'h9E3779B1 + {28'd0, k} * 32'h85EBCA6B + 32'h01234567; x = x ^ (x >> 15); x = x * 32'h2C1B3C6D; x = x ^ (x >> 12); mix = x; end
    endfunction
%(words)s
    function [31:0] crc8(input [31:0] c, input [7:0] b);
        integer i; reg [31:0] r;
        begin r = c ^ {24'd0, b}; for (i = 0; i < 8; i = i + 1) r = r[0] ? ((r >> 1) ^ 32'hEDB88320) : (r >> 1); crc8 = r; end
    endfunction
    function [7:0] hexch(input [3:0] v); hexch = (v < 4'd10) ? (8'h30 + v) : (8'h41 + v - 4'd10); endfunction
    function [7:0] msg_byte(input [7:0] i);
        begin case (i)
%(body)s
        default: msg_byte = 8'h20; endcase end
    endfunction
    wire tx_busy; reg tx_start = 1'b0; reg [7:0] tx_data = 8'h00;
    board_uart_tx #(.CPB(CPB)) utx (.clk(clk), .start(tx_start), .data(tx_data), .tx(UART_TX), .busy(tx_busy));
    always @(posedge clk) begin
        tx_start <= 1'b0;
        case (ps)
            2'd0: if (gapc >= GAP) begin mi <= 8'd0; crc <= 32'hFFFFFFFF; ps <= 2'd1; end else gapc <= gapc + 32'd1;
            2'd1: if (!tx_busy && !tx_start) begin tx_data <= msg_byte(mi); tx_start <= 1'b1; if (mi < 8'd%(cover)d) crc <= crc8(crc, msg_byte(mi)); ps <= 2'd2; end
            2'd2: if (tx_busy) begin if (mi == 8'd%(last)d) begin seq <= seq + 16'd1; gapc <= 32'd0; ps <= 2'd0; end else begin mi <= mi + 8'd1; ps <= 2'd1; end end
            default: ps <= 2'd0;
        endcase
    end
    reg [23:0] hb = 24'd0; always @(posedge clk) hb <= hb + 24'd1;
    reg ftog = 1'b0; always @(posedge clk) if (ps == 2'd2 && tx_busy && mi == 8'd%(last)d && seq[5:0] == 6'd63) ftog <= ~ftog;   // one pulse per frame at seq 63, 127, ...: toggles every 64 frames
    assign LED0_N = ~hb[23]; assign LED1_N = ~ftog; assign LED2_N = 1'b1; assign LED3_N = 1'b0;
endmodule
""" % dict(n=name, cpb=bt.CPB, gap=gap, words=words, body="\n".join(body), cover=COVER, last=LEN - 1)


CHECK = r'''#!/usr/bin/env python3
"""check_probe.py -- ledger #1131: judge a capture of the serial_probe bitstreams.  python3 check_probe.py capture.bin [more.bin ...]
Counts frames received, valid (format + CRC-32 + the words the frame must carry), corrupt, missed frames (gaps in the 16-bit sequence between valid frames) and, for corrupt frames whose sequence number is readable, how many bytes differ from the frame that should have arrived."""
import re, sys, zlib
M = 0xFFFFFFFF
def mix(seq, k):
    x = (seq * 0x9E3779B1 + k * 0x85EBCA6B + 0x1234567) & M
    x ^= x >> 15
    x = (x * 0x2C1B3C6D) & M
    x ^= x >> 12
    return x & M
def frame(seq):
    body = "UCP seq=%04X d=%s" % (seq, ",".join("%08X" % mix(seq, k) for k in range(8)))
    return body + " crc=%08X\r\n" % (zlib.crc32(body.encode()) & M)
PAT = re.compile(rb"^UCP seq=([0-9A-F]{4}) d=((?:[0-9A-F]{8},){7}[0-9A-F]{8}) crc=([0-9A-F]{8})\r$")
def judge(path):
    data = open(path, "rb").read()
    lines = data.split(b"\n")
    ok = bad = 0; seqs = []; diffbytes = 0; partial = 0; bad_examples = []
    for ln in lines[1:-1] if len(lines) > 2 else []:      # the first and last pieces may be cut by the start/stop of the capture
        m = PAT.match(ln)
        good = False
        if m:
            seq = int(m.group(1), 16)
            body = ln[:ln.index(b" crc=")]
            if int(m.group(3), 16) == zlib.crc32(body) & M and ln + b"\n" == frame(seq).encode():
                ok += 1; seqs.append(seq); good = True
        if not good:
            bad += 1
            m2 = re.match(rb"^UCP seq=([0-9A-F]{4})", ln)
            if m2:
                exp = frame(int(m2.group(1), 16)).encode()
                got = ln + b"\n"
                diffbytes += sum(1 for a, b in zip(exp, got) if a != b) + abs(len(exp) - len(got))
            else:
                partial += 1
            if len(bad_examples) < 3:
                bad_examples.append(ln[:120])
    missed = sum(((b - a - 1) & 0xFFFF) for a, b in zip(seqs, seqs[1:]) if ((b - a) & 0xFFFF) < 1000)
    res = dict(file=path, bytes=len(data), frames_valid=ok, frames_corrupt=bad, corrupt_unreadable_header=partial, differing_bytes_in_corrupt=diffbytes, missed_frames_between_valid=missed,
               first_seq=(seqs[0] if seqs else None), last_seq=(seqs[-1] if seqs else None))
    return res, bad_examples
if __name__ == "__main__":
    worst = 0
    for p in sys.argv[1:]:
        r, ex = judge(p)
        print(" ".join("%s=%s" % kv for kv in r.items()))
        for e in ex:
            print("   corrupt example:", e)
        verdict = "CLEAN" if r["frames_valid"] > 20 and r["frames_corrupt"] == 0 and r["missed_frames_between_valid"] == 0 else ("SILENT" if r["bytes"] == 0 else "DEGRADED")
        print("   verdict:", verdict)
        worst = max(worst, 0 if verdict == "CLEAN" else 1)
    sys.exit(worst)
'''

RUN = r'''#!/bin/sh
# run_probe.sh -- ledger #1131: load each serial-probe bitstream ONCE (no reload on silence), capture the line for SECS seconds (default 20), judge it with check_probe.py.
# Usage:  sudo ./run_probe.sh [/dev/ttyUSB1]      options (env):  SECS=20  ONLY="serial_probe2_fast"  PAUSE=0
cd "$(dirname "$0")" || exit 1
rm -rf raw; mkdir raw; : > probe_results.txt
echo "Waiting 20 s for the board to finish booting its demo ..."; sleep 20
for f in serial_probe*.fs; do
  n=${f%.fs}
  if [ -n "$ONLY" ]; then case " $ONLY " in *" $n "*) ;; *) continue ;; esac; fi
  [ -n "$PAUSE" ] && sleep "$PAUSE"
  echo "[$n] loading ..."
  openFPGALoader -b tangnano20k "$f" > "raw/$n.loader.txt" 2>&1; echo $? > "raw/$n.rc"
  sleep 3
  i=0; while [ $i -lt 25 ]; do [ -e "${1:-/dev/ttyUSB1}" ] && break; sleep 1; i=$((i+1)); done
  sleep 1
  P=${1:-$(ls /dev/ttyUSB* 2>/dev/null | sort -V | tail -1)}
  stty -F "$P" 115200 raw -echo -hupcl clocal -crtscts 2>>"raw/$n.ports"
  timeout ${SECS:-20} cat "$P" > "raw/$n.bin" 2>>"raw/$n.ports"
  echo "[$n] $(wc -c < "raw/$n.bin") bytes from $P"
  if [ ! -s "raw/$n.bin" ]; then      # silent: look at every other ttyUSB for 6 s, keep the first that talks
    for Q in $(ls /dev/ttyUSB* 2>/dev/null | sort -V); do
      [ "$Q" = "$P" ] && continue
      stty -F "$Q" 115200 raw -echo -hupcl clocal -crtscts 2>>"raw/$n.ports"
      timeout 6 cat "$Q" > "raw/$n.alt" 2>>"raw/$n.ports"
      echo "[$n] other port $Q: $(wc -c < "raw/$n.alt") bytes"
      [ -s "raw/$n.alt" ] && cp "raw/$n.alt" "raw/$n.bin" && break
    done
  fi
  echo "[$n] LED check: is LED1 toggling about every second (card is transmitting)? LED0 blinking, LED3 on?"
  { echo "== $n"; python3 check_probe.py "raw/$n.bin"; } | tee -a probe_results.txt
  dmesg 2>/dev/null | grep -i -E "ftdi|ttyUSB" | tail -3 >> "raw/$n.ports"
done
echo; echo "Finished. Results are in $(pwd)/probe_results.txt  (keep the raw/ folder if anything is not CLEAN)"
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "board_serial_probe_v2"))
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--no-pnr", action="store_true")
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    sys.path.insert(0, out)
    open(os.path.join(out, "check_probe.py"), "w").write(CHECK)
    import importlib.util
    spec = importlib.util.spec_from_file_location("check_probe", os.path.join(out, "check_probe.py")); chk = importlib.util.module_from_spec(spec); spec.loader.exec_module(chk)
    for fn, txt in (("run_probe.sh", RUN),):
        p = os.path.join(out, fn); open(p, "w").write(txt); os.chmod(p, 0o755)
    open(os.path.join(out, "board_uart_tx.v"), "w").write(bt.UART_V)
    results = []
    for name, gap in (("serial_probe2_fast", 0), ("serial_probe2_gap", 270000)):
        wd = tempfile.mkdtemp(prefix="sp_")
        open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
        top = "board_top_" + name
        open(os.path.join(wd, top + ".v"), "w").write(verilog(name, gap))
        # simulation: the first two frames the RTL sends must be exactly the frames the checker expects
        sim = bt.simulate(wd, name, [os.path.join(wd, "board_uart_tx.v"), os.path.join(wd, top + ".v")])
        open(os.path.join(wd, "sim.bin"), "w").write(sim)
        got = sim.replace("\r\n", "\n").split("\n")
        want = [frame(s).rstrip("\r\n") for s in (0, 1)]
        if [g.rstrip("\r") for g in got[:2]] != want:
            raise RuntimeError("%s: simulated frames differ from the host's: %r vs %r" % (name, got[:2], want))
        print("== %s: simulated frames 0 and 1 equal the host's (%s)" % (name, want[0]), flush=True)
        shutil.copy(os.path.join(wd, top + ".v"), os.path.join(out, name + ".v"))
        open(os.path.join(out, name + ".cst"), "w").write(bt.cst())
        rec = dict(name=name, gap=gap)
        if not a.no_pnr:
            shutil.copy(os.path.join(out, name + ".cst"), os.path.join(wd, name + ".cst"))
            s = subprocess.run(["yosys", "-q", "-p", "read_verilog -sv board_uart_tx.v %s.v; hierarchy -top %s; synth_gowin -top %s -nowidelut -json %s.json" % (top, top, top, name)], cwd=wd, capture_output=True, text=True, timeout=1500)
            if s.returncode:
                raise RuntimeError("yosys: " + s.stderr[-500:])
            p = subprocess.run(["yowasp-nextpnr-himbaechel-gowin", "--device", bt.DEVICE, "--vopt", "family=GW2A-18C", "--vopt", "cst=%s.cst" % name, "--seed", str(a.seed), "--json", name + ".json", "--write", name + "_r.json", "--report", name + "_rep.json", "--freq", "27"], cwd=wd, capture_output=True, text=True, timeout=3000)
            if p.returncode:
                raise RuntimeError("nextpnr: " + (p.stdout[-300:] + p.stderr[-500:]))
            rep = json.load(open(os.path.join(wd, name + "_rep.json")))
            f = rep["fmax"]["clk"]["achieved"] if "clk" in rep["fmax"] else min(v["achieved"] for v in rep["fmax"].values())
            rec.update(fmax_mhz=round(f, 1), lut4=rep["utilization"]["LUT4"]["used"], dff=rep["utilization"]["DFF"]["used"])
            if f < 27:
                raise RuntimeError("timing not met")
            g = subprocess.run(["gowin_pack", "-d", bt.DEVICE, "-o", os.path.join(out, name + ".fs"), "-s", os.path.join(wd, name + ".cst"), name + "_r.json"], cwd=wd, capture_output=True, text=True)
            if g.returncode:
                raise RuntimeError("gowin_pack: " + g.stderr[-300:])
        results.append(rec)
        print("   built:", rec, flush=True)
    open(os.path.join(out, "README.md"), "w").write(
        "# Serial probe for the Tang Nano 20K (ledger #1131)\n\nTwo bitstreams with no cells in them; they only send framed, CRC-32-protected lines so we can measure the serial line to the PC on its own.\n\n"
        "1. Power the card up cold.  2. `sudo ./run_probe.sh /dev/ttyUSB1`  3. Send `probe_results.txt` (and the `raw/` folder if anything is not CLEAN).\n\n"
        "Verdicts: CLEAN = more than 20 frames, none corrupt, none missed. DEGRADED = some corrupt or missed (the counts say how many and how many bytes differ). SILENT = 0 bytes.\n"
        "LED0 blinking and LED3 on mean the bitstream is running. Each variant is loaded once (no reload on silence). `serial_probe2_fast` sends frames back to back (the hardest case for the PC side); `serial_probe2_gap` leaves about 10 ms between frames.\n\n"
        "| variant | LUT4 | FF | Fmax est. MHz |\n|---|---|---|---|\n" + "\n".join("| %s | %s | %s | %s |" % (r["name"], r.get("lut4", ""), r.get("dff", ""), r.get("fmax_mhz", "")) for r in results) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
