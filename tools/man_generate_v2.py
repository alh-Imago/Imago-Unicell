#!/usr/bin/env python3
"""man_generate_v2.py - vendor-aware MAN generator (2 Nov 2026, Alan 18:16: the front end's Card/MAN page was made before the Kintex was in use and only knows Intel).

Clone of man_generate_v1 (left untouched).  build_man(vendor=...) sends 'intel' to man_generate_v1.build_man unchanged and 'xilinx' to build_man_xilinx here.
build_man_xilinx takes chip facts (a dict, a facts .json, or the openXC7 chip database .bba, which bba_read_v1 reads in about 8 s) plus the board facts you type in.
Anything not given stays null, never a guess.  Gowin (Tang Nano) files are still made by their own generator; this tool refuses 'gowin' with a message saying so.
Output shape follows docs/man/ypcb-00338-1p1.man.json (vendor, synthesis, device, board, capabilities, verification, provenance)."""
import argparse, datetime, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "man_gen"))
import man_generate_v1  # noqa: E402

VENDORS = ("intel", "xilinx", "gowin")
OTHER_SITES = ("IOB", "GTXE2_CHANNEL", "MMCME2_ADV", "PLLE2_ADV", "BUFGCTRL", "BUFHCE", "IDELAY", "ILOGIC", "OLOGIC", "PCIE", "IPAD", "OPAD")


def load_facts(source):
    """source: dict of facts, a facts .json path, or a chip database .bba path."""
    if isinstance(source, dict):
        return source
    if str(source).endswith(".bba"):
        import bba_read_v1
        return bba_read_v1.read(source)
    with open(source) as f:
        return json.load(f)


def build_man_xilinx(card_id, part, family, package, facts, speed_grade=None, speed_grade_source=None,
                     board_name=None, clock_name="SYS_CLK", clock_pin=None, clock_hz=None, clock_io=None,
                     led_pins=None, led_io=None, jtag_idcode=None, do_not=None, extra_pins=None,
                     lut6_yosys=None, generated=None, generated_by=None, provenance=None):
    cf = load_facts(facts)
    st = cf["sites"]
    pkg_name = package.lower()
    pads = cf["pads"]
    pins = {p["pin"] for p in pads}
    problems = []
    for what, pin in [("clock", clock_pin)] + [(f"led[{i}]", p) for i, p in enumerate(led_pins or [])]:
        if pin and pin not in pins:
            problems.append(f"{what} pin {pin} is not in the {pkg_name} package table")
    if problems:
        raise ValueError("; ".join(problems))
    board = {"name": board_name or card_id}
    if clock_pin:
        board["clock"] = {clock_name: {"pin": clock_pin, "io_standard": clock_io, "freq_hz": clock_hz}}
    if led_pins:
        leds = {f"led[{i}]": p for i, p in enumerate(led_pins)}
        leds["io_standard"] = led_io
        board["leds"] = leds
    if extra_pins:
        board["extra_pins"] = dict(extra_pins)
    board["do_not"] = list(do_not or [])
    board["pins_recorded"] = "only what was typed in; the package pins of the chip are in device.package_pins (what the chip has, not what the card connects)"
    return {
        "man_version": "1.1",
        "card_id": card_id,
        "generated": generated or datetime.date.today().isoformat(),
        "generated_by": generated_by or "GENERATED by tools/man_generate_v2.py (build_man_xilinx). Chip facts from the openXC7 chip database via tools/man_gen/bba_read_v1.py; board facts as typed. NOT checked against the card.",
        "vendor": "xilinx",
        "synthesis": {"tool": "openXC7 open flow: yosys -> nextpnr-xilinx -> bitstream",
                      "nowidelut": {"supported": None, "default": None, "note": "not recorded"},
                      "chipdb_note": f"the build needs CHIPDB set to a prebuilt {part.lower()}{pkg_name}.bin"},
        "device": {
            "part": part, "family": family, "package": package.upper(), "speed_grade": speed_grade,
            "speed_grade_source": speed_grade_source,
            "jtag_idcode": jtag_idcode,
            "logic": {"unit": "LUT sites (nextpnr SLICE_LUTX)", "lut_sites_nextpnr": cf["slice_lut_sites"], "lut6_yosys": lut6_yosys,
                      "slices": st.get("SLICE"), "lut4_total": None, "ff_total": cf["slice_ff_sites"], "native_width": None,
                      "note": "use the nextpnr figure for how much of the chip is used; the yosys LUT6 count is a different measure"},
            "dsp": {"total_blocks": st.get("DSP48"), "primitives": [], "abilities": [], "note": "DSP48 sites read from the chip database"},
            "bram": {"total_blocks": st.get("RAMB36"), "ramb18_sites": st.get("RAMB18"), "note": "RAMB36 sites; each can be two RAMB18"},
            "other_sites": {k: st[k] for k in OTHER_SITES if k in st},
            "package_pins": {"package": pkg_name, "pads": len(pads), "unique_pin_names": len(pins),
                             "note": "every pad of the first package record in the chip database: pin name, tile, site (a pad whose name the database does not give is keyed \"null\"). A pin existing here does NOT say the card wires it that way.",
                             "table": {("null" if p["pin"] is None else str(p["pin"])): {"tile": p["tile"], "site": p["site"]} for p in pads}},
        },
        "board": board,
        "capabilities": {"note": "null = not recorded"},
        "verification": {"chip_database": cf.get("source", "chip facts as given"), "unverified": ["speed grade unless a source is stated", "everything marked null"]},
        "provenance": provenance or [cf.get("source", "chip facts as given")],
    }


def build_man(vendor="intel", **kw):
    vendor = (vendor or "intel").lower()
    if vendor == "intel":
        return man_generate_v1.build_man(**kw)
    if vendor == "xilinx":
        return build_man_xilinx(**kw)
    if vendor == "gowin":
        raise ValueError("Gowin (Tang Nano) MAN files are made by their own generator, not this tool yet")
    raise ValueError(f"unknown vendor {vendor!r}; choose one of {', '.join(VENDORS)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--vendor", default="xilinx", choices=VENDORS)
    ap.add_argument("--card-id", required=True)
    ap.add_argument("--part", required=True)
    ap.add_argument("--family", required=True)
    ap.add_argument("--package", required=True)
    ap.add_argument("--chip-facts", required=True, help="facts .json or chip database .bba")
    ap.add_argument("--speed-grade")
    ap.add_argument("--board-name")
    ap.add_argument("--clock-pin")
    ap.add_argument("--clock-hz", type=int)
    ap.add_argument("--clock-io")
    ap.add_argument("--led-pin", action="append", default=[])
    ap.add_argument("--led-io")
    ap.add_argument("--jtag-idcode")
    ap.add_argument("--do-not", action="append", default=[])
    ap.add_argument("--extra-pin", action="append", default=[], metavar="NAME=LOCATION", help="any other pin, kept as documentation")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    if a.vendor != "xilinx":
        sys.exit("this command line makes Xilinx files; for Intel use tools/man_generate_v1.py")
    man = build_man_xilinx(a.card_id, a.part, a.family, a.package, a.chip_facts, speed_grade=a.speed_grade, board_name=a.board_name,
                           clock_pin=a.clock_pin, clock_hz=a.clock_hz, clock_io=a.clock_io, led_pins=a.led_pin, led_io=a.led_io,
                           jtag_idcode=a.jtag_idcode, do_not=a.do_not,
                           extra_pins=dict(e.split("=", 1) for e in a.extra_pin))
    with open(a.output, "w") as f:
        json.dump(man, f, indent=2); f.write("\n")
    print("wrote", a.output)


if __name__ == "__main__":
    main()
