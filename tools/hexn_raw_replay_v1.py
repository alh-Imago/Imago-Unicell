#!/usr/bin/env python3
"""hexn_raw_replay_v1: REAL RIVER EXE ROWS AS A RAW WORD STREAM (new file 1 Nov 2026). Builds, with the same pipeline as hexn_scorer_quant_v1 (learn on 2022, int8 table at scale 4, test rows from 2023):
  table words (192 LOAD + 1 BIAS), SCORE words for N evenly spaced 2023 rows, the expected result word of each (bit-exact reference), and the true labels.
`python3 tools/hexn_raw_replay_v1.py` writes tools/esp32/hexn_open3_test/replay_data.h (N = 1000) and prints the AUC of the float and int8 tables on those rows. Used by tests/vm/test_hexn_open3_v1.py (a smaller N) as a real-data check of mode 3."""
import os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import hexn_real_exe_v1 as E, hexn_real_ocean_v2 as O, hexn_scorer_ref_v1 as R, hexn_scorer_quant_v1 as Q
def build(n=1000, scale=4):
    X, y, el, yr, t, T = E.build(); i22 = np.where(el & (yr == 2022))[0]; i23 = np.where(el & (yr == 2023))[0]; d = X.shape[1]
    lo, hi = np.percentile(X[i22], 1, axis=0), np.percentile(X[i22], 99, axis=0); B = O.bins(X, lo, hi)
    Tb = O.Tab(2, d, lo, hi, 0.0)
    for i in i22: Tb.add(int(y[i]), X[i])
    W = Tb.weights(); Wq = Q.quantise(W, scale)
    pick = i23[np.linspace(0, len(i23) - 1, n).astype(int)]
    table = [R.w_load(c, s, b, Wq[c][s][b]) for c in range(2) for s in range(d) for b in range(12)] + [R.w_bias(0)]
    rows = [R.w_score([int(v) for v in B[i]]) for i in pick]; exp = [R.score(Wq, 0, [int(v) for v in B[i]])[0] for i in pick]
    lab = [int(y[i]) for i in pick]; ar = np.arange(d)[None, :]
    sf = W[1][ar, B[pick]].sum(1) - W[0][ar, B[pick]].sum(1); si = np.array([R.score(Wq, 0, [int(v) for v in B[i]])[2] - R.score(Wq, 0, [int(v) for v in B[i]])[1] for i in pick])
    return table, rows, exp, lab, E.auc(sf, np.array(lab)), E.auc(si, np.array(lab))
def main():
    table, rows, exp, lab, af, ai = build(1000)
    L = ["// replay_data.h -- GENERATED by tools/hexn_raw_replay_v1.py (1 Nov 2026). River Exe: int8 table learned on 2022, 1000 evenly spaced 2023 rows. Do not hand-edit.",
         "// AUC on these rows: float table %.4f, int8 table %.4f; %d of %d rows are high-flow crossings." % (af, ai, sum(lab), len(lab)), "#pragma once", "#include <stdint.h>",
         "static const int REPLAY_TABLE_N = %d, REPLAY_N = %d;" % (len(table), len(rows))]
    for name, arr in (("REPLAY_TABLE", table), ("REPLAY_ROWS", rows), ("REPLAY_EXPECT", exp)):
        L.append("static const uint32_t %s[] = {%s};" % (name, ",".join("0x%08XUL" % (w & 0xFFFFFFFF) for w in arr)))
    L.append("static const uint8_t REPLAY_LABEL[] = {%s};" % ",".join(str(v) for v in lab))
    os.makedirs(os.path.join(HERE, "esp32", "hexn_open3_test"), exist_ok=True)
    open(os.path.join(HERE, "esp32", "hexn_open3_test", "replay_data.h"), "w").write("\n".join(L) + "\n")
    print("rows %d (%d positive) | AUC float %.4f, int8 %.4f | wrote replay_data.h" % (len(rows), sum(lab), af, ai))
if __name__ == "__main__": main()
