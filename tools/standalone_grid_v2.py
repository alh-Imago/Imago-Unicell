#!/usr/bin/env python3
"""tools/standalone_grid_v2.py -- ledger #1171: standalone_grid_v1.py (untouched) plus the DIVISION shell (div_shell_v1e, join mode). Original header: ledger #1116: the STANDALONE (v4 shells, one module per cell, no carrier) counterpart of carrier_grid_v3.py. Same ICM records, same face-to-face wiring, same
ports (clk, rst, ld_*, tap_*, ext_*), same simulate() -- so one test can run a design on the carrier grid and on the standalone grid and compare. Cells: ram_shell_v1, adder_shell_v1e (join_mode),
branch_shell_v1, accumulator_shell_v1; each configured by cfg_valid/cfg_data at boot with the SAME core field words the carrier uses (the v4 and v4c maps are the same). A ram load
(`ld_*`) re-commits the cell with its preload replaced."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import carrier_grid_v4 as C

SHELL = {"ram": ("ram_shell_v1", 80), "adder": ("adder_shell_v1e", 64), "branch": ("branch_shell_v1", 80), "accumulator": ("accumulator_shell_v1", 64), "div": ("div_shell_v1e", 64)}


def generate(records, out, top, tap_id, keep=None):
    os.makedirs(out, exist_ok=True)
    pos = {(r.row, r.col): i for i, r in enumerate(records)}
    n = len(records)
    ids = [r.cell_id for r in records]
    if tap_id not in ids:
        raise SystemExit("tap cell %r not in the design" % tap_id)
    tap_i = ids.index(tap_id)
    L = []
    w = L.append
    w("// GENERATED by tools/standalone_grid_v1.py (ledger #1116) -- a grid of %d standalone v4 shells. Do not hand-edit." % n)
    w("`default_nettype none\n`timescale 1ns / 1ps\n")
    ext = [(i, f) for i, r in enumerate(records) for f, (dr, dc) in C.DELTA.items() if (r.row + dr, r.col + dc) not in pos]
    w("module %s (" % top)
    w("    input  wire clk, input wire rst,")
    w("    input  wire ld_valid, input wire [15:0] ld_cell, input wire [31:0] ld_word,")
    w("    output wire tap_valid, output wire [31:0] tap_data,")
    w("    input  wire [%d:0] ext_arrived, input wire [%d:0] ext_ack_in," % (len(ext) - 1, len(ext) - 1))
    w("    input  wire [%d:0] ext_data_in," % (32 * len(ext) - 1))
    w("    output wire [%d:0] ext_fire, output wire [%d:0] ext_data_out" % (len(ext) - 1, 32 * len(ext) - 1))
    w(");")
    w("    reg boot_q = 1'b0; reg [3:0] rst_q = 4'hF;")
    w("    always @(posedge clk) begin rst_q <= {rst_q[2:0], rst}; boot_q <= (rst_q[3] && !rst); end")
    w("    wire cfg_boot = boot_q;")
    for i, r in enumerate(records):
        w("    wire [31:0] d%d_n, d%d_s, d%d_e, d%d_w; wire f%d_n, f%d_s, f%d_e, f%d_w; wire a%d_n, a%d_s, a%d_e, a%d_w;" % ((i,) * 12))
    extidx = {(i, f): k for k, (i, f) in enumerate(ext)}
    for i, r in enumerate(records):
        mod, cw = SHELL[r.core]
        base = C.core_word(r)
        cv_ = "(cfg_boot || (ld_valid && ld_cell == 16'd%d))" % i
        if r.core == "ram":
            import copy
            z = copy.copy(r); z.preload_value = 0
            ldw = C.core_word(z)
            cfgd = "(ld_valid && ld_cell == 16'd%d) ? ((%d'h%x & ~(%d'hFFFFFFFF << 14)) | (%d'h1 << 13) | ({%d'b0, ld_word} << 14)) : %d'h%x" % (i, cw, ldw, cw, cw, cw - 32, cw, base)
        else:
            cfgd = "%d'h%x" % (cw, base)
        ins = []
        for f in "NSEW":
            dr, dc = C.DELTA[f]
            j = pos.get((r.row + dr, r.col + dc))
            fl = f.lower()
            if j is None:
                k = extidx[(i, f)]
                ins.append(".data_in_%s(ext_data_in[%d:%d]), .arrived_%s(ext_arrived[%d]), .ack_in_%s(ext_ack_in[%d])" % (fl, 32 * k + 31, 32 * k, fl, k, fl, k))
            else:
                o = C.OPP[f].lower()
                ins.append(".data_in_%s(d%d_%s), .arrived_%s(f%d_%s), .ack_in_%s(a%d_%s)" % (fl, j, o, fl, j, o, fl, j, o))
        outs = [".data_out_%s(d%d_%s), .fire_%s(f%d_%s), .ack_out_%s(a%d_%s)" % (f, i, f, f, i, f, f, i, f) for f in "nsew"]
        w("    %s #(.CELL_ID(16'h%04x)) C%d (   // %s (%d,%d) %s" % (mod, i, i, r.cell_id, r.row, r.col, r.core))
        w("        .clk(clk), .rst(rst),")
        w("        .active_in_n(1'b1), .active_in_s(1'b1), .active_in_e(1'b1), .active_in_w(1'b1),")
        w("        .freeze_in_n(1'b0), .freeze_in_s(1'b0), .freeze_in_e(1'b0), .freeze_in_w(1'b0),")
        w("        .cfg_valid(%s), .cfg_data(%s)," % (cv_, cfgd))
        w("        " + ", ".join(ins) + ",")
        w("        " + ", ".join(outs) + ",")
        w("        .ready_out(), .ready_in_n(1'b1), .ready_in_s(1'b1), .ready_in_e(1'b1), .ready_in_w(1'b1),")
        w("        .program_in(1'b0), .program_done(), .prog_data_in_n(32'h0), .prog_data_in_s(32'h0), .prog_data_in_e(32'h0), .prog_data_in_w(32'h0),")
        w("        .prog_arrived_in_n(1'b0), .prog_arrived_in_s(1'b0), .prog_arrived_in_e(1'b0), .prog_arrived_in_w(1'b0),")
        w("        .prog_ack_out_n(), .prog_ack_out_s(), .prog_ack_out_e(), .prog_ack_out_w()%s" % {"ram": ",\n        .status_data_valid()", "adder": ",\n        .status_data_valid(), .status_a_arrived()", "branch": ",\n        .status_data_valid()", "accumulator": ",\n        .status_negative()", "div": ",\n        .status_data_valid(), .status_a_arrived()"}[r.core])
        w("    );")
    for k, (i, f) in enumerate(ext):
        w("    assign ext_fire[%d] = f%d_%s; assign ext_data_out[%d:%d] = d%d_%s;" % (k, i, f.lower(), 32 * k + 31, 32 * k, i, f.lower()))
    r = records[tap_i]
    tv, td = [], []
    for f in "NSEW":
        dr, dc = C.DELTA[f]
        j = pos.get((r.row + dr, r.col + dc))
        if j is not None:
            o = C.OPP[f].lower()
            tv.append("f%d_%s" % (j, o)); td.append("(f%d_%s ? d%d_%s : 32'h0)" % (j, o, j, o))
    w("    assign tap_valid = %s;" % " | ".join(tv))
    w("    assign tap_data = %s;" % " | ".join(td))
    w("endmodule")
    open(os.path.join(out, top + ".v"), "w").write("\n".join(L) + "\n")
    meta = {"top": top, "cells": [{"index": i, "cell_id": r.cell_id, "row": r.row, "col": r.col, "core": r.core, "io_name": r.io_name} for i, r in enumerate(records)],
            "ext": [{"k": k, "cell": records[i].cell_id, "face": f} for k, (i, f) in enumerate(ext)], "tap": tap_id, "shells": sorted({SHELL[r.core][0] for r in records})}
    json.dump(meta, open(os.path.join(out, "GRID.json"), "w"), indent=1)
    return meta


def simulate(records, tap_id, clocks, loads=(), workdir=None, top="standalone_grid_sim"):
    """same contract as carrier_grid_v2.simulate: [(clock, signed_value)] for every clock the TAP cell is offered a word."""
    import subprocess, tempfile, verilog_deps_v1 as vd
    work = workdir or tempfile.mkdtemp(prefix="sgrid_")
    meta = generate(records, work, top, tap_id)
    n = len(meta["ext"])
    idx = {c["cell_id"]: c["index"] for c in meta["cells"]}
    ld = "".join("        wait_clk(%d); ld_cell = 16'd%d; ld_word = 32'd%d; ld_valid = 1; @(posedge clk); ld_valid = 0;\n" % (c, idx[cid], w & 0xFFFFFFFF) for c, cid, w in sorted(loads))
    tb = """`timescale 1ns/1ps
module tb;
    reg clk = 0, rst = 1; always #5 clk = ~clk;
    reg ld_valid = 0; reg [15:0] ld_cell = 0; reg [31:0] ld_word = 0;
    wire tap_valid; wire [31:0] tap_data;
    wire [%(n)d-1:0] ef; wire [%(nb)d-1:0] eo;
    %(top)s g(.clk(clk), .rst(rst), .ld_valid(ld_valid), .ld_cell(ld_cell), .ld_word(ld_word), .tap_valid(tap_valid), .tap_data(tap_data),
        .ext_arrived(%(n)d'b0), .ext_ack_in(%(n)d'b0), .ext_data_in({%(nb)d{1'b0}}), .ext_fire(ef), .ext_data_out(eo));
    integer c = 0;
    always @(posedge clk) begin c <= c + 1; if (tap_valid) $display("TAP %%0d %%0d", c, $signed(tap_data)); end
    task wait_clk(input integer k); begin while (c < k) @(posedge clk); end endtask
    initial begin
        repeat (4) @(posedge clk); rst = 0;
%(ld)s        wait_clk(%(clocks)d); $finish;
    end
endmodule
""" % dict(n=n, nb=32 * n, top=top, ld=ld, clocks=clocks)
    open(os.path.join(work, "tb.v"), "w").write(tb)
    deps = set()
    for m in meta["shells"]:
        deps |= set(vd.deps(m, [work, os.path.join(ROOT, "fpga", "verilog")]))
    deps = [os.path.relpath(d, work) if d.startswith(work) else d for d in sorted(deps)]
    r = subprocess.run(["iverilog", "-g2012", "-o", "t.vvp", "tb.v", top + ".v"] + deps, cwd=work, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("iverilog: " + r.stderr[-1200:])
    o = subprocess.run(["vvp", "t.vvp"], cwd=work, capture_output=True, text=True, timeout=1800).stdout
    return [(int(p[1]), int(p[2])) for p in (l.split() for l in o.splitlines()) if p and p[0] == "TAP"]
