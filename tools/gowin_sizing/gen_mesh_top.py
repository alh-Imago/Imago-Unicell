def gen_command(n):
    """command_shell_v1c: a controller, not a data-mesh cell (freeze_out/program_out instead of the
    standard data_out/ack_out shape). Not tiled in a real data mesh, so this instantiates N independent
    copies with every neighbor-facing port tied off (no mesh wiring), which is the honest, self-consistent
    reading for this cell type."""
    top = f"mesh_command_{n}"
    lines = [HEADER.format(top=top, n=n, module="command_shell_v1c", rows=1, cols=n, cfg_w_hi=63, cfg_expr=cfg_expr_for(64))]
    xor_terms = []
    for idx in range(n):
        nm = f"c_{idx}"
        lines.append(f"wire {nm}_status_active, {nm}_status_freeze_state, {nm}_ready_out;")
        lines.append(f"command_shell_v1c #(.CELL_ID(16'h{0x1000 + idx:04X})) {nm} (")
        lines.append("    .clk(clk), .rst(rst),")
        active_n = "entry_active" if idx == 0 else "1'b0"
        data_n = "entry_data" if idx == 0 else "32'h0"
        arrived_n = "entry_arrived" if idx == 0 else "1'b0"
        lines.append(f"    .active_in_n({active_n}), .active_in_s(1'b0), .active_in_e(1'b0), .active_in_w(1'b0),")
        lines.append("    .freeze_in_n(1'b0), .freeze_in_s(1'b0), .freeze_in_e(1'b0), .freeze_in_w(1'b0),")
        lines.append("    .cfg_valid(cfg_valid_bcast), .cfg_data(cfg_data_bcast),")
        lines.append(f"    .data_in_n({data_n}), .data_in_s(32'h0), .data_in_e(32'h0), .data_in_w(32'h0),")
        lines.append(f"    .arrived_n({arrived_n}), .arrived_s(1'b0), .arrived_e(1'b0), .arrived_w(1'b0),")
        lines.append("    .ack_out_n(), .ack_out_s(), .ack_out_e(), .ack_out_w(),")
        lines.append(f"    .ready_out({nm}_ready_out),")
        lines.append("    .freeze_out_n(), .freeze_out_s(), .freeze_out_e(), .freeze_out_w(),")
        lines.append("    .program_out_n(), .program_out_s(), .program_out_e(), .program_out_w(),")
        lines.append("    .prog_data_out_n(), .prog_data_out_s(), .prog_data_out_e(), .prog_data_out_w(),")
        lines.append("    .prog_arrived_out_n(), .prog_arrived_out_s(), .prog_arrived_out_e(), .prog_arrived_out_w(),")
        lines.append("    .prog_ack_in_n(1'b0), .prog_ack_in_s(1'b0), .prog_ack_in_e(1'b0), .prog_ack_in_w(1'b0),")
        lines.append("    .program_in(1'b0), .program_done(),")
        lines.append("    .prog_data_in_n(32'h0), .prog_data_in_s(32'h0), .prog_data_in_e(32'h0), .prog_data_in_w(32'h0),")
        lines.append("    .prog_arrived_in_n(1'b0), .prog_arrived_in_s(1'b0), .prog_arrived_in_e(1'b0), .prog_arrived_in_w(1'b0),")
        lines.append("    .prog_ack_out_n(), .prog_ack_out_s(), .prog_ack_out_e(), .prog_ack_out_w(),")
        lines.append(f"    .status_active({nm}_status_active), .status_freeze_state({nm}_status_freeze_state)")
        lines[-1] = lines[-1] + "\n);\n"
        xor_terms.extend([f"{nm}_status_active", f"{nm}_status_freeze_state", f"{nm}_ready_out"])
    lines.append(FOOTER.format(xor_expr=" ^ ".join(xor_terms)))
    return "\n".join(lines)


def gen_baseline():
    """points.md #889: the measurement harness with ZERO cell instances -- its own fixed LUT/ALU/DFF/Fmax
    cost, to be subtracted from every other result so the reported per-cell figures are the cell alone,
    not cell-plus-harness. array_alive here depends only on BTN_ENTRY (still real, non-prunable)."""
    lines = [HEADER.format(top="mesh_baseline_0", n=0, module="(none)", rows=0, cols=0, cfg_w_hi=63, cfg_expr=cfg_expr_for(64))]
    lines.append(FOOTER.format(xor_expr="entry_active ^ entry_arrived ^ entry_data[0]"))
    return "\n".join(lines)


def main():
    if sys.argv[1] == "baseline":
        sys.stdout.write(gen_baseline())
        return
    cell_type, n = sys.argv[1], int(sys.argv[2])
    rows = int(sys.argv[3]) if len(sys.argv) > 3 else (3 if n == 9 else 1)
    cols = int(sys.argv[4]) if len(sys.argv) > 4 else (3 if n == 9 else 1)
    if cell_type == "nano":
        sys.stdout.write(gen_nano(n, rows, cols))
    elif cell_type == "command":
        sys.stdout.write(gen_command(n))
    elif cell_type in STANDARD:
        sys.stdout.write(gen_standard(cell_type, n, rows, cols))
    else:
        raise SystemExit(f"no generator for {cell_type!r} (have: {sorted(STANDARD)} + nano + command)")


if __name__ == "__main__":
    main()
