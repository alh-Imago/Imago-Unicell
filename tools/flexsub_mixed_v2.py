#!/usr/bin/env python3
"""flexsub_mixed_v2.py -- ledger #1162 (v2 = v1 plus STANDARD and CARRIER regions; v1 untouched). Ledger #1114 text: MIXED-family designs with the sub bridge inserted AUTOMATICALLY (Alan, 12 Oct 2026: the bridge "feeds into the compiler and assembler systems ... and the composer as an
automatic insert when using mixed blocks that use the sub family").

A hierarchical ICM (icm-vix-v1) may tag a block (placement) with `"family": "flex"` or `"sub"` (optional; absent = --default-family, flex). This tool

  1. flattens the design and groups the cells into REGIONS: a region is a connected set of cells of one family;
  2. for every edge between two regions (a "crossing"), cuts it: the sending region gets an exit port (io_name `bx<k>_out`), the receiving region a synthetic entry relay (io_name `bx<k>_in`) placed where the
     sending cell was, so each region is an ordinary stand-alone design for the EXISTING generators (flexsub_icm_flex_v1 for flex, flexsub_icm_generate_v1 for sub) -- no cell emitter is changed;
  3. generates each region, and writes a top module that instantiates the regions and puts `flex_to_sub_v1` / `sub_to_flex_v1` (sub/verilog/flex_sub_bridge_v1.v) on every crossing, with the `done` line of a
     sub region's exit bridge opening its entry bridge (one word in flight per sub region: a sub block cannot refuse or queue a word, ledger #1112).

v2 adds `"family": "std"` (the standalone v4 shells) and `"carrier"` (the VIXeN carrier trimmed to the cores used): such a region is generated by the standard line's own grid generators, its outside faces
(GRID.json `ext`) are the crossings, and the stateless adapters of sub/verilog/flex_std_adapter_v1.v (#1160) join it to a flex neighbour -- or, in series, to the other std-line family. No synthetic cell is needed
for them: the missing neighbour IS the outside face. Their `ready_out` is exported by tools/grid_ext_ready_v1.py. Limits: ram / adder / branch / accumulator only (the std line's cores); a std / carrier region has no
host-named cell and no ring; std / carrier <-> sub crossings are refused (not built); everything else as below.

Stage-1 limits (each refused with its reason, never guessed): a crossing's sending cell has exactly one consumer; a sub region has exactly one entry crossing and one exit crossing and no host port of its own
(the host reaches it only through the bridge); 32-bit data; a flex region may be a ring only through the existing flex flags (not passed through here).
"""
import argparse
import collections
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "nano"))
import flexsub_icm_netlist_v1 as nl  # noqa: E402
import flexsub_icm_generate_v1 as fig  # noqa: E402
import icm_vix_v1 as vix  # noqa: E402
import grid_ext_ready_v1 as gx  # noqa: E402

STD_FAMILIES = ("std", "carrier")
STD_CORES = ("ram", "adder", "branch", "accumulator")
ADAPTER = os.path.join(HERE, "..", "sub", "verilog", "flex_std_adapter_v1.v")
OPP = {"N": "S", "S": "N", "E": "W", "W": "E"}

ROOT_DIR = os.path.abspath(os.path.join(HERE, ".."))
BRIDGE = os.path.join(HERE, "..", "sub", "verilog", "flex_sub_bridge_v1.v")


class MixedError(ValueError):
    pass


def _inst(cid):
    return cid.split(".", 1)[0]


def is_mixed(path):      # v2: unchanged meaning
    """True when the file is an ICM-VIX whose placements name a family (ledger #1114): the assembler then builds it as separate regions with bridges."""
    try:
        with open(path) as f:
            head = json.load(f)
    except (OSError, ValueError):
        return False
    if not str(head.get("format_version", "")).startswith("icm-vix"):
        return False
    return any(p.get("family") for p in head.get("design_map", {}).get("placements", []))


def plan(path, default_family="flex"):
    """Regions, crossings and the region ICM dicts. No files written."""
    doc = vix.IcmVixFile.load(path)
    fam_of = {p.instance: (p.family or default_family) for p in doc.placements}
    for inst, f in fam_of.items():
        if f not in ("flex", "sub", "std", "carrier"):
            raise MixedError(f"block {inst!r}: family {f!r} is not 'flex', 'sub', 'std' or 'carrier'")
    _, _recs, cells, edges, inputs, outputs, ext_out, _w = nl.extract(path)
    fam = {c: fam_of[_inst(c)] for c in cells}
    parent = {c: c for c in cells}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for s, d, *_ in edges:
        if fam[s] == fam[d]:
            parent[find(s)] = find(d)
    groups = collections.defaultdict(list)
    for c in sorted(cells):
        groups[find(c)].append(c)
    regions = []                                      # stable order: by first cell id
    for k, (_root, members) in enumerate(sorted(groups.items(), key=lambda kv: kv[1][0])):
        regions.append({"name": f"{fam[members[0]]}{k}", "family": fam[members[0]], "cells": members})
    region_of = {c: r["name"] for r in regions for c in r["cells"]}
    crossings = []
    for s, d, face, role, oc in edges:
        if region_of[s] == region_of[d]:
            continue
        if len(outputs.get(s, [])) != 1 or ext_out.get(s):
            raise MixedError(f"{s}: a cell that sends across a family boundary must have exactly one consumer and no other output (it feeds {outputs.get(s)} and faces {ext_out.get(s)})")
        if cells[s].io_name:
            raise MixedError(f"{s}: a cell that sends across a family boundary cannot also carry the host name {cells[s].io_name!r}")
        crossings.append({"k": len(crossings), "src": s, "dst": d, "face": face, "from": region_of[s], "to": region_of[d]})
    by_name = {r["name"]: r for r in regions}
    for x in crossings:
        ff, tf = by_name[x["from"]]["family"], by_name[x["to"]]["family"]
        if (ff in STD_FAMILIES and tf == "sub") or (ff == "sub" and tf in STD_FAMILIES):
            raise MixedError(f"crossing {x['src']} -> {x['dst']}: {ff} -> {tf} is not built (the sub bridge speaks the flex handshake; put a flex block between them)")
    if sum(1 for r in regions if r["family"] == "carrier") > 1:
        raise MixedError("more than one carrier region: each would write its own trimmed carrier module under the same name; keep the carrier cells in one connected block (or use family std)")
    for r in regions:
        r["ins"] = [x for x in crossings if x["to"] == r["name"]]
        r["outs"] = [x for x in crossings if x["from"] == r["name"]]
        if r["family"] in STD_FAMILIES:
            bad = sorted({cells[c].core for c in r["cells"]} - set(STD_CORES))
            if bad:
                raise MixedError(f"{r['family']} region {r['name']}: the standard line has no cell for core(s) {', '.join(bad)} (it has {', '.join(STD_CORES)})")
            host = [c for c in r["cells"] if cells[c].io_name]
            if host:
                raise MixedError(f"{r['family']} region {r['name']}: cells {host} carry host names; a {r['family']} region is reached only through its crossings")
        if r["family"] == "sub":
            if len(r["ins"]) != 1 or len(r["outs"]) != 1:
                raise MixedError(f"sub region {r['name']} ({r['cells'][0]}...): needs exactly ONE entry crossing and ONE exit crossing (one word in flight, #1112); it has {len(r['ins'])} in, {len(r['outs'])} out")
            host = [c for c in r["cells"] if cells[c].io_name]
            if host:
                raise MixedError(f"sub region {r['name']}: cells {host} carry host names; a sub region is reached only through the bridge")
    # region ICM documents (flat: one pattern at the origin, absolute cells)
    for r in regions:
        cl = []
        for c in r["cells"]:
            rec = cells[c]
            io = rec.io_name
            for x in r["outs"]:
                if x["src"] == c and r["family"] not in STD_FAMILIES:
                    io = f"bx{x['k']}_out"
            cl.append({"cell_id": c, "rel_row": rec.row, "rel_col": rec.col, "core": rec.core, "core_config": dict(rec.core_config or {}),
                       "addon_config": dict(rec.addon_config or {}), "io_name": io, "preload_value": rec.preload_value})
        for x in (r["ins"] if r["family"] not in STD_FAMILIES else []):
            sr = cells[x["src"]]
            cl.append({"cell_id": f"bx{x['k']}_in", "rel_row": sr.row, "rel_col": sr.col, "core": "ram",
                       "core_config": {"downstream_mask": [x["face"]], "fixed_mode": 0}, "addon_config": {}, "io_name": f"bx{x['k']}_in", "preload_value": None})
        cores = sorted({c["core"] for c in cl})
        r["doc"] = {"format_version": "icm-vix-v1", "description": f"region {r['name']} ({r['family']}) of {os.path.basename(path)}, cut by flexsub_mixed_v1",
                    "header": {"cores_used": cores, "cell_count": len(cl)},
                    "patterns": {"region": {"cells": [{k: v for k, v in c.items() if v is not None} for c in cl]}},
                    "design_map": {"placements": [{"instance": "r", "pattern": "region", "at": [0, 0]}], "connections": []}}
    return {"regions": regions, "crossings": crossings, "cells": cells, "by_name": by_name}


def _ports(vtext, top):
    m = re.search(r"module\s+" + re.escape(top) + r"\s*\((.*?)\);", vtext, re.S)
    ports = {}
    for d, w, n in re.findall(r"(input|output)\s+wire\s*(\[[^\]]*\])?\s*(\w+)", m.group(1)):
        ports[n] = (d, w.strip())
    return ports


def _gen_std(r, rp, output, mod):
    """A standard / carrier region: the standard line's own grid generator on the region's cells (no tap observation: a crossing's sender is NOT turned into a hold ram), ext_ready exported."""
    import std_icm_generate_v1 as sig
    import carrier_grid_v3 as G
    import standalone_grid_v1 as S
    recs = vix.IcmVixFile.load(rp).flatten()[0]
    sig.normalise(recs)
    for q in recs:
        if q.core == "adder":
            q.core_config["join_mode"] = 1
    tap = recs[0].cell_id                                    # the grid needs a tap cell; nothing reads it here
    if r["family"] == "std":
        meta = S.generate(recs, output, mod, tap)
    else:
        keep = tuple(sorted({sig.KEEP_NAME[q.core] for q in recs}))
        meta = G.generate(recs, output, mod, tap, keep=keep)
    gx.add_ext_ready(os.path.join(output, mod + ".v"), meta)
    json.dump(meta, open(os.path.join(output, f"GRID_{r['name']}.json"), "w"), indent=1)
    # copy the cell / shell / add-on sources the region needs, so the output folder is complete (never over a file the other regions wrote)
    import tempfile
    import verilog_deps_v1 as vd
    tmp = tempfile.mkdtemp()
    for f in (mod + ".v", "carrier_sub.v"):
        if os.path.exists(os.path.join(output, f)):
            shutil.copy2(os.path.join(output, f), tmp)
    have = set(os.listdir(output))
    for f in vd.deps(mod, [tmp, os.path.join(ROOT_DIR, "fpga", "verilog")]):
        if os.path.basename(f) not in have:
            shutil.copy2(f, os.path.join(output, os.path.basename(f)))
    shutil.rmtree(tmp, ignore_errors=True)
    gj = os.path.join(output, "GRID.json")
    if os.path.exists(gj):
        os.remove(gj)                                        # one GRID_<region>.json per region instead of a GRID.json that the last region would overwrite
    return meta


def generate(path, output, top="mixed_top", default_family="flex", man_path=None):
    p = plan(path, default_family)
    os.makedirs(output, exist_ok=True)
    files = set()
    for r in p["regions"]:
        rp = os.path.join(output, f"{r['name']}.icm-hier.json")
        json.dump(r["doc"], open(rp, "w"), indent=1)
        mod = f"{top}_{r['name']}"
        r["module"] = mod
        if r["family"] in STD_FAMILIES:
            r["meta"] = _gen_std(r, rp, output, mod)
            r["rec"] = {"files": [f for f in os.listdir(output) if f.endswith(".v")]}
            r["ports"] = {}
            files.update(f for f in os.listdir(output) if f.endswith(".v"))
            continue
        if r["family"] == "flex":
            import flexsub_icm_flex_v1 as ff
            rec = ff.generate_flex(rp, output, top=mod, man_path=man_path)
        else:
            rec = fig.generate(rp, output, top=mod, family="sub", man_path=man_path)
        r["rec"] = rec
        r["ports"] = _ports(open(os.path.join(output, f"{mod}.v")).read(), mod)
        files.update(f for f in rec["files"] if f.endswith(".v"))
    shutil.copy2(BRIDGE, os.path.join(output, "flex_sub_bridge_v1.v"))
    files.add("flex_sub_bridge_v1.v")
    if any(r["family"] in STD_FAMILIES for r in p["regions"]):
        shutil.copy2(ADAPTER, os.path.join(output, "flex_std_adapter_v1.v"))
        files.add("flex_std_adapter_v1.v")
    L = []
    L.append(f"// {top}.v -- GENERATED by tools/flexsub_mixed_v2.py; do not hand-edit. Source: {os.path.basename(path)}; regions: " + ", ".join(f"{r['name']}({r['family']})" for r in p["regions"]) + f"; bridges: {len(p['crossings'])}")
    L.append("`default_nettype none\n`timescale 1ns / 1ps")
    top_ports = []
    cross_ports = {f"bx{x['k']}_{d}" for x in p["crossings"] for d in ("in", "out")}
    taken = set()
    for r in p["regions"]:
        for n, (d, w) in r["ports"].items():
            base = re.sub(r"^(in|out)_(.*?)(_data|_valid|_ack)$", r"\2", n)
            if base in cross_ports or n in ("clk", "rst", "cfg_valid"):
                continue
            if n in taken:
                raise MixedError(f"host port {n} appears in two regions")
            taken.add(n)
            top_ports.append(f"    {d} wire {w + ' ' if w else ''}{n}")
    L.append(f"module {top} (\n    input wire clk,\n    input wire rst,\n    input wire cfg_valid" + "".join(",\n" + t for t in top_ports) + "\n);")
    fam_of = {r["name"]: r["family"] for r in p["regions"]}
    for r in p["regions"]:
        if r["family"] in STD_FAMILIES:
            continue
        for x in r["outs"]:
            n = f"bx{x['k']}_out"
            L.append(f"wire [31:0] {n}_data; wire {n}_valid" + (f", {n}_ack;" if r["family"] == "flex" else ";"))
        for x in r["ins"]:
            n = f"bx{x['k']}_in"
            L.append(f"wire [31:0] {n}_data; wire {n}_valid" + (f", {n}_ack;" if r["family"] == "flex" else ";"))
    for r in p["regions"]:
        if r["family"] == "sub":
            L.append(f"wire {r['name']}_done;   // exit bridge -> entry bridge: the held word has left, the next may enter")
    # standard / carrier regions: one bundle of ext vectors each; bit k is driven by the crossing that uses that outside face, tied off otherwise
    ext_drive = {}                                            # region -> {k: {"arrived":..,"ack_in":..,"data_in":..}}
    ext_k = {}
    for r in p["regions"]:
        if r["family"] in STD_FAMILIES:
            ext_k[r["name"]] = {(e["cell"][2:] if e["cell"].startswith("r.") else e["cell"], e["face"]): e["k"] for e in r["meta"]["ext"]}      # the region file wraps its cells in one instance "r"
            ext_drive[r["name"]] = {}
            n = len(r["meta"]["ext"])
            L.append(f"wire [{max(n - 1, 0)}:0] {r['name']}_ext_arrived, {r['name']}_ext_ack_in, {r['name']}_ext_fire, {r['name']}_ext_ready; wire [{32 * max(n, 1) - 1}:0] {r['name']}_ext_data_in, {r['name']}_ext_data_out;")
    for x in p["crossings"]:
        f_from, f_to = fam_of[x["from"]], fam_of[x["to"]]
        k = x["k"]
        if f_from == "flex" and f_to == "sub":
            L.append(f"flex_to_sub_v1 #(.WIDTH(32)) bridge{k} (.clk(clk), .rst(rst), .in_data(bx{k}_out_data), .in_valid(bx{k}_out_valid), .in_ack(bx{k}_out_ack), "
                     f".sub_data(bx{k}_in_data), .sub_valid(bx{k}_in_valid), .done({x['to']}_done));   // flex {x['from']} -> sub {x['to']}")
            continue
        if f_from == "sub" and f_to == "flex":
            L.append(f"sub_to_flex_v1 #(.WIDTH(32)) bridge{k} (.clk(clk), .rst(rst), .sub_data(bx{k}_out_data), .sub_valid(bx{k}_out_valid), "
                     f".out_data(bx{k}_in_data), .out_valid(bx{k}_in_valid), .out_ack(bx{k}_in_ack), .done({x['from']}_done));   // sub {x['from']} -> flex {x['to']}")
            continue
        if f_from == f_to:
            raise MixedError("internal: a crossing between two regions of one family")
        # a std-line end and/or a flex end. Flex-side nets: (data, valid, ack) -- the region's own bx wires, or an intermediate set when both ends are std-line.
        sf = f_from in STD_FAMILIES
        st = f_to in STD_FAMILIES
        if sf:                                                # sender is a std-line region: its outside face, direction x["face"]
            ks = ext_k[x["from"]][(x["src"], x["face"])]
            sdata = f"{x['from']}_ext_data_out[{32 * ks + 31}:{32 * ks}]"
            if st:
                L.append(f"wire [31:0] m{k}_data; wire m{k}_valid, m{k}_ack;")
                fl = (f"m{k}_data", f"m{k}_valid", f"m{k}_ack")
            else:
                fl = (f"bx{k}_in_data", f"bx{k}_in_valid", f"bx{k}_in_ack")
            L.append(f"wire x{k}_sack;")
            L.append(f"std_to_flex_v1 #(.WIDTH(32)) bridge{k}{'a' if st else ''} (.std_data({sdata}), .std_fire({x['from']}_ext_fire[{ks}]), .std_ack(x{k}_sack), .flex_ack({fl[2]}), .flex_data({fl[0]}), .flex_valid({fl[1]}));   // {f_from} {x['from']} -> flex side")
            ext_drive[x["from"]].setdefault(ks, {})["ack_in"] = f"x{k}_sack"
        if st:                                                # receiver is a std-line region: the face toward the sender, direction OPP[x["face"]]
            kr = ext_k[x["to"]][(x["dst"], OPP[x["face"]])]
            fl = (f"m{k}_data", f"m{k}_valid", f"m{k}_ack") if sf else (f"bx{k}_out_data", f"bx{k}_out_valid", f"bx{k}_out_ack")
            L.append(f"wire [31:0] x{k}_rdata; wire x{k}_rarr;")
            L.append(f"flex_to_std_v1 #(.WIDTH(32)) bridge{k}{'b' if sf else ''} (.flex_data({fl[0]}), .flex_valid({fl[1]}), .flex_ack({fl[2]}), .std_ready({x['to']}_ext_ready[{kr}]), .std_data(x{k}_rdata), .std_arrived(x{k}_rarr));   // flex side -> {f_to} {x['to']}")
            ext_drive[x["to"]].setdefault(kr, {})["arrived"] = f"x{k}_rarr"
            ext_drive[x["to"]][kr]["data_in"] = f"x{k}_rdata"
    for r in p["regions"]:
        if r["family"] not in STD_FAMILIES:
            continue
        n = len(r["meta"]["ext"])
        d = ext_drive[r["name"]]
        for sig_, key, w in (("ext_arrived", "arrived", 1), ("ext_ack_in", "ack_in", 1)):
            for kk in range(n):
                L.append(f"assign {r['name']}_{sig_}[{kk}] = {d.get(kk, {}).get(key, chr(49) + chr(39) + 'b0')};")
        for kk in range(n):
            L.append(f"assign {r['name']}_ext_data_in[{32 * kk + 31}:{32 * kk}] = {d.get(kk, {}).get('data_in', chr(51) + chr(50) + chr(39) + 'h0')};")
        L.append(f"{r['module']} u_{r['name']} (.clk(clk), .rst(rst), .ld_valid(1'b0), .ld_cell(16'd0), .ld_word(32'd0), .tap_valid(), .tap_data(), "
                 f".ext_arrived({r['name']}_ext_arrived), .ext_ack_in({r['name']}_ext_ack_in), .ext_data_in({r['name']}_ext_data_in), .ext_fire({r['name']}_ext_fire), .ext_data_out({r['name']}_ext_data_out), .ext_ready({r['name']}_ext_ready));")
    for r in p["regions"]:
        if r["family"] in STD_FAMILIES:
            continue
        conn = ["    .clk(clk)", "    .rst(rst)", "    .cfg_valid(cfg_valid)"]
        for n, (d, w) in r["ports"].items():
            if n in ("clk", "rst", "cfg_valid"):
                continue
            base = re.sub(r"^(in|out)_(.*?)(_data|_valid|_ack)$", r"\2", n)
            wire = (n[3:] if n.startswith("in_") else n[4:]) if base in cross_ports else n      # a crossing port joins the bridge net of the same name; a host port keeps its name
            conn.append(f"    .{n}({wire})")
        L.append(f"{r['module']} u_{r['name']} (\n" + ",\n".join(conn) + "\n);")
    L.append("endmodule")
    open(os.path.join(output, f"{top}.v"), "w").write("\n".join(L) + "\n")
    rec = {"generator": "tools/flexsub_mixed_v2.py", "top": top, "source": os.path.basename(path), "default_family": default_family,
           "regions": [{"name": r["name"], "family": r["family"], "cells": len(r["cells"]), "module": r["module"]} for r in p["regions"]],
           "bridges": [{"k": x["k"], "from": x["from"], "to": x["to"], "src_cell": x["src"], "dst_cell": x["dst"]} for x in p["crossings"]],
           "files": sorted(files) + [f"{top}.v"]}
    json.dump(rec, open(os.path.join(output, "ASSEMBLY_mixed.json"), "w"), indent=2)
    return rec


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("icm")
    ap.add_argument("--output", required=True)
    ap.add_argument("--top", default="mixed_top")
    ap.add_argument("--default-family", default="flex", choices=["flex", "sub", "std", "carrier"])
    ap.add_argument("--man")
    a = ap.parse_args(argv)
    try:
        r = generate(a.icm, a.output, top=a.top, default_family=a.default_family, man_path=a.man)
    except (MixedError, ValueError, FileNotFoundError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    print(f"Mixed: {len(r['regions'])} regions ({', '.join(x['family'] for x in r['regions'])}), {len(r['bridges'])} bridges inserted -> {a.output} (top {r['top']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
