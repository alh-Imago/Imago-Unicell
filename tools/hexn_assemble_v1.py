#!/usr/bin/env python3
"""hexn_assemble_v1.py - the HEX-N ASSEMBLER (3 Nov 2026, Alan 10:07: 'a full base to run the assembler against', 'a full end to end run'). Carrier style (HEXN_ASSEMBLER_SCOPING_v1.md section 8): the assembler makes the PATTERN design from a pattern REFERENCE file, and a program (a unit file) is loaded into it afterwards.

  build  REF.json --out DIR [--card tang-nano-20k] [--clkdiv N]
         -> DIR/src/ (flat copy of every Verilog file the design needs: tiles, cores, crossing, frame, the generated hexn_pattern_top.v and hexn_card_top.v), DIR/hexn.cst (clock and UART pins read from the card's MAN file),
            DIR/synth.ys, DIR/build.sh (yosys -> nextpnr-himbaechel-gowin -> gowin_pack; the same tools as the placed measurements), DIR/ASSEMBLY.json (pattern id, name, content hash, sha256 of every file, chain width, rows, card).
  image  REF.json UNIT.json --out FILE
         -> the config chain bytes for the 'B' command of hexn_frame_v1, after checking the unit against the pattern (header pattern id, base name); refused with a plain message when they do not match.
Python API: assemble(ref, outdir, man_path, clkdiv), chain_image(ref, program) -> bytes, check_unit_for(ref, unit) -> list of problems.
SCOPE, stated plainly: simulated end to end (tests/vm/test_hexn_assembler_v1.py, UART in / UART out); the yosys + nextpnr build script is written but only the PRE-EXISTING placed measurements (wrapper top) have been run, NOT build.sh of this frame; no board run. The frame is the UART command port of hexn_frame_v1, not the SPI-bridge frame of the scoping note.
Not wired into tools/project_assemble_v1.py (-s hexn): that proven file would need a clone (project_assemble_v2) for the one dispatch line; left for Alan's decision."""
import argparse, hashlib, json, os, shutil, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import hexn_pattern_gen_v8 as P
import hexn_icm_export_v3 as X

VDIR = os.path.join(ROOT, "sub", "verilog")
FRAME_FILES = [os.path.join(VDIR, f) for f in ("hexn_cross_v1.v", "hexn_xtop_v1.v", "hexn_frame_v1.v")]
DEFAULT_MAN = os.path.join(ROOT, "docs", "man", "tang-nano-20k.man.json")


def chain_len(ref):
    return sum(P.widths_of(ref))


def chain_image(ref, program):
    """the config chain as bytes for the frame's 'B' command: chain bit i (the i-th bit shifted in) is bit (i mod 8) of byte (i div 8)"""
    words, widths = P.load_words(ref, program); bits = P.chain_bits(words, widths)
    out = bytearray((len(bits) + 7) // 8)
    for i, b in enumerate(bits):
        if b: out[i // 8] |= 1 << (i % 8)
    return bytes(out)


def check_unit_for(ref, unit):
    """problems (empty = fine) that stop this unit being loaded into a card built from this reference"""
    import hexn_unit_file_v1 as U
    probs = []
    st = U.check(unit)
    if st["header"] != U.OK: probs.append("unit header refused (status %d)" % st["header"])
    for p in U.PARTS:
        if st[p] != U.OK: probs.append("unit %s part refused (status %d)" % (p, st[p]))
    h = unit.get("header", {})
    if h.get("pattern") != ref["name"]: probs.append("unit is for pattern %r, this design is %r" % (h.get("pattern"), ref["name"]))
    if h.get("pattern_id") is not None and h["pattern_id"] != ref["pattern_id"]: probs.append("unit expects pattern id %08X, this design has %08X" % (h["pattern_id"], ref["pattern_id"]))
    return probs


def _sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def card_top(ref, clkdiv=234):
    return ("`default_nettype none\n// hexn_card_top for pattern %s (ID %s), generated by tools/hexn_assemble_v1.py; do not edit.\n"
            "module hexn_card_top #(parameter CLKDIV = %d) (input wire clk, input wire uart_rx, output wire uart_tx, output wire [5:0] led);\n"
            "    hexn_frame_v1 #(.ROWS(%d), .CHAIN_BITS(%d), .CLKDIV(CLKDIV), .PATTERN_ID(32'h%s)) f (.clk(clk), .rx(uart_rx), .tx(uart_tx), .led(led));\nendmodule\n") % (
        ref["name"], ref["pattern_id_hex"], clkdiv, ref["rows"], chain_len(ref), ref["pattern_id_hex"])


def cst_from_man(man):
    b = man["board"]
    try: clk, tx, rx = b["clock"]["CLK_27M"]["pin"], b["uart"]["tx"]["pin"], b["uart"]["rx"]["pin"]; leds = [b["leds"]["LED%d_N" % i] for i in range(6)]
    except KeyError as e: raise ValueError("MAN %s board table is missing %s: cannot build a .cst" % (man.get("card_id"), e))
    L = ['IO_LOC "clk" %d;' % clk, 'IO_PORT "clk" IO_TYPE=LVCMOS33 PULL_MODE=NONE;', 'IO_LOC "uart_tx" %d;' % tx, 'IO_PORT "uart_tx" IO_TYPE=LVCMOS33 PULL_MODE=UP DRIVE=8;',
         'IO_LOC "uart_rx" %d;' % rx, 'IO_PORT "uart_rx" IO_TYPE=LVCMOS33 PULL_MODE=UP;']
    for i, p in enumerate(leds): L += ['IO_LOC "led[%d]" %d;' % (i, p), 'IO_PORT "led[%d]" IO_TYPE=LVCMOS33 DRIVE=8;' % i]
    return "\n".join(L) + "\n"


def assemble(ref, outdir, man_path=None, clkdiv=234):
    import hexn_pattern_ref_v9 as R
    probs = R.check_reference(ref)
    if probs: raise ValueError("reference refused: %s" % probs)
    man = json.load(open(man_path or DEFAULT_MAN))
    src = os.path.join(outdir, "src"); os.makedirs(src, exist_ok=True)
    files = {}
    for f in P.FILES + FRAME_FILES:
        shutil.copy(f, src); files[os.path.basename(f)] = _sha(f)
    for name, text in (("hexn_pattern_top.v", P.generate(ref)), ("hexn_card_top.v", card_top(ref, clkdiv))):
        open(os.path.join(src, name), "w").write(text); files[name] = hashlib.sha256(text.encode()).hexdigest()
    open(os.path.join(outdir, "hexn.cst"), "w").write(cst_from_man(man))
    vs = sorted(files)
    open(os.path.join(outdir, "synth.ys"), "w").write("".join("read_verilog -sv src/%s\n" % f for f in vs) + "hierarchy -top hexn_card_top\nsynth_gowin -top hexn_card_top -nowidelut -json hexn.json\n")
    dev = man["device"]
    open(os.path.join(outdir, "build.sh"), "w").write("#!/bin/sh\n# generated by hexn_assemble_v1.py for card %s; needs yosys, nextpnr-himbaechel (gowin) and gowin_pack\nset -e\nyosys -q -l synth.log synth.ys\n"
        "nextpnr-himbaechel --device GW2AR-LV18QN88C8/I7 --vopt family=GW2A-18C --vopt cst=hexn.cst --json hexn.json --write hexn_pnr.json --freq 27\n"
        "gowin_pack -d GW2A-18C -o hexn.fs hexn_pnr.json\n" % man["card_id"])
    os.chmod(os.path.join(outdir, "build.sh"), 0o755)
    rec = dict(format="hexn-assembly-v1", card=man["card_id"], device=str(dev)[:80], pattern=ref["name"], pattern_id=ref["pattern_id"], pattern_id_hex=ref["pattern_id_hex"], content_hash=ref["content_hash"],
               rows=ref["rows"], cols=ref["cols"], chain_bits=chain_len(ref), clkdiv=clkdiv, files=files,
               note="build.sh not run for this frame; placed measurements exist only for the pattern in its measurement wrapper")
    json.dump(rec, open(os.path.join(outdir, "ASSEMBLY.json"), "w"), indent=1, sort_keys=True)
    return rec


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0]); sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build"); b.add_argument("ref"); b.add_argument("--out", required=True); b.add_argument("--card", default="tang-nano-20k"); b.add_argument("--clkdiv", type=int, default=234)
    i = sub.add_parser("image"); i.add_argument("ref"); i.add_argument("unit"); i.add_argument("--out", required=True)
    a = ap.parse_args(); ref = json.load(open(a.ref))
    if a.cmd == "build":
        r = assemble(ref, a.out, os.path.join(ROOT, "docs", "man", a.card + ".man.json"), a.clkdiv); print("built", r["pattern"], r["pattern_id_hex"], "chain bits", r["chain_bits"])
    else:
        unit = json.load(open(a.unit)); pr = check_unit_for(ref, unit)
        if pr: sys.exit("refused: " + "; ".join(pr))
        open(a.out, "wb").write(chain_image(ref, X.from_icm(unit["program"]))); print("wrote", a.out)
