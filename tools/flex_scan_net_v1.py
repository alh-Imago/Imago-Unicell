#!/usr/bin/env python3
"""tools/flex_scan_net_v1.py -- ledger #1145: give a flex (v4sa) design a SCAN PATH through the registers that hold a word in flight, so the whole running state of the grid can be shifted OUT (capture) and back IN (restore).

New files only; no cell file and no assembler output is edited:
  * `<cell>_cell_v4sa_scan.v`  -- a clone of the proven v4sa cell with three added ports (scan_en, scan_in, scan_out). When scan_en is high (and rst/cfg_valid are not) the cell's DYNAMIC registers
    shift by one place as one chain; with scan_en low the cell is the proven cell exactly. The dynamic registers are those of docs/freeze/FREEZE_CAPTURE_LIST.md (the ones that change while the design runs):
        ram    : pending, have, data_reg            adder : pending, pending_c, carry_buffer, out_buffer
        merge  : pending, rr, out_buffer            branch: has_loaded_1, has_loaded_2, held1_reg, held2_reg, pending_1, pending_2, out_buffer
    Configuration registers (armed, modes, routes ...) are NOT in the chain: a restored card is configured by the same cfg pulse as the original and then loaded.
  * `<top>_fz_scan.v` -- the design `<top>_fz.v` (from flex_freeze_net_v1 / flex_busy_port_v1) with every non-constant cell swapped for its scan clone and the cells' scan ports daisy-chained, plus three new
    ports on the design: input scan_en, input scan_in, output scan_out. Constant cells (ASSEMBLY.json `constants`: always-valid sources whose only state is their configuration) are left out of the chain.
  * `SCAN_MAP.json` -- the chain in order: for each cell its type, registers, widths and where its bits sit in the shifted stream, and the total length.

Stream order: shifting N = total times with scan_in tied to scan_out leaves the state unchanged (recirculate) and the N bits that came out ARE the state. The same N bits fed back in on scan_in put that state in.
The first bit out is the most significant bit of the LAST cell's vector; the vectors come out in reverse chain order. SCAN_MAP.json gives the exact position of every register.

  python3 tools/flex_scan_net_v1.py ASSEMBLED_DIR TOP     (needs ASSEMBLED_DIR/TOP_fz.v and ASSEMBLY.json)
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CELLS = os.path.join(ROOT, "sub", "verilog")
SCAN_REGS = {
    "ram": ["pending", "have", "data_reg"],
    "adder": ["pending", "pending_c", "carry_buffer", "out_buffer"],
    "merge": ["pending", "rr", "out_buffer"],
    "branch": ["has_loaded_1", "has_loaded_2", "held1_reg", "held2_reg", "pending_1", "pending_2", "out_buffer"],
}


class ScanError(Exception):
    pass


def reg_widths(src, regs):
    out = []
    for r in regs:
        m = re.search(r"^\s*reg\s*(\[[^\]]+\])?\s*%s\b" % re.escape(r), src, re.M)
        if not m:
            raise ScanError("register %s not declared in the cell" % r)
        out.append("WIDTH" if m.group(1) and "WIDTH" in m.group(1) else "1")
    return out


def instrument(kind):
    path = os.path.join(CELLS, "%s_cell_v4sa.v" % kind)
    src = open(path).read()
    regs = SCAN_REGS[kind]
    wid = reg_widths(src, regs)
    if src.count("end else if (!freeze_in) begin") != 1:
        raise ScanError("%s: expected exactly one 'end else if (!freeze_in) begin'" % kind)
    if not re.search(r"input\s+wire\s+freeze_in\s*,", src):
        raise ScanError("%s: freeze_in port not found" % kind)
    sb = " + ".join(wid)
    cat = ", ".join(regs)
    out = src.replace("module %s_cell_v4sa " % kind, "module %s_cell_v4sa_scan " % kind, 1)
    out = re.sub(r"(input\s+wire\s+freeze_in\s*,)", r"\1\n    input  wire        scan_en,    // ledger #1145: shift the dynamic registers as one chain\n    input  wire        scan_in,\n    output wire        scan_out,", out, count=1)
    out = out.replace("    always @(posedge clk) begin",
                      "    // ledger #1145: scan chain over the registers that hold a word in flight (clone of the proven cell; with scan_en low it is the proven cell)\n"
                      "    localparam SB = %s;\n    wire [SB-1:0] scan_vec = {%s};\n    assign scan_out = scan_vec[SB-1];\n\n    always @(posedge clk) begin" % (sb, cat), 1)
    out = out.replace("end else if (!freeze_in) begin",
                      "end else if (scan_en) begin\n            {%s} <= {scan_vec[SB-2:0], scan_in};\n        end else if (!freeze_in) begin" % cat, 1)
    out = "// GENERATED by tools/flex_scan_net_v1.py (ledger #1145) from %s_cell_v4sa.v; do not hand-edit.\n" % kind + out
    return out, regs, wid


def width_of(expr, width_param):
    return width_param if expr == "WIDTH" else 1


def make(dirpath, top):
    src = open(os.path.join(dirpath, top + "_fz.v")).read()
    consts = {"c_" + re.sub(r"[^A-Za-z0-9_]", "_", c) for c in json.load(open(os.path.join(dirpath, "ASSEMBLY.json")))["constants"]}
    cells = {}
    for kind in SCAN_REGS:
        text, regs, wid = instrument(kind)
        open(os.path.join(dirpath, "%s_cell_v4sa_scan.v" % kind), "w").write(text)
        cells[kind] = (regs, wid)
    lines = src.split("\n")
    out, chain, n = [], [], 0
    inst = re.compile(r"^(\w+)_cell_v4sa(\s+#\(.*?\))?\s+(c_\w+)\s*\((.*)$")
    for ln in lines:
        m = inst.match(ln)
        if not m:
            out.append(ln)
            continue
        kind, params, name = m.group(1), m.group(2) or "", m.group(3)
        if name in consts:
            out.append(ln)
            continue
        if kind not in SCAN_REGS:
            raise ScanError("cell %s is a %s: no scan clone for that type yet" % (name, kind))
        wm = re.search(r"\.WIDTH\((\d+)\)", params)
        w = int(wm.group(1)) if wm else 32
        if ".freeze_in(freeze_all)" not in ln:
            raise ScanError("cell %s has no .freeze_in(freeze_all)" % name)
        ln2 = ln.replace(kind + "_cell_v4sa", kind + "_cell_v4sa_scan", 1)
        ln2 = ln2.replace(".freeze_in(freeze_all)", ".freeze_in(freeze_all), .scan_en(scan_en), .scan_in(sc[%d]), .scan_out(sc[%d])" % (n, n + 1), 1)
        regs, wid = cells[kind]
        chain.append({"cell": name, "type": kind, "width": w, "regs": [{"name": r, "bits": width_of(e, w)} for r, e in zip(regs, wid)]})
        out.append(ln2)
        n += 1
    if n == 0:
        raise ScanError("no scannable cell instances found")
    text = "\n".join(out)
    text = text.replace("module %s_fz (" % top, "module %s_fz_scan (\n    input  wire scan_en,\n    input  wire scan_in,\n    output wire scan_out," % top, 1)
    decl = "wire [%d:0] sc;\nassign sc[0] = scan_in;\nassign scan_out = sc[%d];\n" % (n, n)
    i = text.index(");", text.index("module %s_fz_scan" % top)) + 2
    text = text[:i] + "\n" + decl + text[i:]
    open(os.path.join(dirpath, top + "_fz_scan.v"), "w").write(text)
    # positions in the shifted stream: the last cell's vector comes out first
    total = 0
    for c in chain:
        c["bits"] = sum(r["bits"] for r in c["regs"])
        total += c["bits"]
    pos = 0
    for c in reversed(chain):
        c["stream_offset"] = pos
        off = pos
        for r in c["regs"]:
            r["stream_offset"] = off
            off += r["bits"]
        pos += c["bits"]
    meta = {"top": top + "_fz_scan", "cells_in_chain": n, "total_bits": total, "chain": chain,
            "stream_order": "bit 0 = first bit shifted out = MSB of the last cell's vector; registers inside a cell come out in the listed order, each MSB first",
            "constants_left_out": sorted(consts)}
    json.dump(meta, open(os.path.join(dirpath, "SCAN_MAP.json"), "w"), indent=1)
    return meta


if __name__ == "__main__":
    m = make(sys.argv[1], sys.argv[2])
    print("scan chain: %d cells, %d bits" % (m["cells_in_chain"], m["total_bits"]))
