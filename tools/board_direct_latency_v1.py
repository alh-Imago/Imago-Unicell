#!/usr/bin/env python3
"""tools/board_direct_latency_v1.py -- ledger #1206: test T2 of docs/NO_INTERRUPT_PARALLEL_TEST_PLAN_v3.md on the Tang Nano 20K.

How long from a change on a real input pin to the design's result changing, and does that time wobble?

The chip generates its own "sensor": a random-timed edge on an output pin (STIM, Tang pin 86) that Alan loops back with one jumper into sensor input 1 (pin 72).
The direct-mode unit (fpga/verilog/sd_unit_v1.v, the same RTL as unit_tree_direct_v1) samples that pin once per millisecond, feeds the tree design and latches the result.
A counter on the 27 MHz clock times every event, rising edge and falling edge, and keeps for each of four numbers the smallest, the largest and the sum:
  A = edge to result (includes the wait for the next 1 ms sample: a spread of up to 27,000 clocks is EXPECTED, it is the sampling window, not jitter),
  B = last sample tick to result (what the design itself adds after sampling: the part that must not wobble).
The measurement counts clocks, so the numbers do not depend on any outside instrument. Two builds: lat_idle (nothing else running) and lat_busy (24 free-running 32-bit
xorshift lanes, whose folded output is part of the printed line so synthesis cannot delete them).
The sample tick is replicated in this top (same reset, same 27,000-clock period as the unit's own counter); the simulation checks that this copy is in step (B must be constant).
Usage: python3 tools/board_direct_latency_v1.py [--out fpga/board_tests_latency] [--no-pnr] [--seed N] [--sim-only]
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import sd_unit_top_v1 as U  # noqa: E402
import board_tests_v1 as bt  # noqa: E402

ICM = os.path.join(ROOT, "nano", "examples", "parallel_reduction_tree.icm-hier.json")
NCYC = 2048          # rising + falling edge pairs on the card
STORM_LANES = 24
PERIOD_NS = 1000.0 / 27.0   # 37.037 ns per clock

SERIES = ["rA", "rB", "fA", "fB"]


def hexfn():
    return """    function [7:0] hx(input [3:0] n); hx = (n < 4'd10) ? (8'd48 + {4'b0, n}) : (8'd55 + {4'b0, n}); endfunction
    function [63:0] h8(input [31:0] v); h8 = {hx(v[31:28]), hx(v[27:24]), hx(v[23:20]), hx(v[19:16]), hx(v[15:12]), hx(v[11:8]), hx(v[7:4]), hx(v[3:0])}; endfunction
"""


def top_v(ins, outs):
    conn = ", ".join([f".in_{p}_data(lane_data[{j}*32 +: 32]), .in_{p}_valid(lane_valid[{j}]), .in_{p}_ack(lane_ack[{j}])" for j, p in enumerate(ins)] +
                     [f".out_{p}_data(out_data[{k}*32 +: 32]), .out_{p}_valid(out_valid[{k}]), .out_{p}_ack(out_ack[{k}])" for k, p in enumerate(outs)])
    L, O = len(ins), len(outs)
    # storm lanes
    st = []
    for i in range(STORM_LANES):
        seed = (0x9E3779B9 * (i + 1)) & 0xFFFFFFFF or 1
        st.append(f"    reg [31:0] s{i} = 32'h{seed:08X}; wire [31:0] a{i} = s{i} ^ (s{i} << 13); wire [31:0] b{i} = a{i} ^ (a{i} >> 17); wire [31:0] c{i} = b{i} ^ (b{i} << 5);")
        st.append(f"    always @(posedge clk) if (STORM != 0) s{i} <= c{i};")
    fold = " ^ ".join(f"s{i}" for i in range(STORM_LANES))
    stats = []
    for s in SERIES:
        stats.append(f"    reg [31:0] {s}_mn = 32'hFFFFFFFF, {s}_mx = 32'd0, {s}_sm = 32'd0;")
    upd = []
    for s in SERIES:
        upd.append(f"            task_{s}: ;")
    # line parts: (verilog expr, bytes)
    parts = [('"UCT "', 4), ("NAME", 8), ('" res="', 5), ("res_c", 1), ('" n="', 3), ("h8(ncyc)", 8), ('" to="', 4), ("h8(to_fail)", 8)]
    for s in SERIES:
        parts += [(f'" {s}="', 4), (f"h8({s}_mn)", 8), ('","', 1), (f"h8({s}_mx)", 8), ('","', 1), (f"h8({s}_sm)", 8)]
    parts += [('" chk="', 5), ("h8(chk)", 8), ('"\\015\\n"', 2)]
    line = ", ".join(e for e, _ in parts)
    LEN = sum(n for _, n in parts)

    def rec(series_a, series_b, cond_tag):
        # record A and B for one event
        out = []
        for s, val in ((series_a, "lat_a"), (series_b, "lat_b")):
            out.append(f"{s}_mn <= ({val} < {s}_mn) ? {val} : {s}_mn; {s}_mx <= ({val} > {s}_mx) ? {val} : {s}_mx; {s}_sm <= {s}_sm + {val};")
        return " ".join(out)

    v = f"""// lat_top.v -- GENERATED by tools/board_direct_latency_v1.py (ledger #1206). T2: input-pin edge to result latency, counted in 27 MHz clocks. Do not hand-edit.
`default_nettype none
module lat_top #(parameter [63:0] NAME = "lat_idle", parameter integer STORM = 0, parameter integer NCYC = {NCYC}, parameter integer GAPW = 17, parameter integer HOLDW = 16,
                 parameter integer CPB = {bt.CPB}, parameter integer TO = 100000, parameter integer WARM = 200000, parameter integer REPEAT = 40000000) (
    input  wire BOARD_CLK, output wire UART_TX, input wire SENS0, output wire STIM,
    output wire LED0_N, output wire LED1_N, output wire LED2_N, output wire LED3_N
);
    wire clk = BOARD_CLK;
{hexfn()}
    // same power-up reset as unit_top
    reg [15:0] rcnt = 0; wire rst = ~&rcnt; always @(posedge clk) if (rst) rcnt <= rcnt + 1'b1;
    reg cfg_done = 1'b0, cfg_valid = 1'b0;
    always @(posedge clk) begin cfg_valid <= 1'b0; if (rst) cfg_done <= 1'b0; else if (!cfg_done) begin cfg_valid <= 1'b1; cfg_done <= 1'b1; end end
    wire [{L}*32-1:0] lane_data; wire [{L - 1}:0] lane_valid, lane_ack;
    wire [{O}*32-1:0] out_data;  wire [{O - 1}:0] out_valid, out_ack;
    wire ready_line, direct_on, live_nz, live_two; wire [15:0] live_amt;
    sd_unit_v1 #(.LANES({L}), .OUTS({O}), .AW(10), .INIT_DIV(34), .FAST_DIV(2), .DESIGN_ID(32'h54524545), .NSENS(2), .DIRECT_RAW(0), .DIRECT_DEFAULT(1), .SENS_INVERT(0)) U (
        .clk(clk), .rst(rst), .sd_clk(), .sd_mosi(), .sd_miso(1'b1), .sd_cs_n(),
        .spi_sclk(1'b0), .spi_cs_n(1'b1), .spi_mosi(1'b0), .spi_miso(),
        .lane_data(lane_data), .lane_valid(lane_valid), .lane_ack(lane_ack), .out_data(out_data), .out_valid(out_valid), .out_ack(out_ack), .ready_line(ready_line),
        .sens_pins({{1'b0, SENS0}}), .direct_on(direct_on), .live_nz(live_nz), .live_two(live_two), .live_amt(live_amt));
    {U_TOP} D (.clk(clk), .rst(rst), .cfg_valid(cfg_valid), {conn});

    // ---- clocks: a free-running count, and a copy of the unit's 1 ms sample tick (same reset, period 27,000 clocks)
    reg [31:0] now = 32'd0; always @(posedge clk) now <= now + 1'b1;
    reg [14:0] tick = 15'd0; wire tick_hit = (tick == 15'd26999);
    always @(posedge clk) if (rst) tick <= 15'd0; else tick <= tick_hit ? 15'd0 : tick + 1'b1;
    reg [31:0] last_tick = 32'd0; always @(posedge clk) if (tick_hit) last_tick <= now;

    // ---- the free-running load (STORM lanes of xorshift32); its folded output is printed so it stays in the build
{chr(10).join(st)}
    (* keep *) reg [31:0] chk = 32'd0;
    always @(posedge clk) if (STORM != 0) chk <= chk ^ ({fold});

    // ---- random numbers
    reg [31:0] lf = 32'hACE1BEEF; always @(posedge clk) lf <= {{lf[30:0], lf[31] ^ lf[21] ^ lf[1] ^ lf[0]}};

    // ---- the event loop: gap, rising edge, wait for the result, hold, falling edge, wait for the result
{chr(10).join(stats)}
    reg stim_r = 1'b0; assign STIM = stim_r;
    reg [3:0] st = 4'd0; reg [31:0] t0 = 32'd0, cnt = 32'd0, to_cnt = 32'd0, to_fail = 32'd0, ncyc = 32'd0;
    wire [31:0] lat_a = now - t0, lat_b = now - last_tick;
    localparam S_WARM = 0, S_GAP = 1, S_RGO = 2, S_RWAIT = 3, S_HOLD = 4, S_FGO = 5, S_FWAIT = 6, S_DONE = 7;
    always @(posedge clk) begin
        case (st)
            S_WARM: if (!rst && now > WARM) begin st <= S_GAP; cnt <= 32'd2000 + {{15'd0, lf[GAPW-1:0]}}; end
            S_GAP:  if (cnt == 0) st <= S_RGO; else cnt <= cnt - 1'b1;
            S_RGO:  begin stim_r <= 1'b1; t0 <= now; to_cnt <= 32'd0; st <= S_RWAIT; end
            S_RWAIT: begin
                to_cnt <= to_cnt + 1'b1;
                if (live_amt != 16'd0) begin {rec("rA", "rB", "r")} cnt <= 32'd3000 + {{16'd0, lf[HOLDW-1:0]}}; st <= S_HOLD; end
                else if (to_cnt >= TO) begin to_fail <= to_fail + 1'b1; cnt <= 32'd3000 + {{16'd0, lf[HOLDW-1:0]}}; st <= S_HOLD; end
            end
            S_HOLD: if (cnt == 0) st <= S_FGO; else cnt <= cnt - 1'b1;
            S_FGO:  begin stim_r <= 1'b0; t0 <= now; to_cnt <= 32'd0; st <= S_FWAIT; end
            S_FWAIT: begin
                to_cnt <= to_cnt + 1'b1;
                if (live_amt == 16'd0) begin {rec("fA", "fB", "f")} ncyc <= ncyc + 1'b1; cnt <= 32'd2000 + {{15'd0, lf[GAPW-1:0]}}; st <= (ncyc + 1 == NCYC) ? S_DONE : S_GAP; end
                else if (to_cnt >= TO) begin to_fail <= to_fail + 1'b1; ncyc <= ncyc + 1'b1; cnt <= 32'd2000 + {{15'd0, lf[GAPW-1:0]}}; st <= (ncyc + 1 == NCYC) ? S_DONE : S_GAP; end
            end
            default: ;
        endcase
    end
    wire done = (st == S_DONE);
    wire [7:0] res_c = (to_fail == 0) ? "P" : "F";

    // ---- print the line once the run is over, then again every REPEAT clocks
    wire [8*{LEN}-1:0] line = {{{line}}};
    reg [7:0] ci = 8'd0; reg [31:0] rep = 32'd0; reg sending = 1'b0; reg start = 1'b0; wire busy;
    board_uart_tx #(.CPB(CPB)) T (.clk(clk), .start(start), .data(line[(({LEN}-1)-ci)*8 +: 8]), .tx(UART_TX), .busy(busy));
    always @(posedge clk) begin
        start <= 1'b0;
        if (!done) begin sending <= 1'b0; ci <= 8'd0; rep <= 32'd0; end
        else if (!sending) begin if (rep >= REPEAT || rep == 0) begin sending <= 1'b1; ci <= 8'd0; rep <= 32'd1; end else rep <= rep + 1'b1; end
        else if (start) ci <= ci + 1'b1;          // the transmitter is latching line[ci] this cycle; move on to the next byte
        else if (!busy) begin
            if (ci == {LEN}) begin sending <= 1'b0; end
            else start <= 1'b1;
        end
    end
    reg [24:0] hb = 25'd0; always @(posedge clk) hb <= hb + 1'b1;
    assign LED0_N = ~hb[24]; assign LED1_N = ~(done && to_fail == 0); assign LED2_N = ~(done && to_fail != 0); assign LED3_N = ~done;
endmodule
`default_nettype wire
"""
    return v, LEN


U_TOP = "icm_parallel_reduction_tree_flex"

CST = """IO_LOC "BOARD_CLK" 4;
IO_PORT "BOARD_CLK" IO_TYPE=LVCMOS33 PULL_MODE=NONE;
IO_LOC "UART_TX" 69;
IO_PORT "UART_TX" IO_TYPE=LVCMOS33 DRIVE=8;
IO_LOC "LED0_N" 15;
IO_PORT "LED0_N" IO_TYPE=LVCMOS33 DRIVE=8;
IO_LOC "LED1_N" 16;
IO_PORT "LED1_N" IO_TYPE=LVCMOS33 DRIVE=8;
IO_LOC "LED2_N" 17;
IO_PORT "LED2_N" IO_TYPE=LVCMOS33 DRIVE=8;
IO_LOC "LED3_N" 18;
IO_PORT "LED3_N" IO_TYPE=LVCMOS33 DRIVE=8;
IO_LOC "SENS0" 72;
IO_PORT "SENS0" IO_TYPE=LVCMOS33 PULL_MODE=DOWN;
IO_LOC "STIM" 86;
IO_PORT "STIM" IO_TYPE=LVCMOS33 DRIVE=8;
"""

TB = """`timescale 1ns / 1ps
module tb;
    reg clk = 0; always #18.5 clk = ~clk;
    wire tx, stim, l0, l1, l2, l3;
    lat_top #(.NAME("%(name)s"), .STORM(%(storm)d), .NCYC(%(ncyc)d), .GAPW(%(gapw)d), .HOLDW(%(holdw)d), .TO(100000), .WARM(200000), .REPEAT(100000000)) dut (.BOARD_CLK(clk), .UART_TX(tx), .SENS0(stim), .STIM(stim), .LED0_N(l0), .LED1_N(l1), .LED2_N(l2), .LED3_N(l3));
    integer i; reg [7:0] b;
    initial begin
        forever begin
            @(negedge tx);
            #(%(half)d);
            b = 0;
            for (i = 0; i < 8; i = i + 1) begin #(%(bit)d); b = {tx, b[7:1]}; end
            #(%(bit)d);
            $write("%%c", b);
            if (b == 8'h0A) begin $display("END"); $finish; end
        end
    end
    initial begin #(%(limit)d); $display("TIMEOUT"); $finish; end
endmodule
"""


def parse(line):
    d = {}
    m = re.match(r"UCT (\S+) res=(\w) n=([0-9A-F]{8}) to=([0-9A-F]{8})", line)
    d["name"], d["res"], d["n"], d["to"] = m.group(1), m.group(2), int(m.group(3), 16), int(m.group(4), 16)
    for s in SERIES:
        mm = re.search(s + r"=([0-9A-F]{8}),([0-9A-F]{8}),([0-9A-F]{8})", line)
        d[s] = tuple(int(x, 16) for x in mm.groups())
    d["chk"] = int(re.search(r"chk=([0-9A-F]{8})", line).group(1), 16)
    return d


def sim(work, files, name, storm, ncyc, gapw, holdw):
    wd = os.path.join(work, "sim_" + name)
    shutil.rmtree(wd, ignore_errors=True)
    os.makedirs(wd)
    open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
    open(os.path.join(wd, "tb.v"), "w").write(TB % dict(name=name, storm=storm, ncyc=ncyc, gapw=gapw, holdw=holdw, half=int(bt.CPB * 37.037 / 2), bit=int(bt.CPB * 37.037), limit=ncyc * 400000 * 37 + 400000 * 37 * 4))
    cmd = ["iverilog", "-g2012", "-o", "sim.vvp", "tb.v", "board_uart_tx.v"] + files
    r = subprocess.run(cmd, cwd=wd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("iverilog: " + r.stderr[-1500:])
    r = subprocess.run(["vvp", "sim.vvp"], cwd=wd, capture_output=True, text=True, timeout=3000)
    out = r.stdout
    line = next((ln for ln in out.splitlines() if ln.startswith("UCT")), "")
    if not line:
        raise SystemExit("simulation printed no UCT line:\n" + out[-800:])
    return line.strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "board_tests_latency"))
    ap.add_argument("--no-pnr", action="store_true")
    ap.add_argument("--sim-only", action="store_true")
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(os.path.join(out, "groups"), exist_ok=True)
    work = tempfile.mkdtemp(prefix="blat_")
    ud = os.path.join(work, "unit")
    top, ins, outs = U.build(ICM, ud, 2, 1)
    assert top == U_TOP, top
    flist = [os.path.join(ud, p) for p in open(os.path.join(ud, "FILES.txt")).read().split() if p != "unit_top.v"]
    v, LEN = top_v(ins, outs)
    open(os.path.join(work, "lat_top.v"), "w").write(v)
    files = [os.path.join(work, "lat_top.v")] + flist
    meta = {"line_bytes": LEN, "ncyc": NCYC, "storm_lanes": STORM_LANES, "period_ns": PERIOD_NS, "builds": {}}
    for name, storm in (("lat_idle", 0), ("lat_busy", 1)):
        # simulation with a short run and short gaps: the checks are B constant, A spread over the sampling window, no time-outs
        sl = sim(work, files, name, storm, 24, 12, 11)
        d = parse(sl)
        print("SIM", sl)
        if d["res"] != "P" or d["to"] != 0 or d["n"] != 24:
            raise SystemExit(f"{name}: simulation not clean: {sl}")
        for s in ("rB", "fB"):
            if d[s][0] != d[s][1]:
                raise SystemExit(f"{name}: {s} is not constant in simulation (min {d[s][0]}, max {d[s][1]}): the tick copy may be out of step: {sl}")
        meta["builds"][name] = {"sim_line": sl, "storm": storm}
        if a.sim_only:
            continue
        wd = os.path.join(work, "syn_" + name)
        os.makedirs(wd)
        txt = open(os.path.join(work, "lat_top.v")).read().replace('parameter [63:0] NAME = "lat_idle", parameter integer STORM = 0', f'parameter [63:0] NAME = "{name}", parameter integer STORM = {storm}')
        open(os.path.join(wd, "lat_top.v"), "w").write(txt)
        open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
        names = []
        for f in flist:
            shutil.copy(f, os.path.join(wd, os.path.basename(f)))
            names.append(os.path.basename(f))
        open(os.path.join(wd, "g.cst"), "w").write(CST)
        fl = ["lat_top.v", "board_uart_tx.v"] + names
        s = subprocess.run(["yosys", "-q", "-l", "y.log", "-p", "read_verilog -sv %s; hierarchy -top lat_top; synth_gowin -top lat_top -nowidelut -json g.json" % " ".join(fl)], cwd=wd, capture_output=True, text=True, timeout=3000)
        if s.returncode:
            raise SystemExit("yosys: " + (s.stderr or s.stdout)[-800:])
        st = open(os.path.join(wd, "y.log")).read()
        lut = re.findall(r"^\s+(\d+)\s+LUT4", st, re.M)
        ff = re.findall(r"^\s+(\d+)\s+DFF\w*", st, re.M)
        meta["builds"][name]["lut4_synth"] = int(lut[-1]) if lut else None
        meta["builds"][name]["dff_synth"] = sum(int(x) for x in ff) if ff else None
        if not a.no_pnr:
            p = subprocess.run(["yowasp-nextpnr-himbaechel-gowin", "--device", bt.DEVICE, "--vopt", "family=GW2A-18C", "--vopt", "cst=g.cst", "--seed", str(a.seed), "--json", "g.json",
                                "--write", "g_r.json", "--report", "g_rep.json", "--freq", "27"], cwd=wd, capture_output=True, text=True, timeout=7000)
            if p.returncode:
                raise SystemExit("nextpnr: " + (p.stdout[-500:] + p.stderr[-600:]))
            rep = json.load(open(os.path.join(wd, "g_rep.json")))
            fmax = rep["fmax"]["clk"]["achieved"] if "clk" in rep["fmax"] else min(x["achieved"] for x in rep["fmax"].values())
            u = rep["utilization"]
            meta["builds"][name].update(fmax_mhz=round(fmax, 1), lut4=u["LUT4"]["used"], dff=u["DFF"]["used"])
            if fmax < 27:
                raise SystemExit(f"{name}: timing NOT met at 27 MHz (Fmax {fmax:.1f})")
            g = subprocess.run(["gowin_pack", "-d", bt.DEVICE, "-o", os.path.abspath(os.path.join(out, "groups", name + ".fs")), "-s", "g.cst", "g_r.json"], cwd=wd, capture_output=True, text=True)
            if g.returncode:
                raise SystemExit("gowin_pack: " + g.stderr[-400:])
            shutil.copy(os.path.join(wd, "g.cst"), os.path.join(out, "groups", name + ".cst"))
        print(name, {k: v for k, v in meta["builds"][name].items() if k != "sim_line"})
    b = meta["builds"]
    if not a.sim_only and b["lat_busy"].get("dff") and b["lat_idle"].get("dff"):
        extra = b["lat_busy"]["dff"] - b["lat_idle"]["dff"]      # flip-flops after place and route (the synthesis log's DFF lines double count)
        print("flip-flops added by the busy build:", extra, "(expected about", STORM_LANES * 32 + 32, ")")
        if extra < STORM_LANES * 32:
            raise SystemExit("the busy build did not keep its load lanes: synthesis deleted them")
    shutil.copy(os.path.join(work, "lat_top.v"), os.path.join(out, "lat_top_generated.v"))
    json.dump(meta, open(os.path.join(out, "latency_meta.json"), "w"), indent=1)
    print("done:", out)


if __name__ == "__main__":
    main()
