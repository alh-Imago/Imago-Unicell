# testbench: a behavioural stand-in for the ESP32 answering after a fixed delay (1.5 us); the real ESP32 is NOT simulated
TB = """`timescale 1ns / 1ps
module tb;
    reg clk = 0; always #18.5 clk = ~clk;
    wire tx, stim, stormp, l0, l1, l2, l3, l4, l5;
    reg resp = 1'b0;
    always @(stim) #1500 resp = stim;
    c1_top #(.NAME("%(name)s"), .STORM(%(storm)d), .NCYC(%(ncyc)d), .GAPW(12), .TO(%(to)d), .WARM(2000), .REPEAT(100000000), .PRET(20000), .PRED(10000)) dut (.BOARD_CLK(clk), .UART_TX(tx), .RESP(resp), .STIM(stim), .STORMP(stormp), .LED0_N(l0), .LED1_N(l1), .LED2_N(l2), .LED3_N(l3), .LED4_N(l4), .LED5_N(l5));
    integer i; reg [7:0] b; integer toggles = 0; always @(stormp) toggles = toggles + 1;
    initial begin
        forever begin
            @(negedge tx);
            #(%(half)d);
            b = 0;
            for (i = 0; i < 8; i = i + 1) begin #(%(bit)d); b = {tx, b[7:1]}; end
            #(%(bit)d);
            $write("%%c", b);
            if (b == 8'h0A) begin $display("STORMTOGGLES %%0d", toggles); $finish; end
        end
    end
    initial begin #(%(limit)d); $display("TIMEOUT"); $finish; end
endmodule
"""


def parse(line):
    m = re.match(r"UCC (\S+) res=(\w) n=([0-9A-F]{8}) to=([0-9A-F]{8}) pre=([0-9A-F]{8})", line)
    d = dict(name=m.group(1), res=m.group(2), n=int(m.group(3), 16), to=int(m.group(4), 16), pre=int(m.group(5), 16))
    for s in ("r", "f"):
        mm = re.search(r" %s=([0-9A-F]{8}),([0-9A-F]{8}),([0-9A-F]{8})" % s, line)
        d[s] = tuple(int(x, 16) for x in mm.groups())
    mm = re.search(r" h=([0-9A-F,]+)", line)
    d["h"] = [int(x, 16) for x in mm.group(1).split(",")]
    return d


def sim(work, name, storm, ncyc):
    wd = os.path.join(work, "sim_" + name)
    shutil.rmtree(wd, ignore_errors=True)
    os.makedirs(wd)
    open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
    open(os.path.join(wd, "tb.v"), "w").write(TB % dict(name=name, storm=storm, ncyc=ncyc, to=TO_CLK, half=int(bt.CPB * 37.037 / 2), bit=int(bt.CPB * 37.037), limit=ncyc * 400000 * 37 + 100000 * 37 * 40))
    r = subprocess.run(["iverilog", "-g2012", "-o", "sim.vvp", "tb.v", "board_uart_tx.v", os.path.join(work, "c1_top.v")], cwd=wd, capture_output=True, text=True)
    if r.returncode:
        raise SystemExit("iverilog: " + r.stderr[-1500:])
    r = subprocess.run(["vvp", "sim.vvp"], cwd=wd, capture_output=True, text=True, timeout=3000)
    line = next((ln for ln in r.stdout.splitlines() if ln.startswith("UCC")), "")
    tog = next((int(ln.split()[1]) for ln in r.stdout.splitlines() if ln.startswith("STORMTOGGLES")), -1)
    if not line:
        raise SystemExit("simulation printed no UCC line:\n" + r.stdout[-800:])
    return line.strip(), tog


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "board_tests_c1"))
    ap.add_argument("--no-pnr", action="store_true")
    ap.add_argument("--sim-only", action="store_true")
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(os.path.join(out, "groups"), exist_ok=True)
    work = tempfile.mkdtemp(prefix="bc1_")
    v, LEN = top_v()
    open(os.path.join(work, "c1_top.v"), "w").write(v)
    meta = {"line_bytes": LEN, "ncyc": NEV, "builds": {}}
    for name, storm in (("c1_quiet", 0), ("c1_storm", 1)):
        sl, tog = sim(work, name, storm, 24)
        d = parse(sl)
        print("SIM", sl, "| storm pin toggles:", tog)
        if d["res"] != "P" or d["to"] != 0 or d["n"] != 24 or d["pre"] != 16:
            raise SystemExit(f"{name}: simulation not clean: {sl}")
        if (storm == 0) != (tog == 0):
            raise SystemExit(f"{name}: storm pin toggles {tog} do not match the build")
        for s in ("r", "f"):
            if d[s][1] - d[s][0] > 1:
                raise SystemExit(f"{name}: {s} spread {d[s][1] - d[s][0]} in simulation with a fixed-delay stand-in; expected at most 1 clock")
        meta["builds"][name] = {"sim_line": sl, "storm_toggles_sim": tog}
        if a.sim_only:
            continue
        wd = os.path.join(work, "syn_" + name)
        os.makedirs(wd)
        txt = open(os.path.join(work, "c1_top.v")).read().replace('parameter [63:0] NAME = "c1_quiet", parameter integer STORM = 0', f'parameter [63:0] NAME = "{name}", parameter integer STORM = {storm}')
        open(os.path.join(wd, "c1_top.v"), "w").write(txt)
        open(os.path.join(wd, "board_uart_tx.v"), "w").write(bt.UART_V)
        open(os.path.join(wd, "g.cst"), "w").write(CST)
        s = subprocess.run(["yosys", "-q", "-l", "y.log", "-p", "read_verilog -sv c1_top.v board_uart_tx.v; hierarchy -top c1_top; synth_gowin -top c1_top -nowidelut -json g.json"], cwd=wd, capture_output=True, text=True, timeout=3000)
        if s.returncode:
            raise SystemExit("yosys: " + (s.stderr or s.stdout)[-800:])
        if not a.no_pnr:
            p = subprocess.run(["yowasp-nextpnr-himbaechel-gowin", "--device", bt.DEVICE, "--vopt", "family=GW2A-18C", "--vopt", "cst=g.cst", "--seed", str(a.seed), "--json", "g.json",
                                "--write", "g_r.json", "--report", "g_rep.json", "--freq", "27"], cwd=wd, capture_output=True, text=True, timeout=7000)
            if p.returncode:
                raise SystemExit("nextpnr: " + (p.stdout[-500:] + p.stderr[-600:]))
            rep = json.load(open(os.path.join(wd, "g_rep.json")))
            fmax = rep["fmax"]["clk"]["achieved"] if "clk" in rep["fmax"] else min(x["achieved"] for x in rep["fmax"].values())
            u = rep["utilization"]
            meta["builds"][name].update(fmax_mhz=round(fmax, 1), lut4=u["LUT4"]["used"], dff=u["DFF"]["used"])
            if fmax < 27:
                raise SystemExit(f"{name}: timing NOT met at 27 MHz (Fmax {fmax:.1f})")
            g = subprocess.run(["gowin_pack", "-d", bt.DEVICE, "-o", os.path.abspath(os.path.join(out, "groups", name + ".fs")), "-s", "g.cst", "g_r.json"], cwd=wd, capture_output=True, text=True)
            if g.returncode:
                raise SystemExit("gowin_pack: " + g.stderr[-400:])
            shutil.copy(os.path.join(wd, "g.cst"), os.path.join(out, "groups", name + ".cst"))
        print(name, {k: v for k, v in meta["builds"][name].items() if k != "sim_line"})
    shutil.copy(os.path.join(work, "c1_top.v"), os.path.join(out, "c1_top_generated.v"))
    json.dump(meta, open(os.path.join(out, "c1_meta.json"), "w"), indent=1)
    print("done:", out)


if __name__ == "__main__":
    main()
