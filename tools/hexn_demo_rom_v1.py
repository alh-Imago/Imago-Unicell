#!/usr/bin/env python3
"""tools/hexn_demo_rom_v1.py -- Hex-N (new file 1 Nov 2026): writes fpga/verilog/hexn_demo_rom_v1.v, the power-up table for the reaction-game demo (a ROM of LOAD words + one BIAS word, 193 words).
Sensor slots used by the game: 0 = pressed the right button (bin 11) or the wrong one (bin 0); 1 = reaction time as a log2 bin (b = floor(log2 ms), capped at 11 = 2048 ms or more); 2..7 unused.
  reaction bin b: class 1 ('good hit') weight -10*max(0, b-7), class 0 weight -10*max(0, 8-b)  -> class 1 up to bin 7 (under 256 ms), class 0 from bin 8
  wrong button (slot 0, bin 0): class 1 weight -100                                              -> a wrong button is never a good hit
  bias 0.  Edit demo_table() to change the game's judging; the test reads the same function."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def demo_table():
    W = [[[0] * 16 for _ in range(8)] for _ in range(2)]
    for b in range(12):
        W[1][1][b] = -10 * max(0, b - 7); W[0][1][b] = -10 * max(0, 8 - b)
    W[1][0][0] = -100
    return W, 0
def words():
    import sys; sys.path.insert(0, os.path.join(ROOT, "tools")); import hexn_scorer_ref_v1 as R
    W, bias = demo_table()
    return [R.w_load(c, s, b, W[c][s][b]) for c in range(2) for s in range(8) for b in range(12)] + [R.w_bias(bias)]
def write():
    ws = words()
    L = ["// hexn_demo_rom_v1.v -- GENERATED by tools/hexn_demo_rom_v1.py (Hex-N, 1 Nov 2026). Power-up table words for the scorer demo. Do not hand-edit.",
         "module hexn_demo_rom_v1 (input wire [7:0] addr, output reg [31:0] data);",
         "    localparam N = %d;" % len(ws), "    always @* begin case (addr)"]
    L += ["        8'd%d: data = 32'h%08X;" % (i, w) for i, w in enumerate(ws)]
    L += ["        default: data = 32'hF0000000;", "    endcase end", "endmodule"]
    open(os.path.join(ROOT, "fpga", "verilog", "hexn_demo_rom_v1.v"), "w").write("\n".join(L) + "\n"); return len(ws)
if __name__ == "__main__": print(write(), "words written")
