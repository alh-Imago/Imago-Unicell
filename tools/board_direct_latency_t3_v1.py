#!/usr/bin/env python3
"""tools/board_direct_latency_t3_v1.py -- ledger #1209: test T3 of docs/NO_INTERRUPT_PARALLEL_TEST_PLAN_v3.md, cloned from tools/board_direct_latency_v2.py (T2, ledger #1207/#1208).

Does a second input changing at a random moment disturb the timing of the first?
Two jumpers: Tang pin 86 (STIM) -> pin 72 (sensor input 1) and pin 53 (STIM2) -> pin 71 (sensor input 2). Both are driven by the chip itself.
Each event the chip picks a new state of the two inputs (the number of active sensors must change, so the result must change). If only one input changes, that edge is timed (series s).
If BOTH change, the two edges are a random 0..65,535 clocks apart (0..2.4 ms, so they land in the same or in different 1 ms samples, in either order) and the time is taken from the FIRST edge to the final correct result (series d).
A = first edge to the final result; B = last 1 ms sample tick to the final result (the design's own part, expected to be constant at 8 clocks as in T2).
Also counted: bad = the result was not the right value at the end of a hold of at least 30,000 clocks (one sample tick always falls in it); to = events that never reached the right value.
Pre-flight as in T2: both pins toggled together slowly 16 times; pre= pin 72 followed, p1= pin 71 followed. res=L if either is not 16.
Two builds: lt3_idle and lt3_busy (24 free-running xorshift32 load lanes).
Usage: python3 tools/board_direct_latency_t3_v1.py [--out fpga/board_tests_latency3] [--no-pnr] [--seed N] [--sim-only]
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import sd_unit_top_v1 as U  # noqa: E402
import board_tests_v1 as bt  # noqa: E402

ICM = os.path.join(ROOT, "nano", "examples", "parallel_reduction_tree.icm-hier.json")
NCYC = 2048          # rising + falling edge pairs on the card
STORM_LANES = 24
PERIOD_NS = 1000.0 / 27.0   # 37.037 ns per clock

SERIES = ["sA", "sB", "dA", "dB"]


def hexfn():
    return """    function [7:0] hx(input [3:0] n); hx = (n < 4'd10) ? (8'd48 + {4'b0, n}) : (8'd55 + {4'b0, n}); endfunction
    function [63:0] h8(input [31:0] v); h8 = {hx(v[31:28]), hx(v[27:24]), hx(v[23:20]), hx(v[19:16]), hx(v[15:12]), hx(v[11:8]), hx(v[7:4]), hx(v[3:0])}; endfunction
"""


def top_v(ins, outs):
    conn = ", ".join([f".in_{p}_data(lane_data[{j}*32 +: 32]), .in_{p}_valid(lane_valid[{j}]), .in_{p}_ack(lane_ack[{j}])" for j, p in enumerate(ins)] +
                     [f".out_{p}_data(out_data[{k}*32 +: 32]), .out_{p}_valid(out_valid[{k}]), .out_{p}_ack(out_ack[{k}])" for k, p in enumerate(outs)])
    L, O = len(ins), len(outs)
    # storm lanes
    st = []
    for i in range(STORM_LANES):
        seed = (0x9E3779B9 * (i + 1)) & 0xFFFFFFFF or 1
        st.append(f"    reg [31:0] s{i} = 32'h{seed:08X}; wire [31:0] a{i} = s{i} ^ (s{i} << 13); wire [31:0] b{i} = a{i} ^ (a{i} >> 17); wire [31:0] c{i} = b{i} ^ (b{i} << 5);")
        st.append(f"    always @(posedge clk) if (STORM != 0) s{i} <= c{i};")
    fold = " ^ ".join(f"s{i}" for i in range(STORM_LANES))
    stats = []
    for s in SERIES:
        stats.append(f"    reg [31:0] {s}_mn = 32'hFFFFFFFF, {s}_mx = 32'd0, {s}_sm = 32'd0;")
    upd = []
    for s in SERIES:
        upd.append(f"            task_{s}: ;")
    # line parts: (verilog expr, bytes)
    parts = [('"UCT "', 4), ("NAME", 8), ('" res="', 5), ("res_c", 1), ('" n="', 3), ("h8(ncyc)", 8), ('" to="', 4), ("h8(to_fail)", 8), ('" pre="', 5), ("h8(pre_hit)", 8), ('" p1="', 4), ("h8(pre_hit1)", 8), ('" bad="', 5), ("h8(bad)", 8), ('" nd="', 4), ("h8(nd)", 8)]
    for s in SERIES:
        parts += [(f'" {s}="', 4), (f"h8({s}_mn)", 8), ('","', 1), (f"h8({s}_mx)", 8), ('","', 1), (f"h8({s}_sm)", 8)]
    parts += [('" chk="', 5), ("h8(chk)", 8), ('"\\015\\n"', 2)]
    line = ", ".join(e for e, _ in parts)
    LEN = sum(n for _, n in parts)

    def rec(series_a, series_b, cond_tag):
        # record A and B for one event
        out = []
        for s, val in ((series_a, "lat_a"), (series_b, "lat_b")):
            out.append(f"{s}_mn <= ({val} < {s}_mn) ? {val} : {s}_mn; {s}_mx <= ({val} > {s}_mx) ? {val} : {s}_mx; {s}_sm <= {s}_sm + {val};")
        return " ".join(out)

    v = f"""// lat_top.v -- GENERATED by tools/board_direct_latency_t3_v1.py (ledger #1209). T3: two input pins, edge to result latency, counted in 27 MHz clocks. Do not hand-edit.
`default_nettype none
module lat_top #(parameter [63:0] NAME = "lt3_idle", parameter integer STORM = 0, parameter integer NCYC = {NCYC}, parameter integer GAPW = 17, parameter integer HOLDW = 16,
                 parameter integer CPB = {bt.CPB}, parameter integer TO = 300000, parameter integer WARM = 200000, parameter integer REPEAT = 40000000, parameter integer PRET = 4000000, parameter integer PRED = 100000) (
    input  wire BOARD_CLK, output wire UART_TX, input wire SENS0, input wire SENS1, output wire STIM, output wire STIM2,
    output wire LED0_N, output wire LED1_N, output wire LED2_N, output wire LED3_N, output wire LED4_N, output wire LED5_N
);
    wire clk = BOARD_CLK;
{hexfn()}
    // same power-up reset as unit_top
    reg [15:0] rcnt = 0; wire rst = ~&rcnt; always @(posedge clk) if (rst) rcnt <= rcnt + 1'b1;
    reg cfg_done = 1'b0, cfg_valid = 1'b0;
    always @(posedge clk) begin cfg_valid <= 1'b0; if (rst) cfg_done <= 1'b0; else if (!cfg_done) begin cfg_valid <= 1'b1; cfg_done <= 1'b1; end end
    wire [{L}*32-1:0] lane_data; wire [{L - 1}:0] lane_valid, lane_ack;
    wire [{O}*32-1:0] out_data;  wire [{O - 1}:0] out_valid, out_ack;
    wire ready_line, direct_on, live_nz, live_two; wire [15:0] live_amt;
    sd_unit_v1 #(.LANES({L}), .OUTS({O}), .AW(10), .INIT_DIV(34), .FAST_DIV(2), .DESIGN_ID(32'h54524545), .NSENS(2), .DIRECT_RAW(0), .DIRECT_DEFAULT(1), .SENS_INVERT(0)) U (
        .clk(clk), .rst(rst), .sd_clk(), .sd_mosi(), .sd_miso(1'b1), .sd_cs_n(),
        .spi_sclk(1'b0), .spi_cs_n(1'b1), .spi_mosi(1'b0), .spi_miso(),
        .lane_data(lane_data), .lane_valid(lane_valid), .lane_ack(lane_ack), .out_data(out_data), .out_valid(out_valid), .out_ack(out_ack), .ready_line(ready_line),
        .sens_pins({{SENS1, SENS0}}), .direct_on(direct_on), .live_nz(live_nz), .live_two(live_two), .live_amt(live_amt));
    {U_TOP} D (.clk(clk), .rst(rst), .cfg_valid(cfg_valid), {conn});

    // ---- clocks: a free-running count, and a copy of the unit's 1 ms sample tick (same reset, period 27,000 clocks)
    reg [31:0] now = 32'd0; always @(posedge clk) now <= now + 1'b1;
    reg [14:0] tick = 15'd0; wire tick_hit = (tick == 15'd26999);
    always @(posedge clk) if (rst) tick <= 15'd0; else tick <= tick_hit ? 15'd0 : tick + 1'b1;
    reg [31:0] last_tick = 32'd0; always @(posedge clk) if (tick_hit) last_tick <= now;

    // ---- the free-running load (STORM lanes of xorshift32); its folded output is printed so it stays in the build
{chr(10).join(st)}
    (* keep *) reg [31:0] chk = 32'd0;
    always @(posedge clk) if (STORM != 0) chk <= chk ^ ({fold});

    // ---- random numbers
    reg [31:0] lf = 32'hACE1BEEF; always @(posedge clk) lf <= {{lf[30:0], lf[31] ^ lf[21] ^ lf[1] ^ lf[0]}};

    // ---- the event loop (T3): gap, pick a new state of the two inputs, one or two edges, wait for the right result, hold and check
{chr(10).join(stats)}
    reg stim_r = 1'b0, stim2_r = 1'b0; assign STIM = stim_r; assign STIM2 = stim2_r;
    reg [3:0] st = 4'd0; reg [31:0] t0 = 32'd0, cnt = 32'd0, to_cnt = 32'd0, to_fail = 32'd0, ncyc = 32'd0, bad = 32'd0, nd = 32'd0, dly = 32'd0;
    reg [1:0] tgt = 2'd0; reg [15:0] exp_amt = 16'd0; reg first1 = 1'b0, dual = 1'b0;
    wire [31:0] lat_a = now - t0, lat_b = now - last_tick;
    localparam S_WARM = 0, S_GAP = 1, S_PICK = 2, S_E1 = 3, S_D = 4, S_W = 5, S_HOLD = 6, S_DONE = 7, S_PRE = 8;
    reg [31:0] pre_hit = 32'd0, pre_hit1 = 32'd0, pre_n = 32'd0, pre_t = 32'd0;
    wire [1:0] nw = lf[1:0];
    wire [1:0] npop = {{1'b0, nw[0]}} + {{1'b0, nw[1]}};
    wire [1:0] cpop = {{1'b0, stim_r}} + {{1'b0, stim2_r}};
    wire ch0 = (nw[0] != stim_r), ch1 = (nw[1] != stim2_r);
    always @(posedge clk) begin
        case (st)
            S_WARM: if (!rst && now > WARM) begin st <= S_PRE; pre_t <= 32'd0; end
            S_PRE: begin
                // pre-flight: both pins toggle together, slowly, 16 times; PRED clocks after each toggle each input must equal its output
                pre_t <= pre_t + 1'b1;
                if (pre_t == 32'd0) begin stim_r <= ~stim_r; stim2_r <= ~stim2_r; end
                if (pre_t == PRED) begin if (SENS0 == stim_r) pre_hit <= pre_hit + 1'b1; if (SENS1 == stim2_r) pre_hit1 <= pre_hit1 + 1'b1; pre_n <= pre_n + 1'b1; end
                if (pre_t >= PRET) begin pre_t <= 32'd0; if (pre_n == 32'd16) begin if (pre_hit == 32'd16 && pre_hit1 == 32'd16) begin stim_r <= 1'b0; stim2_r <= 1'b0; st <= S_GAP; cnt <= 32'd2000 + {{15'd0, lf[GAPW-1:0]}}; end else st <= S_DONE; end end
            end
            S_GAP:  if (cnt == 0) st <= S_PICK; else cnt <= cnt - 1'b1;
            S_PICK: if (npop != cpop) begin
                        tgt <= nw; exp_amt <= {{1'b0, npop, 13'd0}}; dual <= ch0 && ch1; first1 <= (ch0 && ch1) ? lf[2] : ch1; dly <= {{16'd0, lf[18:3]}}; st <= S_E1;
                    end
            S_E1: begin
                t0 <= now; to_cnt <= 32'd0;
                if (first1) stim2_r <= tgt[1]; else stim_r <= tgt[0];
                st <= dual ? S_D : S_W;
            end
            S_D: begin
                to_cnt <= to_cnt + 1'b1;
                if (dly == 0) begin if (first1) stim_r <= tgt[0]; else stim2_r <= tgt[1]; st <= S_W; end
                else dly <= dly - 1'b1;
            end
            S_W: begin
                to_cnt <= to_cnt + 1'b1;
                if (live_amt == exp_amt) begin
                    if (dual) begin {rec("dA", "dB", "d")} nd <= nd + 1'b1; end else begin {rec("sA", "sB", "s")} end
                    cnt <= 32'd30000 + {{16'd0, lf[HOLDW-1:0]}}; st <= S_HOLD;
                end else if (to_cnt >= TO) begin to_fail <= to_fail + 1'b1; cnt <= 32'd30000 + {{16'd0, lf[HOLDW-1:0]}}; st <= S_HOLD; end
            end
            S_HOLD: if (cnt == 0) begin
                        if (live_amt != exp_amt) bad <= bad + 1'b1;
                        ncyc <= ncyc + 1'b1; cnt <= 32'd2000 + {{15'd0, lf[GAPW-1:0]}}; st <= (ncyc + 1 == NCYC) ? S_DONE : S_GAP;
                    end else cnt <= cnt - 1'b1;
            default: ;
        endcase
    end
    wire done = (st == S_DONE);
    wire [7:0] res_c = (pre_hit != 32'd16 || pre_hit1 != 32'd16) ? "L" : ((to_fail == 0 && bad == 0) ? "P" : "F");
    wire pass = (pre_hit == 32'd16) && (pre_hit1 == 32'd16) && (to_fail == 0) && (bad == 0);

    // ---- print the line once the run is over, then again every REPEAT clocks
    wire [8*{LEN}-1:0] line = {{{line}}};
    reg [7:0] ci = 8'd0; reg [31:0] rep = 32'd0; reg sending = 1'b0; reg start = 1'b0; wire busy;
    board_uart_tx #(.CPB(CPB)) T (.clk(clk), .start(start), .data(line[(({LEN}-1)-ci)*8 +: 8]), .tx(UART_TX), .busy(busy));
    always @(posedge clk) begin
        start <= 1'b0;
        if (!done) begin sending <= 1'b0; ci <= 8'd0; rep <= 32'd0; end
        else if (!sending) begin if (rep >= REPEAT || rep == 0) begin sending <= 1'b1; ci <= 8'd0; rep <= 32'd1; end else rep <= rep + 1'b1; end
        else if (start) ci <= ci + 1'b1;          // the transmitter is latching line[ci] this cycle; move on to the next byte
        else if (!busy) begin
            if (ci == {LEN}) begin sending <= 1'b0; end
            else start <= 1'b1;
        end
    end
    reg [24:0] hb = 25'd0; always @(posedge clk) hb <= hb + 1'b1;
    assign LED0_N = ~hb[24]; assign LED1_N = ~(done && pass); assign LED2_N = ~(done && !pass); assign LED3_N = ~done;
    assign LED4_N = ~stim_r; assign LED5_N = ~SENS0;      // the level sent out on pin 86, and the level seen on pin 72: they should blink together
endmodule
`default_nettype wire
"""
    return v, LEN


U_TOP = "icm_parallel_reduction_tree_flex"

