def top_text(cpb, mutant="none"):
    T = r"""// board_top_saveload.v -- GENERATED by tools/board_saveload_v1.py (ledger #1098); do not hand-edit.
`default_nettype none
`timescale 1ns / 1ps
module board_top_saveload #(parameter integer CPB = @CPB@) (
    input wire BOARD_CLK, input wire UART_RX, output wire UART_TX, output wire LED0_N, output wire LED1_N, output wire LED2_N, output wire LED3_N);
wire clk = BOARD_CLK;
reg [7:0] por_cnt = 8'h00; reg [3:0] srst_cnt = 4'd0; reg boot = 1'b1;
wire rst = (por_cnt != 8'hFF) || (srst_cnt != 4'd0);
always @(posedge clk) begin if (por_cnt != 8'hFF) por_cnt <= por_cnt + 8'd1; end

reg cfg_grid = 1'b0, cfg_acc = 1'b0, load_valid = 1'b0, rel = 1'b0; reg [15:0] n_steps = 16'd0; reg [1:0] mode = 2'd1; reg [2:0] dly = 3'd4; reg [4:0] lag = 5'd0; reg [31:0] load_data = 32'h0;
wire busy, stopped, held_valid, take_o; wire [15:0] steps; wire [31:0] held, take_d;
looped_cordic_stop_wrapper_v2 core (.clk(clk), .rst(rst), .cfg_grid(cfg_grid), .cfg_acc(cfg_acc), .n_steps(n_steps), .mode(mode), .feed_delay(dly), .trig_lag(lag),
    .load_valid(load_valid), .load_data(load_data), .release_pulse(rel), .busy(busy), .stopped(stopped), .steps_done(steps), .held_word(held), .held_valid(held_valid), .take_o(take_o), .take_data(take_d));

wire rx_v; wire [7:0] rx_d; board_uart_rx #(.CPB(CPB)) urx (.clk(clk), .rx(UART_RX), .valid(rx_v), .data(rx_d));
wire tx_busy; reg tx_start = 1'b0; reg [7:0] tx_data = 8'h00;
board_uart_tx #(.CPB(CPB)) utx (.clk(clk), .start(tx_start), .data(tx_data), .tx(UART_TX), .busy(tx_busy));

reg [31:0] runclk = 32'd0; reg run_en = 1'b0; reg prev_stopped = 1'b0;
localparam [2:0] S_IDLE = 3'd0, S_COLL = 3'd1, S_REPLY = 3'd2;
reg [2:0] st = S_IDLE; reg [7:0] cmd = 8'h00; reg [2:0] nrx = 3'd0; reg [39:0] sh = 40'h0; reg [95:0] txq = 96'h0; reg [3:0] txn = 4'd0; reg [15:0] frames = 16'd0; reg pend_srst = 1'b0;
always @(posedge clk) begin
    cfg_grid <= 1'b0; cfg_acc <= 1'b0; load_valid <= 1'b0; rel <= 1'b0; tx_start <= 1'b0;
    prev_stopped <= stopped;
    if (srst_cnt != 4'd0) srst_cnt <= srst_cnt - 4'd1;     // the only driver of srst_cnt together with the soft-reset assignment below (same block)
    if (run_en && !stopped) runclk <= runclk + 32'd1;
    if (stopped && !prev_stopped) run_en <= 1'b0;
    if (rst) begin st <= S_IDLE; boot <= 1'b1; mode <= 2'd1; dly <= 3'd4; lag <= 5'd0; n_steps <= 16'd0; run_en <= 1'b0; runclk <= 32'd0; txn <= 4'd0; end
    else if (boot) begin cfg_grid <= 1'b1; boot <= 1'b0; end
    else case (st)
        S_IDLE: if (rx_v) begin
                    frames <= frames + 16'd1; cmd <= rx_d; nrx <= 3'd0; sh <= 40'h0;
                    if (rx_d == 8'h58) begin pend_srst <= 1'b1; txq <= {8'h4B, 88'h0}; txn <= 4'd1; st <= S_REPLY; end
                    else if (rx_d == 8'h47) begin rel <= 1'b1; run_en <= 1'b1; runclk <= 32'd0; txq <= {8'h4B, 88'h0}; txn <= 4'd1; st <= S_REPLY; end
                    else if (rx_d == 8'h51) begin txq <= {8'h51, 5'b0, held_valid, busy, stopped, steps, held, runclk}; txn <= 4'd12; st <= S_REPLY; end
                    else if (rx_d == 8'h43 || rx_d == 8'h4C) st <= S_COLL;
                end
        S_COLL: if (rx_v) begin
                    sh <= {sh[31:0], rx_d}; nrx <= nrx + 3'd1;
                    if (cmd == 8'h43 && nrx == 3'd4) begin mode <= sh[25:24]; n_steps <= {sh[23:16], sh[15:8]}; dly <= sh[2:0]; lag <= rx_d[4:0]; cfg_acc <= 1'b1; txq <= {8'h4B, 88'h0}; txn <= 4'd1; st <= S_REPLY; end
                    if (cmd == 8'h4C && nrx == 3'd3) begin load_data <= {sh[23:0], rx_d}@LOADXOR@; load_valid <= 1'b1; run_en <= 1'b1; runclk <= 32'd0; txq <= {8'h4B, 88'h0}; txn <= 4'd1; st <= S_REPLY; end
                end
        S_REPLY: begin
                    if (txn == 4'd0 && !tx_busy && !tx_start) begin if (pend_srst) begin srst_cnt <= 4'd8; pend_srst <= 1'b0; end st <= S_IDLE; end
                    else if (!tx_busy && !tx_start) begin tx_data <= txq[95:88]; tx_start <= 1'b1; txq <= {txq[87:0], 8'h00}; txn <= txn - 4'd1; end
                end
        default: st <= S_IDLE;
    endcase
end
reg [23:0] hb = 24'd0; always @(posedge clk) hb <= hb + 24'd1;
assign LED0_N = ~hb[23]; assign LED1_N = ~stopped; assign LED2_N = ~busy; assign LED3_N = ~(frames != 16'd0);
endmodule
"""
    T = T.replace("@CPB@", str(cpb)).replace("@LOADXOR@", " ^ 32'h1" if mutant == "wrongload" else "")
    return T


def scenario(k1, k2, model):
    """The frames and expectations of the simulated PC (and the same sequence the host script runs on the board). model[i] = value at step i+1."""
    S = []

    def C(mode, n, dly, lag): return ("C", mode, n, dly, lag)
    S.append(("S1 back pressure", [("X",), C(1, k1, 4, 0), ("L", Z0), ("WAIT", k1), ("EXP", dict(stopped=1, busy=0, held_valid=1, steps=k1, held=model[k1 - 1])),
             C(1, k2, 4, 0), ("G",), ("WAIT", k1 + k2), ("EXP", dict(stopped=1, busy=0, held_valid=1, steps=k1 + k2, held=model[k1 + k2 - 1]))]))
    S.append(("S2 freeze", [("X",), C(2, k1, 4, 0), ("L", Z0), ("WAIT", k1), ("EXP", dict(stopped=1, busy=0, held_valid=1, steps=k1, held=model[k1 - 1])),
             C(2, k2, 4, 0), ("G",), ("WAIT", k1 + k2), ("EXP", dict(stopped=1, busy=0, held_valid=1, steps=k1 + k2, held=model[k1 + k2 - 1]))]))
    S.append(("S3 freeze with the word inside the grid, then resume", [("X",), C(2, k1, 0, 12), ("L", Z0), ("WAIT", k1), ("EXP", dict(stopped=1, busy=1, held_valid=0, steps=k1)),
             C(2, k2, 0, 12), ("G",), ("WAIT", k1 + k2), ("EXP", dict(stopped=1, busy=1, held_valid=0, steps=k1 + k2)),
             C(2, 1, 4, 0), ("G",), ("WAIT", k1 + k2 + 1), ("EXP", dict(stopped=1, busy=0, held_valid=1, steps=k1 + k2 + 1, held=model[k1 + k2]))]))
    S.append(("S4 save, fresh card, load, run on", [("X",), C(3, k1, 4, 0), ("L", Z0), ("WAIT", k1), ("EXP", dict(stopped=1, busy=0, held_valid=1, steps=k1, held=model[k1 - 1])), ("SAVE",),
             ("X",), C(3, k2, 4, 0), ("LOADSAVED",), ("WAIT", k2), ("EXP", dict(stopped=1, busy=0, held_valid=1, steps=k2, held=model[k1 + k2 - 1]))]))
    return S


def sim_tb(work, files, cpb, k1, k2, model, mutant):
    out = []
    for title, frames in scenario(k1, k2, model)[:int(os.environ.get("SL_SCENARIOS", "99"))]:
        out.append("    $display(\"-- %s\");" % title)
        for f in frames:
            if f[0] == "X":
                out.append("    sendb(8'h58); getb(rb); repeat (200) @(posedge clk);")
            elif f[0] == "C":
                _, mode, n, dly, lag = f
                out.append("    sendb(8'h43); sendb(8'h%02X); sendb(8'h%02X); sendb(8'h%02X); sendb(8'h%02X); sendb(8'h%02X); getb(rb);" % (mode, n >> 8, n & 255, dly, lag))
            elif f[0] == "L":
                out.append("    sendb(8'h4C); " + " ".join("sendb(8'h%02X);" % ((f[1] >> (8 * (3 - j))) & 255) for j in range(4)) + " getb(rb); saved_valid = 0;")
            elif f[0] == "LOADSAVED":
                out.append("    sendb(8'h4C); sendb(saved[31:24]); sendb(saved[23:16]); sendb(saved[15:8]); sendb(saved[7:0]); getb(rb);")
            elif f[0] == "G":
                out.append("    sendb(8'h47); getb(rb);")
            elif f[0] == "WAIT":
                out.append("    qwait(16'd%d);" % f[1])
            elif f[0] == "SAVE":
                out.append("    saved = qheld;")
            elif f[0] == "EXP":
                e = f[1]
                cond = " && ".join(["qstopped == %d" % e["stopped"], "qbusy == %d" % e["busy"], "qvalid == %d" % e["held_valid"], "qsteps == %d" % e["steps"]] + (["qheld == 32'h%08X" % (e["held"] & 0xFFFFFFFF)] if "held" in e else []))
                out.append("    if (%s) $display(\"  ok   stopped=%%0d busy=%%0d held_valid=%%0d steps=%%0d held=%%0d run_clocks=%%0d\", qstopped, qbusy, qvalid, qsteps, $signed(qheld), qrun); "
                           "else begin bad = bad + 1; $display(\"  WRONG stopped=%%0d busy=%%0d held_valid=%%0d steps=%%0d held=%%0d (want %s)\", qstopped, qbusy, qvalid, qsteps, $signed(qheld)); end" % (cond, str(e).replace('"', "'")))
    tb = f"""`timescale 1ns/1ps
module tbh;
  reg clk = 0; reg rx = 1; wire tx, l0, l1, l2, l3;
  board_top_{NAME} #(.CPB({cpb})) dut (.BOARD_CLK(clk), .UART_RX(rx), .UART_TX(tx), .LED0_N(l0), .LED1_N(l1), .LED2_N(l2), .LED3_N(l3));
  always #5 clk = ~clk;
  integer bad = 0, tries; reg [7:0] rb; reg [87:0] v; reg qstopped, qbusy, qvalid; reg [15:0] qsteps; reg [31:0] qheld, qrun, saved; reg saved_valid;
  task sendb(input [7:0] b); integer i; begin
    rx = 0; repeat ({cpb}) @(posedge clk);
    for (i = 0; i < 8; i = i + 1) begin rx = b[i]; repeat ({cpb}) @(posedge clk); end
    rx = 1; repeat ({cpb} * 2) @(posedge clk); end endtask
  // a receiver that runs all the time (replies can start before the sender has finished its stop bits): bytes go into a queue, getb takes the next one
  reg [7:0] rq [0:255]; integer wp = 0, rp = 0;
  always @(negedge tx) begin : rcv integer i; reg [7:0] b; begin
    repeat ({cpb} + {cpb} / 2) @(posedge clk); b = 0;
    for (i = 0; i < 8; i = i + 1) begin b[i] = tx; repeat ({cpb}) @(posedge clk); end
    rq[wp % 256] = b; wp = wp + 1; end end
  task getb(output [7:0] b); begin wait (wp > rp); b = rq[rp % 256]; rp = rp + 1; end endtask
  task query; integer k; reg [7:0] t; begin sendb(8'h51); getb(t); v = 0; for (k = 0; k < 11; k = k + 1) begin getb(t); v = {{v[79:0], t}}; end
    qstopped = v[80]; qbusy = v[81]; qvalid = v[82]; qsteps = v[79:64]; qheld = v[63:32]; qrun = v[31:0]; end endtask
  task qwait(input [15:0] target); begin tries = 0; query; while (!(qstopped && qsteps == target) && tries < 400) begin tries = tries + 1; query; end end endtask
  initial begin
    repeat (400) @(posedge clk);
{chr(10).join(out)}
    if (bad == 0) $display("SAVELOAD PASS"); else $display("SAVELOAD FAIL %0d", bad);
    $finish;
  end
  initial begin #{os.environ.get('SL_TMO_NS', '200000000')}; $display("SIMTIMEOUT"); $finish; end
endmodule
"""
    open(os.path.join(work, "tbh.v"), "w").write(tb)
    c = subprocess.run(["iverilog", "-g2012", "-o", "tbh.vvp", "tbh.v"] + files, cwd=work, capture_output=True, text=True)
    if c.returncode:
        raise SystemExit("iverilog: " + c.stderr[:1500])
    return subprocess.run(["vvp", "tbh.vvp"], cwd=work, capture_output=True, text=True, timeout=6000).stdout


def build_files(work, cpb, mutant="none"):
    shutil.copy(os.path.join(ROOT, "nano", "examples", "looped_cordic_v1_open.icm-hier.json"), os.path.join(work, "open.icm-hier.json"))
    gdir = os.path.join(work, "grid")
    subprocess.run([sys.executable, os.path.join(ROOT, "tools", "project_assemble_v1.py"), "-s", "flex", "--icm", os.path.join(work, "open.icm-hier.json"), "--output", gdir, "--top", "icm_open_flex"],
                   check=True, capture_output=True)
    fz.make(gdir, "icm_open_flex")
    bz.add(gdir, "icm_open_flex")
    for f in ("looped_cordic_stop_wrapper_v2.v", "accumulator_cell_v4sa.v", "latch_cell_v4sa.v"):
        shutil.copy(os.path.join(ROOT, "sub", "verilog", f), gdir)
    open(os.path.join(work, "board_uart_tx.v"), "w").write(bt.UART_V)
    open(os.path.join(work, "board_uart_rx.v"), "w").write(bm.UART_RX_V)
    top = "board_top_" + NAME
    open(os.path.join(work, top + ".v"), "w").write(top_text(cpb, mutant))
    grid_files = sorted(os.path.join(gdir, f) for f in os.listdir(gdir) if f.endswith(".v") and f != "icm_open_flex.v")
    return top, [os.path.join(work, "board_uart_tx.v"), os.path.join(work, "board_uart_rx.v"), os.path.join(work, top + ".v")] + grid_files, gdir


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--out", default=os.path.join(ROOT, "fpga", "board_tests_saveload"))
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--freq", type=float, default=27.0)
    ap.add_argument("--no-pnr", action="store_true")
    ap.add_argument("--mutant", default="none", choices=["none", "wrongload", "nostop"], help="simulation only: break the design on purpose and confirm the simulated PC reports FAIL")
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    work = tempfile.mkdtemp(dir=out, prefix="_work")
    try:
        model = L.model(40)
        top, files, gdir = build_files(work, 8, a.mutant)
        if a.mutant == "nostop":
            raise SystemExit("mutant nostop is not defined for this kit")
        sim = sim_tb(work, files, 8, 3, 3, model, a.mutant)
        lines = [l for l in sim.splitlines() if l.startswith(("--", "  ok", "  WRONG", "SAVELOAD", "SIMTIMEOUT"))]
        print("\n".join(lines))
        verdict = next((l for l in lines if l.startswith("SAVELOAD")), "no verdict")
        if a.mutant != "none":
            caught = "FAIL" in verdict
            print("MUTANT %s -> %s" % (a.mutant, "caught" if caught else "NOT CAUGHT"))
            raise SystemExit(0 if caught else 1)
        if "PASS" not in verdict:
            raise SystemExit("did NOT pass in simulation; no bitstream written")
        top, files, gdir = build_files(work, bt.CPB, "none")
        open(os.path.join(out, NAME + ".v"), "w").write(top_text(bt.CPB))
        open(os.path.join(out, NAME + ".cst"), "w").write(bm.cst_host())
        shutil.copy(os.path.join(out, NAME + ".cst"), os.path.join(work, NAME + ".cst"))
        meta = dict(name=NAME, sim=[l for l in lines if l.startswith(("--", "  ok", "SAVELOAD"))], z0=Z0, drift=L.DRIFT, model_first=model[:8])
        if not a.no_pnr:
            pnr = m2.pnr_report(work, NAME, top, files, a.seed, a.freq, pack_to=out, meta=meta.setdefault("build", {}))
            print("place and route: Fmax %.1f MHz (target %s); used: %s" % (pnr["fmax_mhz"], a.freq, {k: "%d/%d" % (v["used"], v["available"]) for k, v in pnr["utilization"].items()}))
        json.dump(meta, open(os.path.join(out, NAME + ".json"), "w"), indent=1)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
