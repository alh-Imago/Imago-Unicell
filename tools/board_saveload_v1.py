#!/usr/bin/env python3
"""tools/board_saveload_v1.py -- ledger #1098: the board kit for the save / load / retarget proof on the Tang Nano 20K (flex family).

On the card: the open-ring looped CORDIC (assembled from nano/examples/looped_cordic_v1_open.icm-hier.json by the flex assembler; every cell's freeze_in joined to one freeze line by
tools/flex_freeze_net_v1.py; a `busy_any` port added by tools/flex_busy_port_v1.py), the stop wrapper sub/verilog/looped_cordic_stop_wrapper_v2.v (loop-closing register that can be loaded,
step counter = accumulator cell, stop latch = latch cell, back pressure and/or freeze), and a serial front end. The host never stops the card by timing: the card stops ITSELF at a programmed
step count and raises `stopped`; the host reads it afterwards at its own speed (a stopped card with busy=0 holds its whole state in the loop-closing register).

Serial protocol (115200 8N1), the host is the PC; the bitstream never changes:
  'X'                         soft reset of the whole design (counter, latch, grid, closing register) -> 'K'
  'C' mode(1) N(2) dly(1) lag(1)  configure the self-stop: mode bit0 = back pressure, bit1 = freeze; N = results to count before stopping (big-endian); dly = clocks a result waits in the closing
                              register before it is fed back (0..7); lag = clocks the step pulse is delayed before the counter (0..31; moves where a freeze lands). Re-arms the counter -> 'K'
  'L' word(4)                 load a word into the loop-closing register (this is the "load state" and the way the first value goes in) -> 'K'
  'G'                         release the stop latch (go) -> 'K'
  'Q'                         query -> 'Q' flags(1) steps(2) held_word(4) run_clocks(4);  flags: bit0 stopped, bit1 busy (a grid cell still holds a word), bit2 held_valid (the closing register holds a word)
                              steps = results taken since the last 'X'; run_clocks = clocks from the last 'L' or 'G' to the next stop (counted on the card)

  python3 tools/board_saveload_v1.py [--out DIR] [--seed N] [--freq MHZ] [--no-pnr] [--mutant none|wrongload|nostop]
"""
