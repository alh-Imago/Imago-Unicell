#!/usr/bin/env python3
"""tools/make_carrier_subset_v1.py -- ledger #1086: a CLONE of the VIX carrier (fpga/verilog/unicell_vix_carrier_v1.v) that physically contains only the cores you name.

Alan: the full carrier sat at about 80% of the Tang Nano 20K, so for the mutability test give it only the maths cores. The carrier never changes (proven file, untouched): this script
copies it, deletes the instance of every core NOT in --keep and ties that core's output wires to 0, so synthesis removes it. The select decode, the output mux, the config latch and the
shared add-on chain (mask, fine shift, lane shift, invert) are untouched, so a core_select value for a removed core selects nothing (outputs 0).

  python3 tools/make_carrier_subset_v1.py --keep adder,accum,mul --out fpga/verilog/unicell_vix_carrier_v1m.v
"""
import argparse, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "fpga", "verilog", "unicell_vix_carrier_v1.v")
CORES = ["nano", "adder", "ram", "compare", "branch", "accum", "latch", "seq", "mul", "priority", "corner", "cross", "merge", "div", "command"]


def make(keep, src=SRC):
    keep = set(keep)
    bad = keep - set(CORES)
    if bad:
        raise SystemExit("unknown core(s): " + ", ".join(sorted(bad)) + "; choose from " + ", ".join(CORES))
    t = open(src).read()
    removed = []
    for c in CORES:
        if c in keep:
            continue
        pat = re.compile(r"\n    \w+_shell_v1c\s*(#\([^;]*?\))?\s*CORE_%s\s*\([^;]*?\n    \);\n" % c.upper(), re.S)
        m = pat.search(t)
        if not m:
            raise SystemExit("instance CORE_%s not found" % c.upper())
        # every wire declared as <core>_xxx (declaration lines are "wire [..] a, b, c;")
        names = []
        for dm in re.finditer(r"^\s*wire\s*(?:\[[^\]]*\]\s*)?([^;]*);", t, re.M):
            for n in dm.group(1).split(","):
                n = n.strip()
                if re.match(r"%s_\w+$" % c, n):
                    names.append(n)
        # the priority core's two unused wires are declared with other names: take any "<core>_..._unused"
        assigns = "\n    // %s removed (ledger #1086): its outputs are tied to 0\n" % c + "".join("    assign %s = 0;\n" % n for n in sorted(set(names)))
        t = t[:m.start()] + assigns + t[m.end():]
        removed.append(c)
    t = t.replace("module unicell_vix_carrier_v1 #(", "// GENERATED by tools/make_carrier_subset_v1.py (ledger #1086) from unicell_vix_carrier_v1.v; cores kept: %s\nmodule unicell_vix_carrier_v1m #(" % ", ".join(sorted(keep)), 1)
    return t, removed


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--keep", required=True, help="comma list from: " + ",".join(CORES))
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    t, rem = make([x for x in a.keep.split(",") if x])
    open(a.out, "w").write(t)
    print("wrote", a.out, "removed:", ", ".join(rem))


if __name__ == "__main__":
    main()
